/// The file vitruvian-tool.json at the top of a tool's folder. It says what the
/// tool is, which of the app's services it calls, what it adds, and which
/// program to start. A field this schema does not name is ignored, which is how
/// a later version adds one. Two rules are not written here because JSON Schema
/// cannot say them: no two commands, no two panels and no two preferences share
/// an id; and the whole file is at most 65,536 bytes.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Manifest {
    /// The tool's identity, in reverse-DNS form, for example com.acme.deploys.
    /// Letters, digits, hyphens and underscores in parts joined by single dots.
    /// It must have a dot: an id with none belongs to a feature built into the
    /// app. At most 128 characters. It never changes between versions of a
    /// tool.
    pub id: String,
    /// What the tool is called, shown as written.
    pub name: LocalizedText,
    /// One sentence on what the tool does, shown as written.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<LocalizedText>,
    /// The tool's own version, as its author writes it.
    pub version: String,
    /// The protocol version the tool speaks. Version 2 adds panels, what a tool
    /// draws, and changes nothing of version 1. An app that speaks only version
    /// 1 refuses a manifest that says 2. One of: 1, 2.
    pub protocol: String,
    /// Who made the tool. Shown beside its name. The app does not check it.
    pub publisher: String,
    /// The licence the tool is offered under, for example an SPDX identifier.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub license: Option<String>,
    /// An SF Symbol name. A name this Mac does not have draws as a plain puzzle
    /// piece.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub icon: Option<String>,
    /// The app services the tool calls. The app refuses a call to a service
    /// that is not listed. This is not a list of what the tool is allowed to
    /// do: a tool is a separate program and can do anything the app can. One
    /// of: notify, open, clipboard.read, clipboard.write, keystrokes,
    /// processes, storage.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub uses: Option<Vec<String>>,
    /// What the tool adds to the app.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub contributes: Option<Contributes>,
    /// The settings the tool keeps through the app. At most 16.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub preferences: Option<Vec<Preference>>,
    /// When the app starts the tool. onCommand: the first time one of its
    /// commands runs. onLaunch: with the app. Left out, it is onCommand. One
    /// of: onCommand, onLaunch.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub activation: Option<Vec<String>>,
    /// How the tool runs.
    pub runtime: Runtime,
}

/// What the tool adds to the app: commands, and in protocol 2 panels.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Contributes {
    /// The tool's commands. At most 32.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub commands: Option<Vec<Command>>,
    /// What the tool draws, and where. At most 8; at most one in the island and
    /// one in Settings. Protocol 2 only.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub panels: Option<Vec<Panel>>,
}

/// One thing the tool can be asked to do.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Command {
    /// The command's name within the tool. The same characters as a tool id; a
    /// dot is not needed. The app knows the command as <tool id>/<this id>.
    pub id: String,
    /// What the command is called in a list.
    pub title: LocalizedText,
    /// An SF Symbol name. Left out, the tool's icon is used.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub icon: Option<String>,
    /// Where the command is offered: the command bar, the radial menu, the
    /// Quick panel, and as a shortcut the person records. One of: commandBar,
    /// radial, quickPanel, shortcut.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub surfaces: Option<Vec<String>>,
}

/// One place the tool draws in. The app opens it with ui/open and the tool
/// answers with blocks to draw; or, for a web panel, the app shows the page at
/// entry.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Panel {
    /// The panel's name within the tool. The same characters as a command id.
    pub id: String,
    /// What the panel is called: the island page's title, the window's title.
    pub title: LocalizedText,
    /// Where it is shown. island: a page in the island's Tools area. settings:
    /// a part of the tool's detail in Settings. window: a window the app owns,
    /// opened when the person asks. One of: island, settings, window.
    pub placement: String,
    /// An SF Symbol name. Left out, the tool's icon is used.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub icon: Option<String>,
    /// What draws it. blocks: the app, from blocks the tool sends. web: a web
    /// page from the tool's folder. Left out, it is blocks. One of: blocks,
    /// web.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub kind: Option<String>,
    /// A web panel's page, as a path inside the tool's folder, with / between
    /// its parts. No part is empty, . or .., so the path cannot leave the
    /// folder. A blocks panel ignores it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub entry: Option<String>,
}

/// One setting. The tool reads and writes it with storage/get and storage/set.
/// The person sees and changes it in the tool's detail in Settings when it has
/// a title, and the tool is then sent preferences/changed.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Preference {
    /// The setting's name within the tool. The same characters as a command id.
    pub id: String,
    /// What the setting is called where the person changes it, shown as
    /// written. At most 60 characters in each language, with no line break and
    /// no other control character. Left out, the app does not show the setting:
    /// the tool alone reads and writes it. An app older than this field ignores
    /// it, and shows no setting.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub title: Option<LocalizedText>,
    /// What kind of value it holds. One of: string, boolean, integer, number.
    pub r#type: String,
    /// The value before anything is saved. It is of the type named.
    pub default: Value,
}

/// The program the app starts.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Runtime {
    /// external: a separate program. The only kind a manifest file may name.
    pub kind: String,
    /// The program, as a path inside the tool's folder, with / between its
    /// parts. No part is empty, . or .., so the path cannot leave the folder.
    pub exec: String,
}

/// Reads `value` as the protocol type named `name` and writes it back,
/// or None for a name that is no type here. The kit's tests hold the
/// types to the protocol's examples with it.
#[doc(hidden)]
pub fn round_trip(name: &str, value: &Value) -> Option<serde_json::Result<Value>> {
    fn again<T: serde::de::DeserializeOwned + Serialize>(
        value: &Value,
    ) -> serde_json::Result<Value> {
        serde_json::to_value(serde_json::from_value::<T>(value.clone())?)
    }
    Some(match name {
        "Error" => again::<Error>(value),
        "RefusalData" => again::<RefusalData>(value),
        "Empty" => again::<Empty>(value),
        "InitializeParams" => again::<InitializeParams>(value),
        "InitializeResult" => again::<InitializeResult>(value),
        "CommandRunParams" => again::<CommandRunParams>(value),
        "PreferencesChangedParams" => again::<PreferencesChangedParams>(value),
        "LanguageChangedParams" => again::<LanguageChangedParams>(value),
        "CommandsStateParams" => again::<CommandsStateParams>(value),
        "NotifyHudParams" => again::<NotifyHudParams>(value),
        "OpenUrlParams" => again::<OpenUrlParams>(value),
        "OpenUrlResult" => again::<OpenUrlResult>(value),
        "ClipboardReadTextResult" => again::<ClipboardReadTextResult>(value),
        "ClipboardWriteTextParams" => again::<ClipboardWriteTextParams>(value),
        "ClipboardWriteTextResult" => again::<ClipboardWriteTextResult>(value),
        "KeystrokesPasteParams" => again::<KeystrokesPasteParams>(value),
        "KeystrokesPressMenuItemParams" => again::<KeystrokesPressMenuItemParams>(value),
        "KeyEquivalent" => again::<KeyEquivalent>(value),
        "KeystrokesPressMenuItemResult" => again::<KeystrokesPressMenuItemResult>(value),
        "ProcessesTerminateParams" => again::<ProcessesTerminateParams>(value),
        "StorageGetParams" => again::<StorageGetParams>(value),
        "StorageGetResult" => again::<StorageGetResult>(value),
        "StorageSetParams" => again::<StorageSetParams>(value),
        "LogParams" => again::<LogParams>(value),
        "UiOpenParams" => again::<UiOpenParams>(value),
        "UiOpenResult" => again::<UiOpenResult>(value),
        "UiEventParams" => again::<UiEventParams>(value),
        "UiEventResult" => again::<UiEventResult>(value),
        "UiCloseParams" => again::<UiCloseParams>(value),
        "UiRenderParams" => again::<UiRenderParams>(value),
        "UiBadgeParams" => again::<UiBadgeParams>(value),
        "UiTree" => again::<UiTree>(value),
        "UiBlock" => again::<UiBlock>(value),
        "LocalizedText" => again::<LocalizedText>(value),
        "UiText" => again::<UiText>(value),
        "TextBlock" => again::<TextBlock>(value),
        "HeadingBlock" => again::<HeadingBlock>(value),
        "RowBlock" => again::<RowBlock>(value),
        "ButtonBlock" => again::<ButtonBlock>(value),
        "ToggleBlock" => again::<ToggleBlock>(value),
        "FieldBlock" => again::<FieldBlock>(value),
        "UiListRow" => again::<UiListRow>(value),
        "ListBlock" => again::<ListBlock>(value),
        "ProgressBlock" => again::<ProgressBlock>(value),
        "ImageBlock" => again::<ImageBlock>(value),
        "DividerBlock" => again::<DividerBlock>(value),
        "LinkBlock" => again::<LinkBlock>(value),
        "SpacerBlock" => again::<SpacerBlock>(value),
        "Manifest" => again::<Manifest>(value),
        "Contributes" => again::<Contributes>(value),
        "Command" => again::<Command>(value),
        "Panel" => again::<Panel>(value),
        "Preference" => again::<Preference>(value),
        "Runtime" => again::<Runtime>(value),
        _ => return None,
    })
}
