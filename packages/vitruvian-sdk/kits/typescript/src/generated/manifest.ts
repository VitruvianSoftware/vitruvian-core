/** The file vitruvian-tool.json at the top of a tool's folder. It says what the tool is, which of the app's services it calls, what it adds, and which program to start. A field this schema does not name is ignored, which is how a later version adds one. Four rules are not written here because JSON Schema cannot say them: no two commands, no two panels and no two preferences share an id; the whole file is at most 65,536 bytes; no two options of one preference share a value; and a preference with options has a default that is one of them. */
export interface ToolManifest {
  /** The tool's identity, in reverse-DNS form, for example com.acme.deploys. Letters, digits, hyphens and underscores in parts joined by single dots. It must have a dot: an id with none belongs to a feature built into the app. At most 128 characters. It never changes between versions of a tool. */
  id: string;
  /** What the tool is called, shown as written. */
  name: LocalizedText;
  /** One sentence on what the tool does, shown as written. */
  description?: LocalizedText;
  /** The tool's own version, as its author writes it. */
  version: string;
  /** The protocol version the tool speaks. Version 2 adds panels, what a tool draws, and changes nothing of version 1. An app that speaks only version 1 refuses a manifest that says 2. */
  protocol: ProtocolVersion;
  /** Who made the tool. Shown beside its name. The app does not check it. */
  publisher: string;
  /** The licence the tool is offered under, for example an SPDX identifier. */
  license?: string;
  /** An SF Symbol name. A name this Mac does not have draws as a plain puzzle piece. */
  icon?: string;
  /** The app services the tool calls. The app refuses a call to a service that is not listed. This is not a list of what the tool is allowed to do: a tool is a separate program and can do anything the app can. */
  uses?: Service[];
  /** What the tool adds to the app. */
  contributes?: Contributes;
  /** The settings the tool keeps through the app. At most 16. */
  preferences?: Preference[];
  /** When the app starts the tool. onCommand: the first time one of its commands runs. onLaunch: with the app. Left out, it is onCommand. */
  activation?: Activation[];
  /** How the tool runs. */
  runtime: Runtime;
}

