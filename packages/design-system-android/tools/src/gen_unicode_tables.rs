//! Prints `src/unicode_tables.rs`: the character classes Python 3.12's `str`
//! methods (`isprintable`, `isspace`, `isdecimal`, `capitalize`) use on
//! Unicode 15.0.0.

use gen_tokens::unicode_tables::{CASED, CASE_IGNORABLE, DECIMAL, PRINTABLE, SPACE, TITLE};

fn emit_ranges(out: &mut String, name: &str, doc: &str, pairs: &[(u32, u32)]) {
    out.push_str(&format!("/// {doc}\n"));
    out.push_str(&format!("pub static {name}: &[(u32, u32)] = &[\n"));
    for &(lo, hi) in pairs {
        out.push_str(&format!("    (0x{lo:X}, 0x{hi:X}),\n"));
    }
    out.push_str("];\n\n");
}

