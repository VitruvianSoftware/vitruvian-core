"""Writes src/unicode_tables.rs: the character data gen_tokens.py gets from
Python, so the Rust port answers the same way.

    python3 packages/design-system-android/tools/gen_unicode_tables.py \
        > packages/design-system-android/tools/src/unicode_tables.rs

Run it with the Python gen_tokens.py runs on under Bazel (3.12).
gen_tokens_rs_parity_test regenerates the file and fails when it differs, so
a Python whose Unicode data moved shows up as a failing test, not as a quiet
disagreement.

What it covers, and where gen_tokens.py reaches it:
  * PRINTABLE - str.isprintable(), which decides what repr() escapes
    (KeyError messages, str() of a list in an easing curve);
  * SPACE and DECIMAL - what int() skips and reads as digits (the spacing,
    hit and duration keys are sorted with key=int);
  * CASED and CASE_IGNORABLE - the context str.lower() reads to turn a
    capital sigma into a final one, inside str.capitalize() (font sizes);
  * TITLE - str.capitalize()'s first character, where title case is not
    upper case.
Upper and lower case themselves come from Rust's char methods, which carry
the same full mappings; the parity test sweeps every code point that has one.
"""

import sys
import unicodedata

HERE_LICENSE = open(__file__, encoding="utf-8").read().split('"""', 1)[0]
SIGMA = "Σ"


def ranges(test):
    out, start = [], None
    for c in range(0x110000):
        if test(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, pairs, what):
    # One pair a line: the layout rustfmt gives it, so formatting the
    # repository leaves the file as generated.
    lines = [f"/// {what}", f"pub static {name}: &[(u32, u32)] = &["]
    lines += [f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in pairs]
    lines.append("];")
    return "\n".join(lines)


def cased(c):
    ch = chr(c)
    return ch.islower() or ch.isupper() or unicodedata.category(ch) == "Lt"


def case_ignorable(c):
    # Read off str.lower() itself rather than restated from the standard.
    # A sigma after a cased letter is final when nothing cased follows it,
    # skipping case-ignorable characters on the way. So with X at the end,
    # sigma is final iff X is ignorable or not cased; with a cased letter
    # after X, it is final iff X is neither ignorable nor cased.
    ch = chr(c)
    if cased(c):
        return ("A" + SIGMA + ch).lower()[1] == "ς"
    return ("A" + SIGMA + ch + "A").lower()[1] == "σ"


def title_table():
    lines = [
        "/// str.capitalize()'s first character where its title case is not",
        "/// its upper case: (code point, the characters it becomes).",
        "pub static TITLE: &[(u32, &[u32])] = &[",
    ]
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        ch = chr(c)
        if ch.capitalize() != ch.upper():
            mapped = ", ".join(f"0x{ord(m):X}" for m in ch.capitalize())
            lines.append(f"    (0x{c:X}, &[{mapped}]),")
    lines.append("];")
    return "\n".join(lines)


def render():
    decimal = ranges(lambda c: chr(c).isdecimal())
    # int() reads a digit as its distance from the start of its run of ten.
    for lo, hi in decimal:
        for c in range(lo, hi + 1):
            if unicodedata.decimal(chr(c)) != (c - lo) % 10:
                raise SystemExit(f"U+{c:04X}: decimal digits are not in runs of ten")
    parts = [
        HERE_LICENSE.replace("# ", "// ").replace("#\n", "//\n").rstrip(),
        "",
        "// GENERATED by packages/design-system-android/tools/gen_unicode_tables.py",
        f"// from Python {sys.version_info.major}.{sys.version_info.minor}, Unicode "
        f"{unicodedata.unidata_version}. Do not edit by hand.",
        "",
        table(
            "PRINTABLE",
            ranges(lambda c: chr(c).isprintable()),
            "str.isprintable(), which decides what repr() escapes.",
        ),
        "",
        table("SPACE", ranges(lambda c: chr(c).isspace()), "str.isspace()."),
        "",
        table("DECIMAL", decimal, "str.isdecimal(), in runs counting from 0."),
        "",
        table("CASED", ranges(cased), "Characters with the Cased property."),
        "",
        table(
            "CASE_IGNORABLE",
            ranges(case_ignorable),
            "Characters with the Case_Ignorable property.",
        ),
        "",
        title_table(),
        "",
    ]
    return "\n".join(parts)


if __name__ == "__main__":
    sys.stdout.write(render())
