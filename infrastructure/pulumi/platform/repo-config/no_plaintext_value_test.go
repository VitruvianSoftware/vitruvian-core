package main

import (
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

// Every secret this program writes uses `Value`. The provider deprecated
// `PlaintextValue`, warns on each apply, and will drop it. Scans every
// non-test Go file under this module, internal/ included.
func TestNoSecretUsesDeprecatedPlaintextValue(t *testing.T) {
	field := "Plaintext" + "Value:" // split so this file does not match itself
	var hits []string
	err := filepath.WalkDir(".", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for i, line := range strings.Split(string(src), "\n") {
			if strings.Contains(line, field) {
				hits = append(hits, path+":"+strconv.Itoa(i+1))
			}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(hits) > 0 {
		t.Fatalf("secrets set through the deprecated %s field; use Value: instead:\n%s", field, strings.Join(hits, "\n"))
	}
}
