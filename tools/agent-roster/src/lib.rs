/// Trim `.agents/roster/team-notes.md` and ensure it stays within `parseTeam`'s 2000-character limit.
pub fn validate_team_notes(raw: &str) -> Result<Option<String>, String> {
    let normalized = raw.replace("\r\n", "\n");
    let trimmed = normalized.trim();
    let len = trimmed.encode_utf16().count();
    if len > MAX_TEAM_NOTES {
        return Err(format!(
            "team-notes.md: trimmed notes is {len} characters (rule: team notes must be <= {MAX_TEAM_NOTES} characters)"
        ));
    }
    if trimmed.is_empty() {
        Ok(None)
    } else {
        Ok(Some(trimmed.to_string()))
    }
}

fn validate_tier_rows(
    tier_rows: &[TierRow],
    errors: &mut Vec<String>,
) -> BTreeMap<String, BTreeMap<String, HarnessModel>> {
    let mut tier_map: BTreeMap<String, BTreeMap<String, HarnessModel>> = BTreeMap::new();

    for row in tier_rows {
        if row.tier.trim().is_empty() {
            errors
                .push("tiers.tsv: empty tier name (rule: tier name must be non-empty)".to_string());
        }
        if row.effort.eq_ignore_ascii_case("low") {
            errors.push(format!(
                "tier '{}' ({}): effort '{}' is forbidden (rule: never low effort)",
                row.tier, row.harness, row.effort
            ));
        }

        match row.harness.as_str() {
            "antigravity" => {
                if !matches!(row.model.as_str(), "inherit" | "flash" | "pro") {
                    errors.push(format!(
                        "tier '{}' (antigravity): invalid model '{}' (rule: antigravity model must be in {{inherit, flash, pro}})",
                        row.tier, row.model
                    ));
                }
                if row.effort != "-" {
                    errors.push(format!(
                        "tier '{}' (antigravity): invalid effort '{}' (rule: antigravity effort must be \"-\")",
                        row.tier, row.effort
                    ));
                }
            }
            "claude-code" => {
                if !is_valid_claude_code_model(&row.model) {
                    errors.push(format!(
                        "tier '{}' (claude-code): invalid model '{}' (rule: claude-code model must be in {{inherit, opus, sonnet, haiku, fable}} or start with \"claude-\")",
                        row.tier, row.model
                    ));
                }
                if has_forbidden_model_substring(&row.model) {
                    errors.push(format!(
                        "tier '{}' (claude-code): invalid model '{}' (rule: never a low, lite or flash-lo model)",
                        row.tier, row.model
                    ));
                }
                if !is_valid_effort(&row.effort) {
                    errors.push(format!(
                        "tier '{}' (claude-code): invalid effort '{}' (rule: claude-code effort must be in {{-, medium, high, xhigh, max}})",
                        row.tier, row.effort
                    ));
                }
            }
            "opencode" => {
                if !is_valid_opencode_model(&row.model) {
                    errors.push(format!(
                        "tier '{}' (opencode): invalid model '{}' (rule: opencode model must match provider/model ^[a-z0-9-]+/[A-Za-z0-9._-]+(#[a-z]+)?$)",
                        row.tier, row.model
                    ));
                }
                if has_forbidden_model_substring(&row.model) {
                    errors.push(format!(
                        "tier '{}' (opencode): invalid model '{}' (rule: never a low, lite or flash-lo model)",
                        row.tier, row.model
                    ));
                }
                if !is_valid_effort(&row.effort) {
                    errors.push(format!(
                        "tier '{}' (opencode): invalid effort '{}' (rule: opencode effort must be in {{-, medium, high, xhigh, max}})",
                        row.tier, row.effort
                    ));
                }
            }
            "gemini" => {
                if !is_valid_gemini_model(&row.model) {
                    errors.push(format!(
                        "tier '{}' (gemini): invalid model '{}' (rule: gemini model must be an agy model id starting with \"gemini-\", never a low, lite or flash-lo variant)",
                        row.tier, row.model
                    ));
                }
                if row.effort != "-" {
                    errors.push(format!(
                        "tier '{}' (gemini): invalid effort '{}' (rule: gemini effort must be \"-\"; the model id carries it)",
                        row.tier, row.effort
                    ));
                }
            }
            other => {
                errors.push(format!(
                    "tier '{}': unknown harness '{}' (rule: harness must be claude-code, antigravity, opencode, or gemini)",
                    row.tier, other
                ));
            }
        }

        let per_harness = tier_map.entry(row.tier.clone()).or_default();
        if per_harness.contains_key(&row.harness) {
            errors.push(format!(
                "tier '{}' ({}): duplicate row (rule: tier and harness pair must be unique)",
                row.tier, row.harness
            ));
        } else {
            per_harness.insert(
                row.harness.clone(),
                HarnessModel {
                    model: row.model.clone(),
                    effort: row.effort.clone(),
                },
            );
        }
    }

    tier_map
}

fn validate_agent_rows(
    tier_map: &BTreeMap<String, BTreeMap<String, HarnessModel>>,
    agent_rows: &[AgentRow],
    prompts: &BTreeMap<String, String>,
    errors: &mut Vec<String>,
) {
    let mut seen_agents = BTreeSet::new();
    let mut seen_roles: BTreeMap<String, String> = BTreeMap::new();
    let allowed_roles = ROLES.join(", ");
    for agent in agent_rows {
        if !is_valid_agent_name(&agent.name) {
            errors.push(format!(
                "agent '{}': invalid name (rule: agent name must match ^[a-z][a-z0-9-]*$)",
                agent.name
            ));
        }
        if !seen_agents.insert(agent.name.clone()) {
            errors.push(format!(
                "agent '{}': duplicate name (rule: agent name must be unique)",
                agent.name
            ));
        }

        if agent.role.trim().is_empty() {
            errors.push(format!(
                "agent '{}': missing role (rule: role must be one of {allowed_roles})",
                agent.name
            ));
        } else if !is_valid_role(&agent.role) {
            errors.push(format!(
                "agent '{}': unknown role '{}' (rule: role must be one of {allowed_roles})",
                agent.name, agent.role
            ));
        } else if let Some(prev) = seen_roles.insert(agent.role.clone(), agent.name.clone()) {
            errors.push(format!(
                "agent '{}': duplicate role '{}' already assigned to '{}' (rule: role must be unique)",
                agent.name, agent.role, prev
            ));
        }

        let missing_harnesses: Vec<&str> = REQUIRED_HARNESSES
            .iter()
            .copied()
            .filter(|h| {
                tier_map
                    .get(&agent.tier)
                    .map(|m| !m.contains_key(*h))
                    .unwrap_or(true)
            })
            .collect();
        if !missing_harnesses.is_empty() {
            errors.push(format!(
                "agent '{}': tier '{}' missing for harness(es) {} (rule: tier must exist for all 3 harnesses)",
                agent.name,
                agent.tier,
                missing_harnesses.join(", ")
            ));
        }

        match prompts.get(&agent.name) {
            None => {
                errors.push(format!(
                    "agent '{}': missing prompt file prompts/{}.md (rule: prompts/<name>.md must exist and be non-empty)",
                    agent.name, agent.name
                ));
            }
            Some(body) if body.trim().is_empty() => {
                errors.push(format!(
                    "agent '{}': empty prompt file prompts/{}.md (rule: prompts/<name>.md must exist and be non-empty)",
                    agent.name, agent.name
                ));
            }
            Some(_) => {}
        }

        validate_description(&agent.name, &agent.description, errors);
    }
}

fn validate_generic_role_rows(
    tier_map: &BTreeMap<String, BTreeMap<String, HarnessModel>>,
    role_rows: &[RoleRow],
    generic_prompts: &BTreeMap<String, String>,
    errors: &mut Vec<String>,
) {
    let mut seen_roles = BTreeSet::new();
    let allowed_roles = ROLES.join(", ");
    for row in role_rows {
        if row.role.trim().is_empty() {
            errors.push(format!(
                "generic/roles.tsv: missing role (rule: role must be one of {allowed_roles})"
            ));
        } else if !is_valid_role(&row.role) {
            errors.push(format!(
                "generic role '{}': unknown role (rule: role must be one of {allowed_roles})",
                row.role
            ));
        } else if !seen_roles.insert(row.role.clone()) {
            errors.push(format!(
                "generic role '{}': duplicate role (rule: role must be unique in generic/roles.tsv)",
                row.role
            ));
        }

        let missing_harnesses: Vec<&str> = REQUIRED_HARNESSES
            .iter()
            .copied()
            .filter(|h| {
                tier_map
                    .get(&row.tier)
                    .map(|m| !m.contains_key(*h))
                    .unwrap_or(true)
            })
            .collect();
        if !missing_harnesses.is_empty() {
            errors.push(format!(
                "generic role '{}': tier '{}' missing for harness(es) {} (rule: tier must exist for all 3 harnesses)",
                row.role,
                row.tier,
                missing_harnesses.join(", ")
            ));
        }

        match generic_prompts.get(&row.role) {
            None => {
                errors.push(format!(
                    "generic role '{}': missing prompt file generic/prompts/{}.md (rule: generic/prompts/<role>.md must exist and be non-empty)",
                    row.role, row.role
                ));
            }
            Some(body) if body.trim().is_empty() => {
                errors.push(format!(
                    "generic role '{}': empty prompt file generic/prompts/{}.md (rule: generic/prompts/<role>.md must exist and be non-empty)",
                    row.role, row.role
                ));
            }
            Some(_) => {}
        }

        validate_description(
            &format!("generic role '{}'", row.role),
            &row.description,
            errors,
        );
    }
}

fn validate_generic_tier_rows(
    rows: &[TierRow],
    tier_map: &BTreeMap<String, BTreeMap<String, HarnessModel>>,
    role_rows: &[RoleRow],
    errors: &mut Vec<String>,
) -> BTreeMap<String, NativeTierSpec> {
    let mut per_tier: BTreeMap<String, BTreeMap<String, HarnessModel>> = BTreeMap::new();

    for row in rows {
        if row.tier.trim().is_empty() {
            errors.push(
                "generic/tiers.tsv: empty tier name (rule: tier name must be non-empty)"
                    .to_string(),
            );
        } else if row.tier == "lead" {
            errors.push(
                "generic/tiers.tsv: tier 'lead' is not allowed (rule: generic/tiers.tsv defines native defaults for non-lead tiers only)"
                    .to_string(),
            );
        } else if !tier_map.is_empty() && !tier_map.contains_key(&row.tier) {
            errors.push(format!(
                "generic/tiers.tsv: unknown tier '{}' (rule: tier must exist in tiers.tsv)",
                row.tier
            ));
        }

        if row.effort.eq_ignore_ascii_case("low") {
            errors.push(format!(
                "generic/tiers.tsv: tier '{}' ({}): effort '{}' is forbidden (rule: never low effort)",
                row.tier, row.harness, row.effort
            ));
        }
        if has_forbidden_model_substring(&row.model) {
            errors.push(format!(
                "generic/tiers.tsv: tier '{}' ({}): invalid model '{}' (rule: never a low, lite or flash-lo model)",
                row.tier, row.harness, row.model
            ));
        }

        match row.harness.as_str() {
            "claude-code" => {
                if !is_valid_claude_code_model(&row.model) {
                    errors.push(format!(
                        "generic/tiers.tsv: tier '{}' (claude-code): invalid model '{}' (rule: claude-code model must be in {{inherit, opus, sonnet, haiku, fable}} or start with \"claude-\")",
                        row.tier, row.model
                    ));
                }
                if !is_valid_effort(&row.effort) {
                    errors.push(format!(
                        "generic/tiers.tsv: tier '{}' (claude-code): invalid effort '{}' (rule: claude-code effort must be in {{-, medium, high, xhigh, max}})",
                        row.tier, row.effort
                    ));
                }
            }
            "opencode" => {
                if row.model != "-" && !is_valid_opencode_model(&row.model) {
                    errors.push(format!(
                        "generic/tiers.tsv: tier '{}' (opencode): invalid model '{}' (rule: opencode model must be \"-\" or match provider/model ^[a-z0-9-]+/[A-Za-z0-9._-]+(#[a-z]+)?$)",
                        row.tier, row.model
                    ));
                }
                if !is_valid_effort(&row.effort) {
                    errors.push(format!(
                        "generic/tiers.tsv: tier '{}' (opencode): invalid effort '{}' (rule: opencode effort must be in {{-, medium, high, xhigh, max}})",
                        row.tier, row.effort
                    ));
                }
            }
            other => {
                errors.push(format!(
                    "generic/tiers.tsv: tier '{}': unknown harness '{}' (rule: harness must be claude-code or opencode)",
                    row.tier, other
                ));
            }
        }

        let by_harness = per_tier.entry(row.tier.clone()).or_default();
        if by_harness.contains_key(&row.harness) {
            errors.push(format!(
                "generic/tiers.tsv: tier '{}' ({}): duplicate row (rule: tier and harness pair must be unique)",
                row.tier, row.harness
            ));
        } else {
            by_harness.insert(
                row.harness.clone(),
                HarnessModel {
                    model: row.model.clone(),
                    effort: row.effort.clone(),
                },
            );
        }
    }

    let mut out = BTreeMap::new();
    for (tier_name, mut map) in per_tier {
        for h in ["claude-code", "opencode"] {
            if !map.contains_key(h) {
                errors.push(format!(
                    "generic/tiers.tsv: tier '{tier_name}' missing harness '{h}' (rule: each tier in generic/tiers.tsv must define both claude-code and opencode)"
                ));
            }
        }
        if let (Some(claude_code), Some(opencode)) =
            (map.remove("claude-code"), map.remove("opencode"))
        {
            out.insert(
                tier_name,
                NativeTierSpec {
                    claude_code,
                    opencode,
                },
            );
        }
    }

    let required_driver_tiers: BTreeSet<&str> = role_rows
        .iter()
        .filter(|r| {
            r.tier != "lead"
                && tier_map
                    .get(&r.tier)
                    .is_some_and(|m| m.contains_key("gemini"))
        })
        .map(|r| r.tier.as_str())
        .collect();
    for tier in required_driver_tiers {
        if !out.contains_key(tier) {
            errors.push(format!(
                "generic/tiers.tsv: missing native defaults for driver tier '{tier}' (rule: every non-lead tier with a gemini row used by generic/roles.tsv must be defined in generic/tiers.tsv)"
            ));
        }
    }

    out
}

fn build_tiers(
    tier_map: BTreeMap<String, BTreeMap<String, HarnessModel>>,
) -> BTreeMap<String, TierSpec> {
    let mut tiers = BTreeMap::new();
    for (tier_name, mut map) in tier_map {
        if let (Some(claude_code), Some(antigravity), Some(opencode)) = (
            map.remove("claude-code"),
            map.remove("antigravity"),
            map.remove("opencode"),
        ) {
            let gemini = map.remove("gemini").map(|hm| hm.model);
            tiers.insert(
                tier_name,
                TierSpec {
                    claude_code,
                    antigravity,
                    opencode,
                    gemini,
                },
            );
        }
    }
    tiers
}

/// Validate parsed tier rows, agent rows, and prompt bodies, collecting ALL errors.
pub fn validate_roster(
    tier_rows: &[TierRow],
    agent_rows: &[AgentRow],
    prompts: &BTreeMap<String, String>,
) -> Result<Roster, Vec<String>> {
    let mut errors = Vec::new();
    let tier_map = validate_tier_rows(tier_rows, &mut errors);
    validate_agent_rows(&tier_map, agent_rows, prompts, &mut errors);

    if !errors.is_empty() {
        return Err(errors);
    }

    Ok(Roster {
        tiers: build_tiers(tier_map),
        generic_tiers: BTreeMap::new(),
        agents: agent_rows.to_vec(),
        prompts: prompts.clone(),
        generic_roles: Vec::new(),
        generic_prompts: BTreeMap::new(),
        skills: BTreeMap::new(),
        team_notes: None,
    })
}

fn validate_description(agent_name: &str, desc: &str, errors: &mut Vec<String>) {
    if desc.trim().is_empty() {
        errors.push(format!(
            "agent '{agent_name}': description is empty (rule: description must be non-empty)"
        ));
    }
    let char_count = desc.chars().count();
    if char_count > 320 {
        errors.push(format!(
            "agent '{agent_name}': description is {char_count} characters (rule: description must be <= 320 characters)"
        ));
    }
    if desc.contains('\n') || desc.contains('\r') {
        errors.push(format!(
            "agent '{agent_name}': description spans multiple lines (rule: description must be a single line)"
        ));
    }
    if desc.contains(": ") {
        errors.push(format!(
            "agent '{agent_name}': description contains ': ' (rule: description must contain no \": \" colon-space)"
        ));
    }
    let trimmed_start = desc.trim_start();
    if desc.starts_with('#')
        || desc.starts_with('"')
        || desc.starts_with('\'')
        || trimmed_start.starts_with('#')
        || trimmed_start.starts_with('"')
        || trimmed_start.starts_with('\'')
    {
        errors.push(format!(
            "agent '{agent_name}': description starts with '#' or quote (rule: description must have no '#' or quote characters at the start)"
        ));
    }
}

/// Validate one harness's `orchestrate` skill template (`skills/orchestrate/<harness>.md`).
pub fn validate_skill_template(harness: &str, raw: &str, errors: &mut Vec<String>) {
    let normalized = raw.replace("\r\n", "\n");
    if normalized.trim().is_empty() {
        errors.push(format!(
            "skill 'orchestrate' ({harness}): empty skill template skills/orchestrate/{harness}.md (rule: skill template must exist and be non-empty)"
        ));
        return;
    }

    let lines: Vec<&str> = normalized.lines().collect();
    if lines.first().copied() != Some("---") {
        errors.push(format!(
            "skill 'orchestrate' ({harness}): missing YAML frontmatter (rule: skill template must start with '---' frontmatter)"
        ));
        return;
    }

    let Some(close_idx) = lines
        .iter()
        .skip(1)
        .position(|&l| l == "---")
        .map(|i| i + 1)
    else {
        errors.push(format!(
            "skill 'orchestrate' ({harness}): unclosed YAML frontmatter (rule: skill frontmatter must close with '---')"
        ));
        return;
    };

    let mut name_val: Option<&str> = None;
    let mut desc_val: Option<String> = None;
    for &line in &lines[1..close_idx] {
        if let Some(rest) = line.strip_prefix("name:") {
            name_val = Some(rest.trim());
        } else if let Some(rest) = line.strip_prefix("description:") {
            let d = rest.strip_prefix(' ').unwrap_or(rest);
            desc_val = Some(d.to_string());
        } else if let Some(ref mut d) = desc_val {
            if !line.contains(':') {
                d.push('\n');
                d.push_str(line);
            }
        }
    }

    match name_val {
        None => errors.push(format!(
            "skill 'orchestrate' ({harness}): missing 'name:' in frontmatter (rule: skill frontmatter must contain 'name: orchestrate')"
        )),
        Some("orchestrate") => {}
        Some(other) => errors.push(format!(
            "skill 'orchestrate' ({harness}): invalid name '{other}' (rule: skill frontmatter must contain 'name: orchestrate')"
        )),
    }

    match desc_val {
        None => errors.push(format!(
            "skill 'orchestrate' ({harness}): missing 'description:' in frontmatter (rule: skill frontmatter must contain 'description:')"
        )),
        Some(desc) => {
            validate_description(&format!("orchestrate ({harness})"), &desc, errors);
        }
    }

    let marker_count = lines[close_idx + 1..]
        .iter()
        .filter(|&&l| l == TABLE_MARKER)
        .count();
    if marker_count != 1 {
        errors.push(format!(
            "skill 'orchestrate' ({harness}): found {marker_count} '{TABLE_MARKER}' markers (rule: skill template must contain the line '{TABLE_MARKER}' exactly once)"
        ));
    }
}

/// Validate all three harness skill templates in `.agents/roster/skills/orchestrate/<harness>.md`.
pub fn validate_skills(
    skills: &BTreeMap<String, String>,
) -> Result<BTreeMap<String, String>, Vec<String>> {
    let mut errors = Vec::new();
    for harness in REQUIRED_HARNESSES {
        match skills.get(harness) {
            None => errors.push(format!(
                "skill 'orchestrate' ({harness}): missing template skills/orchestrate/{harness}.md (rule: skills/orchestrate/{harness}.md must exist)"
            )),
            Some(raw) => validate_skill_template(harness, raw, &mut errors),
        }
    }
    if errors.is_empty() {
        Ok(skills.clone())
    } else {
        Err(errors)
    }
}

/// Parse TSV strings and validate the entire roster, collecting all errors.
pub fn load_and_validate(
    tiers_tsv: &str,
    agents_tsv: &str,
    prompts: &BTreeMap<String, String>,
) -> Result<Roster, Vec<String>> {
    let (tier_rows, mut errors) = parse_tiers(tiers_tsv);
    let (agent_rows, agent_errors) = parse_agents(agents_tsv);
    errors.extend(agent_errors);

    match validate_roster(&tier_rows, &agent_rows, prompts) {
        Ok(roster) if errors.is_empty() => Ok(roster),
        Ok(_) => Err(errors),
        Err(val_errors) => {
            errors.extend(val_errors);
            Err(errors)
        }
    }
}

/// Parse TSV strings and validate the entire roster plus all three `orchestrate` skill templates.
pub fn load_and_validate_with_skills(
    tiers_tsv: &str,
    agents_tsv: &str,
    prompts: &BTreeMap<String, String>,
    skills: &BTreeMap<String, String>,
) -> Result<Roster, Vec<String>> {
    let mut errors = Vec::new();
    let roster_res = load_and_validate(tiers_tsv, agents_tsv, prompts);
    let skills_res = validate_skills(skills);
    if let Err(e) = &roster_res {
        errors.extend(e.iter().cloned());
    }
    if let Err(e) = &skills_res {
        errors.extend(e.iter().cloned());
    }
    match (roster_res, skills_res) {
        (Ok(mut roster), Ok(valid_skills)) if errors.is_empty() => {
            roster.skills = valid_skills;
            Ok(roster)
        }
        _ => Err(errors),
    }
}

/// Parse TSV strings, generic roles/tiers/prompts, skills, and team notes, collecting all errors.
#[allow(clippy::too_many_arguments)]
pub fn load_and_validate_all(
    tiers_tsv: &str,
    agents_tsv: &str,
    prompts: &BTreeMap<String, String>,
    generic_roles_tsv: &str,
    generic_tiers_tsv: &str,
    generic_prompts: &BTreeMap<String, String>,
    skills: &BTreeMap<String, String>,
    team_notes: Option<&str>,
) -> Result<Roster, Vec<String>> {
    let (tier_rows, mut errors) = parse_tiers(tiers_tsv);
    let (agent_rows, agent_errors) = parse_agents(agents_tsv);
    errors.extend(agent_errors);
    let (role_rows, role_errors) = parse_generic_roles(generic_roles_tsv);
    errors.extend(role_errors);
    let (generic_tier_rows, generic_tier_errors) = parse_generic_tiers(generic_tiers_tsv);
    errors.extend(generic_tier_errors);

    let tier_map = validate_tier_rows(&tier_rows, &mut errors);
    validate_agent_rows(&tier_map, &agent_rows, prompts, &mut errors);
    validate_generic_role_rows(&tier_map, &role_rows, generic_prompts, &mut errors);
    let generic_tiers =
        validate_generic_tier_rows(&generic_tier_rows, &tier_map, &role_rows, &mut errors);

    let valid_skills = match validate_skills(skills) {
        Ok(s) => s,
        Err(skill_errs) => {
            errors.extend(skill_errs);
            BTreeMap::new()
        }
    };

    let valid_notes = match team_notes {
        Some(raw) => match validate_team_notes(raw) {
            Ok(n) => n,
            Err(e) => {
                errors.push(e);
                None
            }
        },
        None => None,
    };

    if errors.is_empty() {
        Ok(Roster {
            tiers: build_tiers(tier_map),
            generic_tiers,
            agents: agent_rows,
            prompts: prompts.clone(),
            generic_roles: role_rows,
            generic_prompts: generic_prompts.clone(),
            skills: valid_skills,
            team_notes: valid_notes,
        })
    } else {
        Err(errors)
    }
}

fn format_table_cell(hm: &HarnessModel) -> String {
    if hm.effort == "-" {
        hm.model.clone()
    } else {
        format!("{} ({})", hm.model, hm.effort)
    }
}

fn format_native_table_cell(hm: &HarnessModel) -> String {
    if hm.model == "-" {
        if hm.effort == "-" {
            "session model".to_string()
        } else {
            format!("session model ({})", hm.effort)
        }
    } else {
        format_table_cell(hm)
    }
}

/// A table cell for a harness where the tier's agents are drivers: `driver model → gemini model`.
fn format_driver_cell(hm: &HarnessModel, gemini: &Option<String>) -> String {
    match gemini {
        Some(g) => format!("{} → {}", format_table_cell(hm), g),
        None => format_table_cell(hm),
    }
}

fn format_generic_cell(
    driver_hm: &HarnessModel,
    native_hm: Option<&HarnessModel>,
    gemini: &Option<String>,
) -> String {
    match (gemini, native_hm) {
        (Some(_), Some(nt)) => format!(
            "{} (gemini: {})",
            format_native_table_cell(nt),
            format_driver_cell(driver_hm, gemini)
        ),
        _ => format_driver_cell(driver_hm, gemini),
    }
}

fn render_cross_harness_table<'a>(
    first_col_header: &str,
    rows: impl Iterator<Item = (&'a str, &'a str)>,
    tiers: &BTreeMap<String, TierSpec>,
    generic_tiers: Option<&BTreeMap<String, NativeTierSpec>>,
) -> String {
    let mut lines = vec![
        format!("| {first_col_header} | Tier | Claude Code | Antigravity | OpenCode |"),
        "|---|---|---|---|---|".to_string(),
    ];
    for (label, tier) in rows {
        let spec = &tiers[tier];
        let nt = generic_tiers.and_then(|gt| gt.get(tier));
        lines.push(format!(
            "| {} | {} | {} | {} | {} |",
            label,
            tier,
            format_generic_cell(&spec.claude_code, nt.map(|n| &n.claude_code), &spec.gemini),
            format_table_cell(&spec.antigravity),
            format_generic_cell(&spec.opencode, nt.map(|n| &n.opencode), &spec.gemini),
        ));
    }
    lines.join("\n")
}

