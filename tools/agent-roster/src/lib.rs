        let roster =
            load_and_validate(SAMPLE_TIERS, SAMPLE_AGENTS, &sample_prompts()).expect("valid");
        let expected = render_all(&roster);
        let mut actual = expected.clone();

        actual.remove(".agents/agents/pace.md");
        actual.insert(
            ".claude/agents/scout.md".to_string(),
            "drifted content".to_string(),
        );
        actual.insert(
            ".opencode/agents/rogue.md".to_string(),
            "extra file".to_string(),
        );

        let diff = diff_outputs(&expected, &actual);
        assert!(!diff.is_clean());
