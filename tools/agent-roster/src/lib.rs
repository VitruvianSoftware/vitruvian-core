fn json_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                out.push_str(&format!("\\u{:04x}", c as u32));
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Render `.agents/team.json` mapping every role present in `roster` (in `ROLES` order)
/// to its agent name, with `$schema` set and optional top-level `notes`.
pub fn render_team_json(roster: &Roster) -> String {
    let mut by_role: BTreeMap<&str, &str> = BTreeMap::new();
    for agent in &roster.agents {
        if !agent.role.is_empty() {
            by_role
                .entry(agent.role.as_str())
                .or_insert(agent.name.as_str());
        }
    }

    let mut entries: Vec<(&str, &str)> = Vec::new();
    for role in ROLES {
        if let Some(&agent) = by_role.get(role) {
            entries.push((role, agent));
        }
    }

    let mut out = String::new();
    out.push_str("{\n");
    out.push_str(&format!(
        "  \"$schema\": {},\n",
        json_string(TEAM_SCHEMA_ID)
    ));
    out.push_str("  \"engine\": \"gemini\",\n");
    if let Some(notes) = roster
        .team_notes
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
    {
        out.push_str(&format!("  \"notes\": {},\n", json_string(notes)));
    }
    if entries.is_empty() {
        out.push_str("  \"roles\": {}\n");
    } else {
        out.push_str("  \"roles\": {\n");
        for (idx, (role, agent)) in entries.iter().enumerate() {
            let comma = if idx + 1 < entries.len() { "," } else { "" };
            out.push_str(&format!(
                "    {}: {{\n      \"agent\": {}\n    }}{comma}\n",
                json_string(role),
                json_string(agent),
            ));
        }
        out.push_str("  }\n");
    }
    out.push_str("}\n");
    out
}

fn is_js_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    (first.is_ascii_alphabetic() || first == '_' || first == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn js_object_key(s: &str) -> String {
    if is_js_identifier(s) {
        s.to_string()
    } else {
        json_string(s)
    }
}

/// Render a plugin's built-in `tier-defaults.mjs` module from `roster.tiers`.
pub fn render_tier_defaults(roster: &Roster, harness: &str) -> String {
    let mut ordered_tiers: Vec<&String> = Vec::new();
    for canonical in CANONICAL_TIERS {
        if let Some((k, _)) = roster.tiers.get_key_value(canonical) {
            ordered_tiers.push(k);
        }
    }
    for k in roster.tiers.keys() {
        if !CANONICAL_TIERS.contains(&k.as_str()) {
            ordered_tiers.push(k);
        }
    }

    let mut out = String::new();
    out.push_str(MIT_JS_HEADER);
    out.push('\n');
    out.push_str(JS_GENERATED_COMMENT);
    out.push('\n');
    out.push_str("export const TIER_DEFAULTS = Object.freeze({\n");
    out.push_str("  tiers: Object.freeze({\n");
    for tier_key in ordered_tiers {
        let spec = &roster.tiers[tier_key];
        let effort = match harness {
            "claude-code" => &spec.claude_code.effort,
            "antigravity" => &spec.antigravity.effort,
            "opencode" => &spec.opencode.effort,
            other => panic!("unknown harness '{other}'"),
        };
        out.push_str(&format!(
            "    {}: Object.freeze({{\n",
            js_object_key(tier_key)
        ));
        if let Some(gemini) = &spec.gemini {
            out.push_str(&format!("      gemini: {},\n", json_string(gemini)));
        }
        out.push_str(&format!(
            "      \"claude-code\": {},\n",
            json_string(&spec.claude_code.model)
        ));
        out.push_str(&format!(
            "      antigravity: {},\n",
            json_string(&spec.antigravity.model)
        ));
        out.push_str(&format!(
            "      opencode: {},\n",
            json_string(&spec.opencode.model)
        ));
        if effort != "-" {
            out.push_str(&format!("      effort: {},\n", json_string(effort)));
        }
        if let Some(native) = roster.generic_tiers.get(tier_key) {
            let native_effort = match harness {
                "claude-code" => native.claude_code.effort.as_str(),
                "opencode" => native.opencode.effort.as_str(),
                "antigravity" => "-",
                other => panic!("unknown harness '{other}'"),
            };
            let opencode_val = if native.opencode.model == "-" {
                "null".to_string()
            } else {
                json_string(&native.opencode.model)
            };
            out.push_str("      native: Object.freeze({\n");
            out.push_str(&format!(
                "        \"claude-code\": {},\n",
                json_string(&native.claude_code.model)
            ));
            out.push_str(&format!("        opencode: {opencode_val},\n"));
            if native_effort != "-" {
                out.push_str(&format!(
                    "        effort: {},\n",
                    json_string(native_effort)
                ));
            }
            out.push_str("      }),\n");
        }
        out.push_str("    }),\n");
    }
    out.push_str("  }),\n");
    out.push_str("});\n");
    out
}

/// Render all generated files (project agent files in `.agents/`, `.claude/`, `.opencode/`,
