#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TierRow {
    pub tier: String,
    pub harness: String,
    pub model: String,
    pub effort: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AgentRow {
    pub name: String,
    pub tier: String,
    pub description: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HarnessModel {
    pub model: String,
    pub effort: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TierSpec {
    pub claude_code: HarnessModel,
    pub antigravity: HarnessModel,
    pub opencode: HarnessModel,
    /// The Gemini model (an `agy models` id) that does this tier's work when the tier has a
    /// `gemini` row. Such a tier runs natively on Gemini in Antigravity; in Claude Code and
    /// OpenCode its agents are generated as drivers that hand the work to this model through
    /// `agy-delegate` and verify the result.
    pub gemini: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Roster {
    pub tiers: BTreeMap<String, TierSpec>,
    pub agents: Vec<AgentRow>,
    pub prompts: BTreeMap<String, String>,
    pub skills: BTreeMap<String, String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    Check,
    Write,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DiffReport {
    pub missing: Vec<String>,
    pub different: Vec<String>,
    pub extra: Vec<String>,
    pub unchanged: usize,
}

impl DiffReport {
    pub fn is_clean(&self) -> bool {
        self.missing.is_empty() && self.different.is_empty() && self.extra.is_empty()
    }
}

/// Parse `.agents/roster/tiers.tsv`, skipping blank and `#` comment lines and requiring the header.
pub fn parse_tiers(tsv: &str) -> (Vec<TierRow>, Vec<String>) {
    let mut rows = Vec::new();
    let mut errors = Vec::new();
    let mut saw_header = false;

    for (idx, raw_line) in tsv.lines().enumerate() {
        let line_no = idx + 1;
        let trimmed = raw_line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if !saw_header {
            saw_header = true;
            if raw_line != "tier\tharness\tmodel\teffort" {
                errors.push(format!(
                    "tiers.tsv:{line_no}: invalid header '{raw_line}' (rule: tiers.tsv header must be 'tier\\tharness\\tmodel\\teffort')"
                ));
            }
            continue;
        }
        let cols: Vec<&str> = raw_line.split('\t').collect();
        if cols.len() != 4 {
            errors.push(format!(
                "tiers.tsv:{line_no}: expected 4 tab-separated columns, found {} (rule: tiers.tsv rows must have 4 columns)",
                cols.len()
            ));
            continue;
        }
        rows.push(TierRow {
            tier: cols[0].to_string(),
            harness: cols[1].to_string(),
            model: cols[2].to_string(),
            effort: cols[3].to_string(),
        });
    }

    if !saw_header {
        errors.push(
            "tiers.tsv: missing header (rule: tiers.tsv header must be 'tier\\tharness\\tmodel\\teffort')"
                .to_string(),
        );
    }

    (rows, errors)
}

/// Parse `.agents/roster/agents.tsv`, skipping blank and `#` comment lines and requiring the header.
pub fn parse_agents(tsv: &str) -> (Vec<AgentRow>, Vec<String>) {
    let mut rows = Vec::new();
    let mut errors = Vec::new();
    let mut saw_header = false;

    for (idx, raw_line) in tsv.lines().enumerate() {
        let line_no = idx + 1;
        let trimmed = raw_line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        if !saw_header {
            saw_header = true;
            if raw_line != "name\ttier\tdescription" {
                errors.push(format!(
                    "agents.tsv:{line_no}: invalid header '{raw_line}' (rule: agents.tsv header must be 'name\\ttier\\tdescription')"
                ));
            }
            continue;
        }
        let cols: Vec<&str> = raw_line.split('\t').collect();
        if cols.len() != 3 {
            errors.push(format!(
                "agents.tsv:{line_no}: expected 3 tab-separated columns, found {} (rule: agents.tsv rows must have 3 columns)",
                cols.len()
            ));
            continue;
        }
        rows.push(AgentRow {
            name: cols[0].to_string(),
            tier: cols[1].to_string(),
            description: cols[2].to_string(),
        });
    }

    if !saw_header {
        errors.push(
            "agents.tsv: missing header (rule: agents.tsv header must be 'name\\ttier\\tdescription')"
                .to_string(),
        );
    }

    (rows, errors)
}

/// Matches `^[a-z][a-z0-9-]*$`.
pub fn is_valid_agent_name(s: &str) -> bool {
    let mut bytes = s.bytes();
    let Some(first) = bytes.next() else {
        return false;
    };
    first.is_ascii_lowercase()
        && bytes.all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

/// Matches `^[a-z0-9-]+/[A-Za-z0-9._-]+(#[a-z]+)?$`.
pub fn is_valid_opencode_model(s: &str) -> bool {
    let Some((provider, rest)) = s.split_once('/') else {
        return false;
    };
    if provider.is_empty()
        || !provider
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
    {
        return false;
    }
    let (model, variant) = match rest.split_once('#') {
        Some((m, v)) => (m, Some(v)),
        None => (rest, None),
    };
    if model.is_empty()
        || !model.bytes().all(|b| {
            b.is_ascii_uppercase()
                || b.is_ascii_lowercase()
                || b.is_ascii_digit()
                || b == b'.'
                || b == b'_'
                || b == b'-'
        })
    {
        return false;
    }
    if let Some(v) = variant {
        if v.is_empty() || !v.bytes().all(|b| b.is_ascii_lowercase()) {
            return false;
        }
    }
    true
}

fn is_valid_claude_code_model(s: &str) -> bool {
    matches!(s, "inherit" | "opus" | "sonnet" | "haiku" | "fable")
        || (s.starts_with("claude-") && s.len() > "claude-".len())
}

/// A Gemini model id for `agy-delegate -m`: starts with `gemini-`, and is never a low or lite variant.
pub fn is_valid_gemini_model(s: &str) -> bool {
    s.starts_with("gemini-")
        && s.len() > "gemini-".len()
        && s.bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'.' || b == b'-')
        && !s.ends_with("-low")
        && !s.contains("-low-")
        && !s.contains("lite")
        && !s.contains("flash-lo")
}

fn is_valid_effort(s: &str) -> bool {
    matches!(s, "-" | "medium" | "high" | "xhigh" | "max")
}

/// Validate parsed tier rows, agent rows, and prompt bodies, collecting ALL errors.
pub fn validate_roster(
    tier_rows: &[TierRow],
    agent_rows: &[AgentRow],
    prompts: &BTreeMap<String, String>,
) -> Result<Roster, Vec<String>> {
    let mut errors = Vec::new();
    let mut tier_map: BTreeMap<String, BTreeMap<String, HarnessModel>> = BTreeMap::new();

    for row in tier_rows {
        if row.tier.trim().is_empty() {
            errors
                .push("tiers.tsv: empty tier name (rule: tier name must be non-empty)".to_string());
        }
        if row.effort.eq_ignore_ascii_case("low") {
            errors.push(format!(
                "tier '{}' ({}): effort '{}' is forbidden (rule: never low effort)",
                row.tier, row.harness, row.effort
            ));
        }

        match row.harness.as_str() {
            "antigravity" => {
                if !matches!(row.model.as_str(), "inherit" | "flash" | "pro") {
                    errors.push(format!(
                        "tier '{}' (antigravity): invalid model '{}' (rule: antigravity model must be in {{inherit, flash, pro}})",
                        row.tier, row.model
                    ));
                }
                if row.effort != "-" {
                    errors.push(format!(
                        "tier '{}' (antigravity): invalid effort '{}' (rule: antigravity effort must be \"-\")",
                        row.tier, row.effort
                    ));
                }
            }
            "claude-code" => {
                if !is_valid_claude_code_model(&row.model) {
                    errors.push(format!(
                        "tier '{}' (claude-code): invalid model '{}' (rule: claude-code model must be in {{inherit, opus, sonnet, haiku, fable}} or start with \"claude-\")",
                        row.tier, row.model
                    ));
                }
                if !is_valid_effort(&row.effort) {
                    errors.push(format!(
                        "tier '{}' (claude-code): invalid effort '{}' (rule: claude-code effort must be in {{-, medium, high, xhigh, max}})",
                        row.tier, row.effort
                    ));
                }
            }
            "opencode" => {
                if !is_valid_opencode_model(&row.model) {
                    errors.push(format!(
                        "tier '{}' (opencode): invalid model '{}' (rule: opencode model must match provider/model ^[a-z0-9-]+/[A-Za-z0-9._-]+(#[a-z]+)?$)",
                        row.tier, row.model
                    ));
                }
                if !is_valid_effort(&row.effort) {
                    errors.push(format!(
                        "tier '{}' (opencode): invalid effort '{}' (rule: opencode effort must be in {{-, medium, high, xhigh, max}})",
                        row.tier, row.effort
                    ));
                }
            }
            "gemini" => {
                if !is_valid_gemini_model(&row.model) {
                    errors.push(format!(
                        "tier '{}' (gemini): invalid model '{}' (rule: gemini model must be an agy model id starting with \"gemini-\", never a low, lite or flash-lo variant)",
                        row.tier, row.model
                    ));
                }
                if row.effort != "-" {
                    errors.push(format!(
                        "tier '{}' (gemini): invalid effort '{}' (rule: gemini effort must be \"-\"; the model id carries it)",
                        row.tier, row.effort
                    ));
                }
            }
            other => {
                errors.push(format!(
                    "tier '{}': unknown harness '{}' (rule: harness must be claude-code, antigravity, opencode, or gemini)",
                    row.tier, other
                ));
            }
        }

        let per_harness = tier_map.entry(row.tier.clone()).or_default();
        if per_harness.contains_key(&row.harness) {
            errors.push(format!(
                "tier '{}' ({}): duplicate row (rule: tier and harness pair must be unique)",
                row.tier, row.harness
            ));
        } else {
            per_harness.insert(
                row.harness.clone(),
                HarnessModel {
                    model: row.model.clone(),
                    effort: row.effort.clone(),
                },
            );
        }
    }

    let mut seen_agents = BTreeSet::new();
    for agent in agent_rows {
        if !is_valid_agent_name(&agent.name) {
            errors.push(format!(
                "agent '{}': invalid name (rule: agent name must match ^[a-z][a-z0-9-]*$)",
                agent.name
            ));
        }
        if !seen_agents.insert(agent.name.clone()) {
            errors.push(format!(
                "agent '{}': duplicate name (rule: agent name must be unique)",
                agent.name
            ));
        }

        let missing_harnesses: Vec<&str> = REQUIRED_HARNESSES
            .iter()
            .copied()
            .filter(|h| {
                tier_map
                    .get(&agent.tier)
                    .map(|m| !m.contains_key(*h))
                    .unwrap_or(true)
            })
            .collect();
        if !missing_harnesses.is_empty() {
            errors.push(format!(
                "agent '{}': tier '{}' missing for harness(es) {} (rule: tier must exist for all 3 harnesses)",
                agent.name,
                agent.tier,
                missing_harnesses.join(", ")
            ));
        }

        match prompts.get(&agent.name) {
            None => {
                errors.push(format!(
                    "agent '{}': missing prompt file prompts/{}.md (rule: prompts/<name>.md must exist and be non-empty)",
                    agent.name, agent.name
                ));
            }
            Some(body) if body.trim().is_empty() => {
                errors.push(format!(
                    "agent '{}': empty prompt file prompts/{}.md (rule: prompts/<name>.md must exist and be non-empty)",
                    agent.name, agent.name
                ));
            }
            Some(_) => {}
        }

        validate_description(&agent.name, &agent.description, &mut errors);
    }

    if !errors.is_empty() {
        return Err(errors);
    }

    let mut tiers = BTreeMap::new();
    for (tier_name, mut map) in tier_map {
        if let (Some(claude_code), Some(antigravity), Some(opencode)) = (
            map.remove("claude-code"),
            map.remove("antigravity"),
            map.remove("opencode"),
        ) {
            let gemini = map.remove("gemini").map(|hm| hm.model);
            tiers.insert(
                tier_name,
                TierSpec {
                    claude_code,
                    antigravity,
                    opencode,
                    gemini,
                },
            );
        }
    }

    Ok(Roster {
        tiers,
        agents: agent_rows.to_vec(),
        prompts: prompts.clone(),
        skills: BTreeMap::new(),
    })
}

fn validate_description(agent_name: &str, desc: &str, errors: &mut Vec<String>) {
    if desc.trim().is_empty() {
        errors.push(format!(
            "agent '{agent_name}': description is empty (rule: description must be non-empty)"
        ));
    }
    let char_count = desc.chars().count();
    if char_count > 320 {
        errors.push(format!(
            "agent '{agent_name}': description is {char_count} characters (rule: description must be <= 320 characters)"
        ));
    }
    if desc.contains('\n') || desc.contains('\r') {
        errors.push(format!(
            "agent '{agent_name}': description spans multiple lines (rule: description must be a single line)"
        ));
    }
    if desc.contains(": ") {
        errors.push(format!(
            "agent '{agent_name}': description contains ': ' (rule: description must contain no \": \" colon-space)"
        ));
    }
    let trimmed_start = desc.trim_start();
    if desc.starts_with('#')
        || desc.starts_with('"')
        || desc.starts_with('\'')
        || trimmed_start.starts_with('#')
        || trimmed_start.starts_with('"')
        || trimmed_start.starts_with('\'')
    {
        errors.push(format!(
            "agent '{agent_name}': description starts with '#' or quote (rule: description must have no '#' or quote characters at the start)"
        ));
    }
}

/// Validate one harness's `orchestrate` skill template (`skills/orchestrate/<harness>.md`).
pub fn validate_skill_template(harness: &str, raw: &str, errors: &mut Vec<String>) {
    let normalized = raw.replace("\r\n", "\n");
    if normalized.trim().is_empty() {
        errors.push(format!(
            "skill 'orchestrate' ({harness}): empty skill template skills/orchestrate/{harness}.md (rule: skill template must exist and be non-empty)"
        ));
        return;
    }

    let lines: Vec<&str> = normalized.lines().collect();
    if lines.first().copied() != Some("---") {
        errors.push(format!(
            "skill 'orchestrate' ({harness}): missing YAML frontmatter (rule: skill template must start with '---' frontmatter)"
        ));
        return;
    }

    let Some(close_idx) = lines
        .iter()
        .skip(1)
        .position(|&l| l == "---")
        .map(|i| i + 1)
    else {
        errors.push(format!(
            "skill 'orchestrate' ({harness}): unclosed YAML frontmatter (rule: skill frontmatter must close with '---')"
        ));
        return;
    };

    let mut name_val: Option<&str> = None;
    let mut desc_val: Option<String> = None;
    for &line in &lines[1..close_idx] {
        if let Some(rest) = line.strip_prefix("name:") {
            name_val = Some(rest.trim());
        } else if let Some(rest) = line.strip_prefix("description:") {
            let d = rest.strip_prefix(' ').unwrap_or(rest);
            desc_val = Some(d.to_string());
        } else if let Some(ref mut d) = desc_val {
            if !line.contains(':') {
                d.push('\n');
                d.push_str(line);
            }
        }
    }

    match name_val {
        None => errors.push(format!(
            "skill 'orchestrate' ({harness}): missing 'name:' in frontmatter (rule: skill frontmatter must contain 'name: orchestrate')"
        )),
        Some("orchestrate") => {}
        Some(other) => errors.push(format!(
            "skill 'orchestrate' ({harness}): invalid name '{other}' (rule: skill frontmatter must contain 'name: orchestrate')"
        )),
    }

    match desc_val {
        None => errors.push(format!(
            "skill 'orchestrate' ({harness}): missing 'description:' in frontmatter (rule: skill frontmatter must contain 'description:')"
        )),
        Some(desc) => {
            validate_description(&format!("orchestrate ({harness})"), &desc, errors);
        }
    }

    let marker_count = lines[close_idx + 1..]
        .iter()
        .filter(|&&l| l == TABLE_MARKER)
        .count();
    if marker_count != 1 {
        errors.push(format!(
            "skill 'orchestrate' ({harness}): found {marker_count} '{TABLE_MARKER}' markers (rule: skill template must contain the line '{TABLE_MARKER}' exactly once)"
        ));
    }
}

/// Validate all three harness skill templates in `.agents/roster/skills/orchestrate/<harness>.md`.
pub fn validate_skills(
    skills: &BTreeMap<String, String>,
) -> Result<BTreeMap<String, String>, Vec<String>> {
    let mut errors = Vec::new();
    for &(harness, _) in &SKILL_OUTPUTS {
        match skills.get(harness) {
            None => errors.push(format!(
                "skill 'orchestrate' ({harness}): missing template skills/orchestrate/{harness}.md (rule: skills/orchestrate/{harness}.md must exist)"
            )),
            Some(raw) => validate_skill_template(harness, raw, &mut errors),
        }
    }
    if errors.is_empty() {
        Ok(skills.clone())
    } else {
        Err(errors)
    }
}

/// Parse TSV strings and validate the entire roster, collecting all errors.
pub fn load_and_validate(
    tiers_tsv: &str,
    agents_tsv: &str,
    prompts: &BTreeMap<String, String>,
) -> Result<Roster, Vec<String>> {
    let (tier_rows, mut errors) = parse_tiers(tiers_tsv);
    let (agent_rows, agent_errors) = parse_agents(agents_tsv);
    errors.extend(agent_errors);

    match validate_roster(&tier_rows, &agent_rows, prompts) {
        Ok(roster) if errors.is_empty() => Ok(roster),
        Ok(_) => Err(errors),
        Err(val_errors) => {
            errors.extend(val_errors);
            Err(errors)
        }
    }
}

/// Parse TSV strings and validate the entire roster plus all three `orchestrate` skill templates.
pub fn load_and_validate_with_skills(
    tiers_tsv: &str,
    agents_tsv: &str,
    prompts: &BTreeMap<String, String>,
    skills: &BTreeMap<String, String>,
) -> Result<Roster, Vec<String>> {
    let mut errors = Vec::new();
    let roster_res = load_and_validate(tiers_tsv, agents_tsv, prompts);
    let skills_res = validate_skills(skills);
    if let Err(e) = &roster_res {
        errors.extend(e.iter().cloned());
    }
    if let Err(e) = &skills_res {
        errors.extend(e.iter().cloned());
    }
    match (roster_res, skills_res) {
        (Ok(mut roster), Ok(valid_skills)) if errors.is_empty() => {
            roster.skills = valid_skills;
            Ok(roster)
        }
        _ => Err(errors),
    }
}

fn format_table_cell(hm: &HarnessModel) -> String {
    if hm.effort == "-" {
        hm.model.clone()
    } else {
        format!("{} ({})", hm.model, hm.effort)
    }
}

/// A table cell for a harness where the tier's agents are drivers: `driver model → gemini model`.
fn format_driver_cell(hm: &HarnessModel, gemini: &Option<String>) -> String {
    match gemini {
        Some(g) => format!("{} → {}", format_table_cell(hm), g),
        None => format_table_cell(hm),
    }
}

/// Render the markdown table that replaces `<!-- roster:table -->` in agent prompts.
pub fn render_roster_table(roster: &Roster) -> String {
    let mut lines = Vec::with_capacity(roster.agents.len() + 2);
    lines.push("| Agent | Tier | Claude Code | Antigravity | OpenCode |".to_string());
    lines.push("|---|---|---|---|---|".to_string());
    for agent in &roster.agents {
        let spec = &roster.tiers[&agent.tier];
        lines.push(format!(
            "| {} | {} | {} | {} | {} |",
            agent.name,
            agent.tier,
            format_driver_cell(&spec.claude_code, &spec.gemini),
            format_table_cell(&spec.antigravity),
            format_driver_cell(&spec.opencode, &spec.gemini),
        ));
    }
    lines.join("\n")
}

/// Render the harness-specific markdown table (`| Agent | Tier | Model | Routing rule |`) that replaces `<!-- roster:table -->` in a skill template.
pub fn render_harness_roster_table(roster: &Roster, harness: &str) -> String {
    let mut lines = Vec::with_capacity(roster.agents.len() + 2);
    lines.push("| Agent | Tier | Model | Routing rule |".to_string());
    lines.push("|---|---|---|---|".to_string());
    for agent in &roster.agents {
        let spec = &roster.tiers[&agent.tier];
        let cell = match harness {
            "claude-code" => format_driver_cell(&spec.claude_code, &spec.gemini),
            "antigravity" => format_table_cell(&spec.antigravity),
            "opencode" => format_driver_cell(&spec.opencode, &spec.gemini),
            other => panic!("unknown harness '{other}'"),
        };
        lines.push(format!(
            "| {} | {} | {} | {} |",
            agent.name, agent.tier, cell, agent.description,
        ));
    }
    lines.join("\n")
}

fn render_prompt_body(raw_prompt: &str, table: &str) -> String {
    let normalized = raw_prompt.replace("\r\n", "\n");
    let stripped = normalized.strip_prefix('\n').unwrap_or(&normalized);
    let mut out_lines = Vec::new();
    for line in stripped.lines() {
        if line == TABLE_MARKER {
            out_lines.push(table);
        } else {
            out_lines.push(line);
        }
    }
    out_lines.join("\n")
}

/// Render a single harness's `orchestrate` skill (`SKILL.md`) from its validated template.
pub fn render_skill(roster: &Roster, harness: &str, raw_template: &str) -> String {
    let normalized = raw_template.replace("\r\n", "\n");
    let after_open = normalized
        .strip_prefix("---\n")
        .expect("validated skill template starts with ---\\n");
    let (fm_inner, rest) = if let Some(r) = after_open.strip_prefix("---\n") {
        ("", r)
    } else {
        after_open
            .split_once("\n---\n")
            .expect("validated skill template closes frontmatter with ---")
    };
    let frontmatter = if fm_inner.is_empty() {
        "---\n---".to_string()
    } else {
        format!("---\n{fm_inner}\n---")
    };
    let table = render_harness_roster_table(roster, harness);
    let body = render_prompt_body(rest, &table);
    format!(
        "{frontmatter}\n{GENERATED_COMMENT}\n\n{}\n",
        body.trim_end_matches('\n')
    )
}

