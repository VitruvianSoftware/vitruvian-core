/// Render the harness-specific markdown table (`| Role | Tier | Model | What it does |`) that replaces `<!-- roster:table -->` in a skill template.
pub fn render_harness_role_table(roster: &Roster, harness: &str) -> String {
    let mut lines = Vec::with_capacity(roster.generic_roles.len() + 2);
    lines.push("| Role | Tier | Model | What it does |".to_string());
    lines.push("|---|---|---|---|".to_string());
    for role in &roster.generic_roles {
        let spec = &roster.tiers[&role.tier];
        let nt = roster.generic_tiers.get(&role.tier);
        let cell = match harness {
            "claude-code" => {
                format_generic_cell(&spec.claude_code, nt.map(|n| &n.claude_code), &spec.gemini)
            }
            "antigravity" => format_table_cell(&spec.antigravity),
            "opencode" => {
                format_generic_cell(&spec.opencode, nt.map(|n| &n.opencode), &spec.gemini)
            }
            other => panic!("unknown harness '{other}'"),
        };
        lines.push(format!(
            "| {} | {} | {} | {} |",
            role.role, role.tier, cell, role.description,
        ));
    }
    lines.join("\n")
}

fn render_prompt_body(raw_prompt: &str, table: &str) -> String {
    let normalized = raw_prompt.replace("\r\n", "\n");
    let stripped = normalized.strip_prefix('\n').unwrap_or(&normalized);
    let mut out_lines = Vec::new();
    for line in stripped.lines() {
        if line == TABLE_MARKER {
            out_lines.push(table);
        } else {
            out_lines.push(line);
        }
    }
    out_lines.join("\n")
}

/// Render a single harness's `orchestrate` skill (`SKILL.md`) from its validated template.
pub fn render_skill(roster: &Roster, harness: &str, raw_template: &str) -> String {
    let normalized = raw_template.replace("\r\n", "\n");
    let after_open = normalized
        .strip_prefix("---\n")
        .expect("validated skill template starts with ---\\n");
    let (fm_inner, rest) = if let Some(r) = after_open.strip_prefix("---\n") {
        ("", r)
    } else {
        after_open
            .split_once("\n---\n")
            .expect("validated skill template closes frontmatter with ---")
    };
    let frontmatter = if fm_inner.is_empty() {
        "---\n---".to_string()
    } else {
        format!("---\n{fm_inner}\n---")
    };
    let table = render_harness_role_table(roster, harness);
    let body = render_prompt_body(rest, &table);
    format!(
        "{frontmatter}\n{GENERIC_GENERATED_COMMENT}\n\n{}\n",
        body.trim_end_matches('\n')
    )
}

