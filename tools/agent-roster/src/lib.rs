/// Render all generated files (3N agent files plus any loaded skill files) keyed by repo-relative path.
pub fn render_all(roster: &Roster) -> BTreeMap<String, String> {
    let table = render_roster_table(roster);
    let mut files = BTreeMap::new();

    for agent in &roster.agents {
        let spec = &roster.tiers[&agent.tier];
        let raw_prompt = &roster.prompts[&agent.name];
        let body = render_prompt_body(raw_prompt, &table);

        files.insert(
            format!(".agents/agents/{}.md", agent.name),
            render_antigravity_agent(agent, spec, &body),
        );
        files.insert(
            format!(".claude/agents/{}.md", agent.name),
            render_claude_code_agent(agent, spec, &body),
        );
        files.insert(
            format!(".opencode/agents/{}.md", agent.name),
            render_opencode_agent(agent, spec, &body),
        );
    }

    for &(harness, out_path) in &SKILL_OUTPUTS {
        if let Some(template) = roster.skills.get(harness) {
            files.insert(
                out_path.to_string(),
                render_skill(roster, harness, template),
            );
        }
    }

    files
}

/// Compare expected output map against existing `.md` files in the three output folders.
pub fn diff_outputs(
    expected: &BTreeMap<String, String>,
    actual: &BTreeMap<String, String>,
) -> DiffReport {
    let mut missing = Vec::new();
    let mut different = Vec::new();
    let mut extra = Vec::new();
    let mut unchanged = 0usize;

    for (path, exp_content) in expected {
        match actual.get(path) {
            None => missing.push(path.clone()),
            Some(act_content) if act_content != exp_content => different.push(path.clone()),
            Some(_) => unchanged += 1,
        }
    }

    for path in actual.keys() {
        if !expected.contains_key(path) {
            extra.push(path.clone());
        }
    }

    DiffReport {
        missing,
        different,
        extra,
        unchanged,
    }
}

fn read_existing_outputs(repo_root: &Path) -> Result<BTreeMap<String, String>, String> {
    let mut actual = BTreeMap::new();
    for rel_dir in OUTPUT_DIRS {
        let dir = repo_root.join(rel_dir);
        if !dir.exists() {
            continue;
        }
        let entries = fs::read_dir(&dir)
            .map_err(|e| format!("failed to read directory {}: {e}", dir.display()))?;
        for entry in entries {
            let entry = entry.map_err(|e| format!("failed to read directory entry: {e}"))?;
            let path = entry.path();
            if path.extension().and_then(|s| s.to_str()) == Some("md") && path.is_file() {
                let file_name = entry.file_name().to_string_lossy().into_owned();
                let rel_path = format!("{rel_dir}/{file_name}");
                let content = fs::read_to_string(&path)
                    .map_err(|e| format!("failed to read {rel_path}: {e}"))?;
                actual.insert(rel_path, content);
            }
        }
    }
    for rel_path in SKILL_OUTPUTS
        .iter()
        .map(|&(_, p)| p)
        .chain(CORE_COPIES)
        .chain(PRICES_COPIES)
    {
        let path = repo_root.join(rel_path);
        if path.is_file() {
            let content =
                fs::read_to_string(&path).map_err(|e| format!("failed to read {rel_path}: {e}"))?;
            actual.insert(rel_path.to_string(), content);
        }
    }
    Ok(actual)
}

/// Run `--check` or `--write` against `repo_root`. Returns process exit code.
pub fn run_in_workspace(repo_root: &Path, mode: Mode) -> i32 {
    let roster_dir = repo_root.join(".agents/roster");
    let tiers_path = roster_dir.join("tiers.tsv");
    let agents_path = roster_dir.join("agents.tsv");

    let tiers_tsv = match fs::read_to_string(&tiers_path) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("error reading {}: {e}", tiers_path.display());
            return 1;
        }
    };
    let agents_tsv = match fs::read_to_string(&agents_path) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("error reading {}: {e}", agents_path.display());
            return 1;
        }
    };

    let (agent_rows_preview, _) = parse_agents(&agents_tsv);
    let mut prompts = BTreeMap::new();
    for agent in &agent_rows_preview {
        let prompt_path = roster_dir
            .join("prompts")
            .join(format!("{}.md", agent.name));
        if let Ok(content) = fs::read_to_string(&prompt_path) {
            prompts.insert(agent.name.clone(), content);
        }
    }

    let mut skills = BTreeMap::new();
    for &(harness, _) in &SKILL_OUTPUTS {
        let skill_path = roster_dir
            .join("skills")
            .join("orchestrate")
            .join(format!("{harness}.md"));
        if let Ok(content) = fs::read_to_string(&skill_path) {
            skills.insert(harness.to_string(), content);
        }
    }

    let roster = match load_and_validate_with_skills(&tiers_tsv, &agents_tsv, &prompts, &skills) {
        Ok(r) => r,
        Err(errors) => {
            for err in errors {
                eprintln!("error: {err}");
            }
            return 1;
        }
    };

    let mut expected = render_all(&roster);
    match fs::read_to_string(repo_root.join(CORE_SOURCE)) {
        Ok(core) => add_core_copies(&mut expected, &core),
        Err(e) => {
            eprintln!("error reading {CORE_SOURCE}: {e}");
            return 1;
        }
    }
    match fs::read_to_string(repo_root.join(PRICES_SOURCE)) {
        Ok(prices) => add_prices_copies(&mut expected, &prices),
        Err(e) => {
            eprintln!("error reading {PRICES_SOURCE}: {e}");
            return 1;
        }
    }
    let actual = match read_existing_outputs(repo_root) {
        Ok(a) => a,
        Err(e) => {
            eprintln!("error: {e}");
            return 1;
        }
    };

    let diff = diff_outputs(&expected, &actual);

    match mode {
        Mode::Check => {
            if diff.is_clean() {
                println!(
                    "agent-roster: all {} generated files up to date",
                    expected.len()
                );
                0
            } else {
                for p in &diff.missing {
                    eprintln!("missing: {p}");
                }
                for p in &diff.different {
                    eprintln!("different: {p}");
                }
                for p in &diff.extra {
                    eprintln!("extra: {p}");
                }
                eprintln!("run: bazel run //tools/agent-roster -- --write");
                1
            }
        }
        Mode::Write => {
            for rel_dir in OUTPUT_DIRS {
                let dir = repo_root.join(rel_dir);
                if let Err(e) = fs::create_dir_all(&dir) {
                    eprintln!("error creating directory {}: {e}", dir.display());
                    return 1;
                }
            }
            let mut written = 0usize;
            for p in diff.missing.iter().chain(diff.different.iter()) {
                let content = &expected[p];
                let full_path = repo_root.join(p);
                if let Some(parent) = full_path.parent() {
                    if let Err(e) = fs::create_dir_all(parent) {
                        eprintln!("error creating directory {}: {e}", parent.display());
                        return 1;
                    }
                }
                if let Err(e) = fs::write(&full_path, content) {
                    eprintln!("error writing {p}: {e}");
                    return 1;
                }
                written += 1;
            }
            let mut removed = 0usize;
            for p in &diff.extra {
                let full_path = repo_root.join(p);
                if let Err(e) = fs::remove_file(&full_path) {
                    eprintln!("error removing {p}: {e}");
                    return 1;
                }
                removed += 1;
            }
            println!(
                "written {written}, unchanged {}, removed {removed}",
                diff.unchanged
            );
            0
        }
    }
}

