/// Matches `^[a-z][a-z0-9-]*$`.
pub fn is_valid_agent_name(s: &str) -> bool {
    let mut bytes = s.bytes();
    let Some(first) = bytes.next() else {
        return false;
    };
    first.is_ascii_lowercase()
        && bytes.all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

/// Matches `^[a-z0-9-]+/[A-Za-z0-9._-]+(#[a-z]+)?$`.
pub fn is_valid_opencode_model(s: &str) -> bool {
    let Some((provider, rest)) = s.split_once('/') else {
        return false;
    };
    if provider.is_empty()
        || !provider
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
    {
        return false;
    }
    let (model, variant) = match rest.split_once('#') {
        Some((m, v)) => (m, Some(v)),
        None => (rest, None),
    };
    if model.is_empty()
        || !model.bytes().all(|b| {
            b.is_ascii_uppercase()
                || b.is_ascii_lowercase()
                || b.is_ascii_digit()
                || b == b'.'
                || b == b'_'
                || b == b'-'
        })
    {
        return false;
    }
    if let Some(v) = variant {
        if v.is_empty() || !v.bytes().all(|b| b.is_ascii_lowercase()) {
            return false;
        }
    }
    true
}

fn is_valid_claude_code_model(s: &str) -> bool {
    matches!(s, "inherit" | "opus" | "sonnet" | "haiku" | "fable")
        || (s.starts_with("claude-") && s.len() > "claude-".len())
}

fn has_forbidden_model_substring(s: &str) -> bool {
    let lower = s.to_ascii_lowercase();
    lower.contains("-low") || lower.contains("-lite") || lower.contains("flash-lo")
}

/// A Gemini model id for `agy-delegate -m`: matches `^gemini-[a-z0-9.-]+$` and never contains `-low`, `-lite`, or `flash-lo`.
pub fn is_valid_gemini_model(s: &str) -> bool {
    s.starts_with("gemini-")
        && s.len() > "gemini-".len()
        && s.bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'.' || b == b'-')
        && !has_forbidden_model_substring(s)
}

/// Extract a valid `Engine: <engine>` line from `brief` (first line starting with `Engine:`,
/// stripping at most one trailing `\r` for CRLF files and accepting only exact `gemini` or
/// `native` after `Engine: `), falling back to `"native"`.
pub fn resolve_brief_engine(brief: &str) -> &'static str {
    for raw_line in brief.split('\n') {
        let line = raw_line.strip_suffix('\r').unwrap_or(raw_line);
        if line.starts_with("Engine:") {
            return match line.strip_prefix("Engine: ") {
                Some("gemini") => "gemini",
                Some("native") => "native",
                _ => "native",
            };
        }
    }
    "native"
}

/// A worktree branch name: matches `^[a-z0-9][a-z0-9._/-]{0,99}$` and contains no `..`.
pub fn is_valid_worktree(s: &str) -> bool {
    let bytes = s.as_bytes();
    if bytes.is_empty() || bytes.len() > 100 || s.contains("..") {
        return false;
    }
    let first_ok = bytes[0].is_ascii_lowercase() || bytes[0].is_ascii_digit();
    let rest_ok = bytes[1..].iter().all(|&b| {
        b.is_ascii_lowercase()
            || b.is_ascii_digit()
            || b == b'.'
            || b == b'_'
            || b == b'/'
            || b == b'-'
    });
    first_ok && rest_ok
}

/// A board channel handle: matches `^[a-z0-9][a-z0-9-]{0,31}$`.
pub fn is_valid_channel(s: &str) -> bool {
    let bytes = s.as_bytes();
    if bytes.is_empty() || bytes.len() > 32 {
        return false;
    }
    let first_ok = bytes[0].is_ascii_lowercase() || bytes[0].is_ascii_digit();
    let rest_ok = bytes[1..]
        .iter()
        .all(|&b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-');
    first_ok && rest_ok
}

/// Extract a valid `Channel: <name>` target from `brief`, returning `None` when absent or invalid.
pub fn resolve_brief_channel<'a>(brief: &'a str) -> Option<&'a str> {
    for line in brief.lines() {
        if let Some(rest) = line.trim().strip_prefix("Channel:") {
            let candidate = rest.trim();
            if is_valid_channel(candidate) {
                return Some(candidate);
            }
            return None;
        }
    }
    None
}

/// Extract a valid `Gemini model: <id>` override from `brief`, falling back to `default_gemini`
/// when absent or invalid.
pub fn resolve_brief_gemini_model<'a>(brief: &'a str, default_gemini: &'a str) -> &'a str {
    for line in brief.lines() {
        if let Some(rest) = line.trim().strip_prefix("Gemini model:") {
            let candidate = rest.trim();
            if is_valid_gemini_model(candidate) {
                return candidate;
            }
            return default_gemini;
        }
    }
    default_gemini
}

