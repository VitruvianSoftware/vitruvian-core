// RenderPresubmitWorkflow compiles declared units into a GitHub Actions dynamic workflow DAG.
func RenderPresubmitWorkflow(units []Unit) (string, error) {
	dag, err := BuildDAG(units)
	if err != nil {
		return "", err
	}

	orderedUnits, err := dag.TopologicalOrder()
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString(mitLicenseHeader)
	b.WriteString("\n\n")
	b.WriteString(generatedBanner)
	b.WriteString("\n\n")

	b.WriteString("name: Presubmit\n\n")
	b.WriteString("on:\n")
	b.WriteString("  pull_request:\n")
	b.WriteString("  merge_group:\n")
	b.WriteString("  push:\n")
	b.WriteString("    branches: [main]\n\n")

	b.WriteString("concurrency:\n")
	b.WriteString("  group: presubmit-${{ github.workflow }}-${{ github.event_name }}-${{ github.event_name == 'pull_request' && github.ref || github.sha }}\n")
	b.WriteString("  cancel-in-progress: ${{ github.event_name == 'pull_request' }}\n\n")

	b.WriteString("permissions:\n")
	b.WriteString("  contents: read\n\n")

	b.WriteString("jobs:\n")

	// Every unit name, as a JSON array literal. This is the fail-safe: if the
	// planner cannot answer, the plan job emits this and everything runs, which
	// is exactly the behaviour before any of this existed.
	allNames := make([]string, 0, len(orderedUnits))
	for _, u := range orderedUnits {
		allNames = append(allNames, fmt.Sprintf("%q", u.Name))
	}
	allNamesJSON := "[" + strings.Join(allNames, ",") + "]"

	// Render the plan job: works out which units this change actually affects.
	//
	// Fails OPEN, deliberately. Every failure path here -- planner crash, no
	// output, malformed output -- emits the full unit list, so a broken planner
	// costs compute rather than test coverage.
	b.WriteString("  plan:\n")
	b.WriteString("    name: plan/affected-units\n")
	b.WriteString("    runs-on: ubuntu-26.04\n")
	// 35, not 20: building the planner takes ~5 min on a cold runner and the
	// query below is allowed 15 (see --timeout-sec), plus checkout and setup.
	b.WriteString("    timeout-minutes: 35\n")
	b.WriteString("    outputs:\n")
	b.WriteString("      units: ${{ steps.plan.outputs.units }}\n")
	b.WriteString("      degraded: ${{ steps.plan.outputs.degraded }}\n")
	b.WriteString("    env:\n")
	b.WriteString("      BUILDBUDDY_API_KEY: ${{ secrets.BUILDBUDDY_API_KEY }}\n")
	b.WriteString("    steps:\n")
	b.WriteString("      - uses: actions/checkout@v7.0.1\n")
	b.WriteString("        with:\n")
	b.WriteString("          persist-credentials: false\n")
	// The diff needs real history; a shallow clone cannot see the base.
	b.WriteString("          fetch-depth: 0\n\n")
	b.WriteString("      - name: Free up runner disk space\n")
	b.WriteString("        uses: ./.github/actions/free-disk-space\n\n")
	b.WriteString("      - name: Set up Bazel\n")
	b.WriteString("        uses: ./.github/actions/setup-bazel\n\n")
	// The dependency map for the diff base, saved by the rdeps-map job when
	// that commit landed on main (#2465). A miss is normal (base not on main
	// yet, or its map job still running): the planner then queries live.
	b.WriteString("      - name: Restore the dependency map for the diff base\n")
	b.WriteString("        uses: actions/cache/restore@55cc8345863c7cc4c66a329aec7e433d2d1c52a9 # v6\n")
	b.WriteString("        with:\n")
	b.WriteString("          path: ${{ runner.temp }}/pipeline-rdeps-map.json\n")
	b.WriteString("          key: pipeline-rdeps-map-v1-${{ github.event.pull_request.base.sha || github.event.merge_group.base_sha || github.event.before }}\n\n")
	b.WriteString("      - name: Work out which units this change affects\n")
	b.WriteString("        id: plan\n")
	// SHAs come from the event payload, so they go through env rather than
	// being interpolated into the script body.
	b.WriteString("        env:\n")
	b.WriteString("          EVENT_NAME: ${{ github.event_name }}\n")
	b.WriteString("          PR_BASE_SHA: ${{ github.event.pull_request.base.sha }}\n")
	b.WriteString("          MQ_BASE_SHA: ${{ github.event.merge_group.base_sha }}\n")
	b.WriteString("          PUSH_BEFORE: ${{ github.event.before }}\n")
	fmt.Fprintf(&b, "          ALL_UNITS: '%s'\n", allNamesJSON)
	b.WriteString("        run: |\n")
	// `set +e` is load-bearing and easy to lose. GitHub runs `run:` steps as
	// `bash -e -o pipefail`, so errexit is ALREADY ON before this script starts
	// -- writing `set -uo pipefail` does not turn it off, and every fail-open
	// branch below becomes unreachable: the step dies on the first non-zero
	// exit with none of its warnings printed. That is exactly what happened on
	// the first run of this job (3m18s of silence, then exit 1).
	b.WriteString("          set +e -u -o pipefail\n")
	b.WriteString("          case \"$EVENT_NAME\" in\n")
	b.WriteString("            pull_request) base=\"$PR_BASE_SHA\" ;;\n")
	b.WriteString("            merge_group)  base=\"$MQ_BASE_SHA\" ;;\n")
	b.WriteString("            push)         base=\"$PUSH_BEFORE\" ;;\n")
	b.WriteString("            *)            base=\"\" ;;\n")
	b.WriteString("          esac\n")
	b.WriteString("          units=\"$ALL_UNITS\"\n")
	b.WriteString("          degraded=unknown\n")
	b.WriteString("          if [ -z \"$base\" ]; then\n")
	b.WriteString("            echo \"::warning::No diff base for event '$EVENT_NAME'; running every unit.\"\n")
	b.WriteString("          else\n")
	// Plain `bazel run`, matching tools/ci/affected-targets.sh, which is the
	// other consumer of this binary and works today. stderr goes to a file
	// rather than /dev/null so a failure here is diagnosable instead of three
	// silent minutes.
	//
	// --head=HEAD is load-bearing. Without it the planner diffs the base
	// against the WORKING TREE, and `bazel run` itself rewrites
	// MODULE.bazel.lock on a Linux runner whenever an os_dependent module
	// extension has no linux entry committed (tools/android_ndk, since #2414).
	// The dirty lockfile then reads as a global-impact change and every unit
	// runs on every diff, silently -- a genuine global change, not a degraded
	// plan, so no warning fires. Diff the commit, not the checkout.
	b.WriteString("            out=\"$(bazel run //tools/pipeline:plan -- \\\n")
	//
	// --timeout-sec=900: on a cold runner the rdeps query loads ~8,400
	// external repos and took 6-10 min (#2465). At the planner's 300s default
	// it timed out about half the time and every unit ran. Waiting longer for
	// a precise answer is cheaper than building all 20 units. A stopgap until
	// PR plans stop running the query live.
	b.WriteString("                     --base=\"$base\" --head=HEAD --event=\"$EVENT_NAME\" --timeout-sec=900 \\\n")
	b.WriteString("                     --rdeps-map=\"$RUNNER_TEMP/pipeline-rdeps-map.json\" \\\n")
	b.WriteString("                     --format=github-matrix --repo-root=\"$PWD\" 2>/tmp/plan.err)\"\n")
	b.WriteString("            rc=$?\n")
	b.WriteString("            if [ \"$rc\" -ne 0 ]; then\n")
	b.WriteString("              echo \"::warning::Planner exited $rc; running every unit. Last lines:\"\n")
	b.WriteString("              tail -n 30 /tmp/plan.err || true\n")
	b.WriteString("            fi\n")
	b.WriteString("            matrix=\"$(printf '%s\\n' \"$out\" | grep '^matrix=' | sed 's/^matrix=//')\"\n")
	b.WriteString("            degraded=\"$(printf '%s\\n' \"$out\" | grep '^is_degraded=' | sed 's/^is_degraded=//')\"\n")
	b.WriteString("            if [ -n \"$matrix\" ] && parsed=\"$(printf '%s' \"$matrix\" | jq -c '[.[].name]' 2>/dev/null)\"; then\n")
	b.WriteString("              units=\"$parsed\"\n")
	b.WriteString("            else\n")
	b.WriteString("              echo \"::warning::Could not read an affected-unit list; running every unit.\"\n")
	b.WriteString("              units=\"$ALL_UNITS\"\n")
	b.WriteString("            fi\n")
	b.WriteString("          fi\n")
	// Say where the answer came from, so a map that is never used (or a
	// live query that keeps running) is visible rather than silently slow.
	b.WriteString("          echo \"plan source: $(printf '%s\\n' \"${out:-}\" | sed -n 's/^plan_source=//p')\"\n")
	b.WriteString("          grep -E '^(no dependency map|dependency map not used|note:)' /tmp/plan.err 2>/dev/null || true\n")
	b.WriteString("          echo \"affected units: $units\"\n")
	b.WriteString("          echo \"units=$units\" >> \"$GITHUB_OUTPUT\"\n")
	b.WriteString("          echo \"degraded=$degraded\" >> \"$GITHUB_OUTPUT\"\n")
	// A degraded plan is CORRECT but expensive, and the whole reason the
	// planner reports it separately from a genuine global change is so it
	// cannot hide. Capturing the flag and never printing it is the same
	// silence in a different place: a 15s default timeout once made every
	// plan a full sweep for months precisely because nothing said so.
	b.WriteString("          if [ \"$degraded\" = \"true\" ]; then\n")
	b.WriteString("            echo \"::warning::Affected-target analysis DEGRADED: could not work out what changed, so every unit is running. Safe but wasteful -- see the planner output below for the cause.\"\n")
	// The warning used to say "see the planner output above", but on exit 0
	// that output was never printed: it sat in /tmp/plan.err. The degraded
	// reason (a timed-out or failed query) is only in stderr, so show it.
	// The planner's own warning line carries the reason; echoing it turns it
	// into an annotation. Fall back to the raw tail if it is missing.
	b.WriteString("            grep -m1 -A15 '^::warning title=Affected-target analysis degraded' /tmp/plan.err || tail -n 30 /tmp/plan.err || true\n")
	b.WriteString("          fi\n")
	b.WriteString("          {\n")
	b.WriteString("            echo \"### Affected units\"\n")
	b.WriteString("            echo \"\"\n")
	b.WriteString("            if [ \"$degraded\" = \"true\" ]; then\n")
	b.WriteString("              echo \"> **Degraded plan.** The affected-target query failed, so every unit is running. This is safe but wastes CI time; fix the cause rather than paying for it.\"\n")
	b.WriteString("              echo \"\"\n")
	b.WriteString("            fi\n")
	b.WriteString("            printf '%s\\n' \"$units\" | jq -r '.[]' 2>/dev/null | sed 's/^/- /' || echo \"- (all)\"\n")
	b.WriteString("          } >> \"$GITHUB_STEP_SUMMARY\"\n\n")

	// Render each unit job
	var jobNames []string
	for _, u := range orderedUnits {
		jobName := "unit-" + u.Name
		jobNames = append(jobNames, jobName)

		fmt.Fprintf(&b, "  %s:\n", jobName)
		fmt.Fprintf(&b, "    name: %s\n", u.Name)
		fmt.Fprintf(&b, "    runs-on: %s\n", u.Runner)
		fmt.Fprintf(&b, "    timeout-minutes: %d\n", u.TimeoutMinutes)

		needs := []string{"plan"}
		for _, d := range u.DependsOn {
			needs = append(needs, "unit-"+d)
		}
		fmt.Fprintf(&b, "    needs: [%s]\n", strings.Join(needs, ", "))

		// Run only when this change actually affects the unit.
		//
		// `always()` is required because an upstream unit may itself have been
		// skipped as unaffected, and a job whose needs were skipped is skipped
		// by default -- which would silently drop this one too. `!cancelled()`
		// keeps a cancelled run from resurrecting the whole matrix.
		//
		// `|| '[]'` guards fromJSON: if the plan job died before setting its
		// output the value is empty, and fromJSON('') is a hard expression
		// error that fails the job rather than skipping it. The first clause
		// then catches that case and runs the unit anyway -- fail open, never
		// fail quiet.
		fmt.Fprintf(&b, "    if: ${{ always() && !cancelled() && (needs.plan.result != 'success' || contains(fromJSON(needs.plan.outputs.units || '[]'), '%s')) }}\n", u.Name)

		b.WriteString("    env:\n")
		b.WriteString("      BUILDBUDDY_API_KEY: ${{ secrets.BUILDBUDDY_API_KEY }}\n")
		if len(u.Env) > 0 {
			// Sorted for the same reason as artifacts below: Go map order is
			// random and this file is diffed by tidy-check, so an unsorted
			// range regenerates differently every run.
			envKeys := make([]string, 0, len(u.Env))
			for k := range u.Env {
				envKeys = append(envKeys, k)
			}
			sort.Strings(envKeys)
			for _, k := range envKeys {
				fmt.Fprintf(&b, "      %s: %q\n", k, u.Env[k])
			}
		}

		b.WriteString("    steps:\n")
		b.WriteString("      - uses: actions/checkout@v7.0.1\n")
		b.WriteString("        with:\n")
		b.WriteString("          persist-credentials: false\n")
		b.WriteString("          fetch-depth: 0\n\n")

		if u.Runner != "macos-latest" {
			b.WriteString("      - name: Free up runner disk space\n")
			b.WriteString("        uses: ./.github/actions/free-disk-space\n\n")
		}

		b.WriteString("      - name: Set up Bazel\n")
		b.WriteString("        uses: ./.github/actions/setup-bazel\n\n")

		if u.Runner != "macos-latest" {
			b.WriteString("      - name: Restore the extracted LLVM toolchain\n")
			b.WriteString("        id: llvm-contents\n")
			b.WriteString("        uses: ./.github/actions/llvm-cache-restore\n\n")
		}

		// A unit that drives a device needs one booted before its targets run.
		// The composite action leaves adb on PATH and ANDROID_HOME/ANDROID_SERIAL
		// exported, which is what the --test_env flags below forward into the
		// test: Bazel scrubs the environment for tests, so without them the
		// test cannot find adb or the device.
		if u.NeedsEmulator {
			b.WriteString("      - name: Boot an Android emulator\n")
			b.WriteString("        uses: ./.github/actions/android-emulator\n\n")
		}

		fmt.Fprintf(&b, "      - name: Build & Test Unit %s\n", u.Name)
		b.WriteString("        run: |\n")
		b.WriteString("          set -euo pipefail\n")
		b.WriteString("          cache_flags=()\n")
		b.WriteString("          extra_flags=()\n")
		if u.Runner == "macos-latest" {
			b.WriteString("          extra_flags=(--config=macos-app)\n")
			b.WriteString("          if [ -n \"${BUILDBUDDY_API_KEY}\" ]; then\n")
			b.WriteString("            cache_flags=(--config=remotecache-ci \"--remote_header=x-buildbuddy-api-key=${BUILDBUDDY_API_KEY}\")\n")
			b.WriteString("          fi\n")
		} else if len(u.Artifacts) > 0 {
			// :remotecache-ci, not :remote, for a unit that publishes files.
			// :remote carries --remote_download_outputs=minimal, so on a cache
			// hit the outputs stay on the remote cache and never land in
			// bazel-bin -- the upload then finds nothing off a perfectly green
			// build. #1296 measured exactly that on the other artifact lanes,
			// and remote.bazelrc names :remotecache as the profile for lanes
			// that consume bazel-bin directly.
			b.WriteString("          if [ -n \"${BUILDBUDDY_API_KEY}\" ]; then\n")
			b.WriteString("            cache_flags=(--config=remotecache-ci \"--remote_header=x-buildbuddy-api-key=${BUILDBUDDY_API_KEY}\")\n")
			b.WriteString("          fi\n")
		} else {
			b.WriteString("          if [ -n \"${BUILDBUDDY_API_KEY}\" ]; then\n")
			b.WriteString("            cache_flags=(--config=remote \"--remote_header=x-buildbuddy-api-key=${BUILDBUDDY_API_KEY}\")\n")
			b.WriteString("          fi\n")
		}
		// A unit's own flags go last so they win over the shared configs above.
		//
		// Each flag is quoted individually: a value may legitimately contain a
		// comma (--fat_apk_cpu=arm64-v8a,x86_64), and unquoted that trips
		// shellcheck SC2054, which reads the comma as an array separator and
		// fails actionlint in CI.
		if len(u.BuildFlags) > 0 {
			quoted := make([]string, 0, len(u.BuildFlags))
			for _, f := range u.BuildFlags {
				quoted = append(quoted, strconv.Quote(f))
			}
			fmt.Fprintf(&b, "          extra_flags+=(%s)\n", strings.Join(quoted, " "))
		}
		if u.NeedsEmulator {
			// --test_output=all: a device test that fails is diagnosed from its
			// own log, and the default summary throws that away.
			b.WriteString("          extra_flags+=(--test_env=ANDROID_HOME --test_env=ANDROID_SERIAL --test_env=PATH --test_output=all)\n")
		}
		targetsStr := strings.Join(u.TestTargets, " ")
		fmt.Fprintf(&b, "          bazel test \"${extra_flags[@]}\" \"${cache_flags[@]}\" %s || { rc=$?; if [ $rc -eq 4 ]; then bazel build \"${extra_flags[@]}\" \"${cache_flags[@]}\" %s; else exit $rc; fi; }\n", targetsStr, targetsStr)

		// Artifacts are copied HERE, inside the build step, because the flags
		// above are what decide where Bazel writes: --android_platforms puts
		// outputs in a different bin directory than the default one, and the
		// `bazel-bin` symlink in the workspace does not point at it. Asking
		// `bazel info` with the same flags is the only reliable answer, and a
		// later step cannot -- shell variables do not survive between steps.
		//
		// cp -L because bazel-bin is a symlink into the output base, which on
		// CI lives outside the checkout, where upload-artifact will not follow.
		if len(u.Artifacts) > 0 {
			stage := make([]string, 0, len(u.Artifacts))
			for n := range u.Artifacts {
				stage = append(stage, n)
			}
			sort.Strings(stage)
			b.WriteString("          bin=$(bazel info \"${extra_flags[@]}\" \"${cache_flags[@]}\" bazel-bin)\n")
			for _, n := range stage {
				fmt.Fprintf(&b, "          mkdir -p .pipeline-artifacts/%s\n", n)
				fmt.Fprintf(&b, "          cp -L \"$bin/%s\" .pipeline-artifacts/%s/\n", u.Artifacts[n], n)
			}
		}
		b.WriteString("\n")

		// Artifacts upload after the targets and before the tripwire. Sorted
		// because Go map order is random and this file is diffed by tidy-check:
		// an unsorted range would regenerate differently every run and fail a
		// check that has nothing to do with what changed.
		if len(u.Artifacts) > 0 {
			names := make([]string, 0, len(u.Artifacts))
			for n := range u.Artifacts {
				names = append(names, n)
			}
			sort.Strings(names)
			for _, n := range names {
				fmt.Fprintf(&b, "      - name: Upload %s\n", n)
				// success() only: an artifact salvaged from a failed build is
				// worse than no artifact, because it still looks installable.
				b.WriteString("        if: success()\n")
				b.WriteString("        uses: actions/upload-artifact@v7\n")
				b.WriteString("        with:\n")
				fmt.Fprintf(&b, "          name: %s\n", n)
				fmt.Fprintf(&b, "          path: .pipeline-artifacts/%s\n", n)
				b.WriteString("          if-no-files-found: error\n\n")
			}
		}

		if u.Runner != "macos-latest" {
			b.WriteString("      - name: LLVM cache tripwire\n")
			b.WriteString("        if: always()\n")
			b.WriteString("        uses: ./.github/actions/llvm-cache-tripwire\n")
			b.WriteString("        with:\n")
			b.WriteString("          restore-outcome: ${{ steps.llvm-contents.outputs.outcome }}\n")
			b.WriteString("          cache-hit: ${{ steps.llvm-contents.outputs.cache-hit }}\n")
			b.WriteString("          pre-count: ${{ steps.llvm-contents.outputs.pre-count }}\n")
			b.WriteString("          pin-path: ${{ steps.llvm-contents.outputs.pin-path }}\n\n")
		}
	}

	// Render Gate Aggregator job
	// On every push to main, compute the dependency map for that commit and
	// save it for the PRs that will be based on it. Off the critical path:
	// nothing needs this job, and a failure only means those PRs query live.
	b.WriteString("  rdeps-map:\n")
	b.WriteString("    name: plan/rdeps-map\n")
	b.WriteString("    if: ${{ github.event_name == 'push' && github.ref == 'refs/heads/main' }}\n")
	b.WriteString("    runs-on: ubuntu-26.04\n")
	b.WriteString("    timeout-minutes: 45\n")
	b.WriteString("    env:\n")
	b.WriteString("      BUILDBUDDY_API_KEY: ${{ secrets.BUILDBUDDY_API_KEY }}\n")
	b.WriteString("    steps:\n")
	b.WriteString("      - uses: actions/checkout@v7.0.1\n")
	b.WriteString("        with:\n")
	b.WriteString("          persist-credentials: false\n\n")
	b.WriteString("      - name: Free up runner disk space\n")
	b.WriteString("        uses: ./.github/actions/free-disk-space\n\n")
	b.WriteString("      - name: Set up Bazel\n")
	b.WriteString("        uses: ./.github/actions/setup-bazel\n\n")
	b.WriteString("      - name: Compute the dependency map for this commit\n")
	b.WriteString("        run: bazel run //tools/pipeline:plan -- --emit-rdeps-map=\"$RUNNER_TEMP/pipeline-rdeps-map.json\" --repo-root=\"$PWD\" --timeout-sec=2100\n\n")
	b.WriteString("      - name: Save it for PRs based on this commit\n")
	b.WriteString("        uses: actions/cache/save@55cc8345863c7cc4c66a329aec7e433d2d1c52a9 # v6\n")
	b.WriteString("        with:\n")
	b.WriteString("          path: ${{ runner.temp }}/pipeline-rdeps-map.json\n")
	b.WriteString("          key: pipeline-rdeps-map-v1-${{ github.sha }}\n\n")
	b.WriteString("  gate:\n")
	b.WriteString("    name: gate/all-required-passed\n")
	fmt.Fprintf(&b, "    needs: [%s]\n", strings.Join(append([]string{"plan"}, jobNames...), ", "))
	b.WriteString("    if: always()\n")
	b.WriteString("    runs-on: ubuntu-26.04\n")
	b.WriteString("    timeout-minutes: 5\n")
	b.WriteString("    steps:\n")
	b.WriteString("      - name: Evaluate Monorepo Gate Verdict\n")
	// toJSON(needs) is the only way a fan-in job can see its upstreams'
	// results. Passed as env rather than interpolated into the script body so
	// a job name can never be read as shell.
	b.WriteString("        env:\n")
	b.WriteString("          NEEDS_JSON: ${{ toJSON(needs) }}\n")
	b.WriteString("        run: |\n")
	b.WriteString("          set -euo pipefail\n")
	b.WriteString("          # `if: always()` makes this job run even when an upstream unit\n")
	b.WriteString("          # failed, so the job's own success says NOTHING about theirs --\n")
	b.WriteString("          # it has to read their results and decide. Skipping that check is\n")
	b.WriteString("          # what let runs 34012010463 (2 units red) and 34010090082 (7 units\n")
	b.WriteString("          # red) report this required gate green.\n")
	b.WriteString("          echo \"$NEEDS_JSON\" | jq -r 'to_entries[] | \"\\(.value.result)\\t\\(.key)\"' | sort\n")
	b.WriteString("          count=$(echo \"$NEEDS_JSON\" | jq -r 'length')\n")
	b.WriteString("          if [ \"$count\" -eq 0 ]; then\n")
	b.WriteString("            echo \"::error::Gate has no upstream units. Failing closed.\"\n")
	b.WriteString("            exit 1\n")
	b.WriteString("          fi\n")
	b.WriteString("          # success and skipped pass; failure, cancelled and anything a\n")
	b.WriteString("          # future GitHub adds do not. Allowlist, not denylist.\n")
	b.WriteString("          bad=$(echo \"$NEEDS_JSON\" | jq -r 'to_entries[] | select(.value.result != \"success\" and .value.result != \"skipped\") | \"\\(.key)=\\(.value.result)\"')\n")
	b.WriteString("          if [ -n \"$bad\" ]; then\n")
	b.WriteString("            echo \"::error::Pipeline units did not pass: $(echo \"$bad\" | tr '\\n' ' ')\"\n")
	b.WriteString("            exit 1\n")
	b.WriteString("          fi\n")
	b.WriteString("          echo \"✓ All $count pipeline units in DAG completed successfully.\"\n")

	return b.String(), nil
}
