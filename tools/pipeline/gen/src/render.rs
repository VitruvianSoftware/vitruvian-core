/// The condition on every step that only feeds the planner.
const PLAN_NEEDED: &str = "steps.release.outputs.skip != 'true' && steps.queued.outputs.verdict != 'hit' && steps.fastlane.outputs.verdict != 'fast'";

/// Why rendering stopped: a DAG error is reported, an action-pin problem is
/// what the Go tool panicked with.
#[derive(Debug, PartialEq)]
pub enum RenderError {
    Dag(String),
    Panic(String),
}

/// Whether a runner label is a macOS machine ("xcode-27" as well as
/// "macos-*").
pub fn is_mac_runner(runner: &str) -> bool {
    runner.starts_with("macos") || runner.starts_with("xcode")
}

/// Go's `RenderPresubmitWorkflow`. `load_pins` is called once, after the DAG
/// is known to be valid, as the Go tool loaded its pin manifest lazily.
pub fn render_presubmit_workflow(
    units: &[Unit],
    load_pins: &mut dyn FnMut() -> Result<Pins, String>,
) -> Result<String, RenderError> {
    let dag = build_dag(units).map_err(RenderError::Dag)?;
    let ordered_units = dag.topological_order().map_err(RenderError::Dag)?;
    let pins =
        load_pins().map_err(|e| RenderError::Panic(format!("{e} [recovered, repanicked]")))?;
    let pin = |action: &str| pins.lookup(action).map_err(RenderError::Panic);

    let mut b = String::with_capacity(64 * 1024);
    b.push_str(MIT_LICENSE_HEADER);
    b.push_str("\n\n");
    b.push_str(GENERATED_BANNER);
    b.push_str("\n\n");

    b.push_str("name: Presubmit\n\n");
    b.push_str("on:\n");
    b.push_str("  pull_request:\n");
    b.push_str("  merge_group:\n");
    b.push_str("  push:\n");
    b.push_str("    branches: [main]\n\n");

    b.push_str("concurrency:\n");
    b.push_str("  group: presubmit-${{ github.workflow }}-${{ github.event_name }}-${{ github.event_name == 'pull_request' && github.ref || github.sha }}\n");
    b.push_str("  cancel-in-progress: ${{ github.event_name == 'pull_request' }}\n\n");

    b.push_str("permissions:\n");
    b.push_str("  contents: read\n\n");

    b.push_str("jobs:\n");

    // Every unit name, as a JSON array literal. This is the fail-safe: if the
    // planner cannot answer, the plan job emits this and everything runs, which
    // is exactly the behaviour before any of this existed.
    let mut all_names: Vec<String> = Vec::with_capacity(ordered_units.len());
    for u in &ordered_units {
        all_names.push(quote(&u.name));
    }
    let all_names_json = format!("[{}]", all_names.join(","));

    // Render the plan job: works out which units this change actually affects.
    //
    // Fails OPEN, deliberately. Every failure path here -- planner crash, no
    // output, malformed output -- emits the full unit list, so a broken planner
    // costs compute rather than test coverage.
    // The condition on every step that only feeds the planner: skipped for a
    // release-bot PR, for a push the merge queue already passed, and for an
    // agent PR in the fast lane.

    b.push_str("  plan:\n");
    b.push_str("    name: plan/affected-units\n");
    b.push_str("    runs-on: ubuntu-26.04\n");
    // 35, not 20: building the planner takes ~5 min on a cold runner and the
    // query below is allowed 15 (see --timeout-sec), plus checkout and setup.
    b.push_str("    timeout-minutes: 35\n");
    b.push_str("    outputs:\n");
    b.push_str("      units: ${{ steps.plan.outputs.units }}\n");
    b.push_str("      degraded: ${{ steps.plan.outputs.degraded }}\n");
    b.push_str("      tree: ${{ steps.fastpass.outputs.tree }}\n");
    // actions: read lets the step below list artifacts; nothing here writes.
    b.push_str("    permissions:\n");
    b.push_str("      contents: read\n");
    b.push_str("      actions: read\n");
    b.push_str("    env:\n");
    b.push_str("      BUILDBUDDY_API_KEY: ${{ secrets.BUILDBUDDY_API_KEY }}\n");
    b.push_str("    steps:\n");
    b.push_str("      - uses: ");
    b.push_str(&pin("actions/checkout")?);
    b.push('\n');
    b.push_str("        with:\n");
    b.push_str("          persist-credentials: false\n");
    // The diff needs real history; a shallow clone cannot see the base.
    b.push_str("          fetch-depth: 0\n\n");
    // A release-bot PR plans NO units on the pull request. It only bumps
    // versions and the changelog of code main already tested, and the merge
    // queue plans and runs this workflow in full on the exact commit that
    // lands, so the PR-side run was the same work done twice (~11 min median
    // on release PRs, 2026-09-14..10-14). Only the bot's own same-repo
    // release-please branches qualify; merge_group and push are untouched.
    // Every step below that only feeds the planner is skipped with it, and so
    // is the fast-pass tree, so no "this code passed" record is written for a
    // run that tested nothing.
    b.push_str("      - name: Is this a release-bot pull request?\n");
    b.push_str("        id: release\n");
    b.push_str("        env:\n");
    b.push_str("          RELEASE_PR: ${{ github.event_name == 'pull_request' && startsWith(github.head_ref, 'release-please--') && github.event.pull_request.user.type == 'Bot' && github.event.pull_request.head.repo.full_name == github.repository }}\n");
    b.push_str("        run: echo \"skip=$RELEASE_PR\" | tee -a \"$GITHUB_OUTPUT\"\n\n");
    // A push to main plans NO units when the merge queue already passed this
    // workflow on the exact code that landed (#3418). The queue squash-merges,
    // so main's commit has the tree its merge_group run tested, and the
    // re-test could only repeat that answer or trip over a flaky test. Any
    // doubt -- a direct push, a red or missing queue run, a lookup error, a
    // change to a file the main-only Actions caches are keyed on -- is a miss,
    // and a miss plans as before. continue-on-error: a broken lookup must never
    // cost a plan. The rdeps-map job does not read this and still runs on
    // every push, so planning for later PRs keeps its dependency map.
    b.push_str("      - name: Did the merge queue already pass this exact code?\n");
    b.push_str("        id: queued\n");
    b.push_str("        if: github.event_name == 'push' && github.ref == 'refs/heads/main'\n");
    b.push_str("        continue-on-error: true\n");
    b.push_str("        env:\n");
    b.push_str("          GH_TOKEN: ${{ github.token }}\n");
    b.push_str("          WORKFLOW_PATH: .github/workflows/presubmit.yaml\n");
    b.push_str("          PUSH_BEFORE: ${{ github.event.before }}\n");
    b.push_str("          FORCED_PUSH: ${{ github.event.forced }}\n");
    b.push_str("        run: |\n");
    b.push_str(
        "          bash tools/ci/queue-fast-pass.sh queued | tee \"$RUNNER_TEMP/queued.out\"\n",
    );
    b.push_str("          {\n");
    b.push_str("            echo \"### Already passed in the merge queue?\"\n");
    b.push_str("            echo \"\"\n");
    b.push_str(
        "            echo \"- verdict: $(sed -n 's/^verdict=//p' \"$RUNNER_TEMP/queued.out\")\"\n",
    );
    b.push_str(
        "            echo \"- why: $(sed -n 's/^reason=//p' \"$RUNNER_TEMP/queued.out\")\"\n",
    );
    b.push_str("          } >> \"$GITHUB_STEP_SUMMARY\"\n\n");
    // LOG ONLY (#2841). In the merge queue, ask whether a pull-request run
    // already passed this workflow on these exact files, and say so in the
    // job summary. Nothing reads the verdict yet: every unit still runs. On a
    // pull request it only reports the tree hash, which the gate uses to
    // name its "passed" marker. continue-on-error: a broken lookup must
    // never cost a plan.
    // An agent PR in the fast lane plans NO units on the pull request (#3418,
    // Step 2b): a PR from a branch in this repository, opened by one of our
    // agent apps (by bot user id), with the agent-fast-lane label. The merge
    // queue still plans and runs every unit on the exact code that lands. The
    // fast checks are other workflows and never see this. The script and the
    // agent roster are read from the BASE commit, so a PR cannot rewrite the
    // rule that lets it skip; on a base that has no script yet, nothing is
    // decided and every unit runs. An unlabelled PR skips the step, so it
    // costs nothing there. Skipping the fast-pass step with the planner keeps
    // the gate from recording "this exact code passed" for a run that tested
    // nothing.
    b.push_str("      - name: Is this an agent PR in the fast lane?\n");
    b.push_str("        id: fastlane\n");
    b.push_str("        if: github.event_name == 'pull_request' && contains(github.event.pull_request.labels.*.name, 'agent-fast-lane')\n");
    b.push_str("        continue-on-error: true\n");
    b.push_str("        env:\n");
    b.push_str("          EVENT_NAME: ${{ github.event_name }}\n");
    b.push_str("          PR_BASE_SHA: ${{ github.event.pull_request.base.sha }}\n");
    b.push_str("          PR_HEAD_REPO: ${{ github.event.pull_request.head.repo.full_name }}\n");
    b.push_str("          PR_AUTHOR_ID: ${{ github.event.pull_request.user.id }}\n");
    b.push_str("          PR_AUTHOR_TYPE: ${{ github.event.pull_request.user.type }}\n");
    b.push_str("          PR_LABELS: ${{ toJSON(github.event.pull_request.labels.*.name) }}\n");
    b.push_str("        run: |\n");
    b.push_str("          if ! git show \"$PR_BASE_SHA:tools/ci/agent-fast-lane.sh\" > \"$RUNNER_TEMP/agent-fast-lane.sh\" ||\n");
    b.push_str("             ! git show \"$PR_BASE_SHA:tools/agent-app/agents.tsv\" > \"$RUNNER_TEMP/agents.tsv\"; then\n");
    b.push_str("            echo \"::notice::The base commit has no fast-lane rule yet; every unit runs.\"\n");
    b.push_str("            exit 0\n");
    b.push_str("          fi\n");
    b.push_str("          AGENTS_TSV=\"$RUNNER_TEMP/agents.tsv\" bash \"$RUNNER_TEMP/agent-fast-lane.sh\" | tee \"$RUNNER_TEMP/fast-lane.out\"\n");
    b.push_str("          {\n");
    b.push_str("            echo \"### Agent fast lane?\"\n");
    b.push_str("            echo \"\"\n");
    b.push_str("            echo \"- verdict: $(sed -n 's/^verdict=//p' \"$RUNNER_TEMP/fast-lane.out\")\"\n");
    b.push_str(
        "            echo \"- why: $(sed -n 's/^reason=//p' \"$RUNNER_TEMP/fast-lane.out\")\"\n",
    );
    b.push_str("          } >> \"$GITHUB_STEP_SUMMARY\"\n\n");
    b.push_str("      - name: Has this exact code already passed? (log only)\n");
    b.push_str("        id: fastpass\n");
    b.push_str("        if: ");
    b.push_str(PLAN_NEEDED);
    b.push('\n');
    b.push_str("        continue-on-error: true\n");
    b.push_str("        env:\n");
    b.push_str("          GH_TOKEN: ${{ github.token }}\n");
    b.push_str("          EVENT_NAME: ${{ github.event_name }}\n");
    b.push_str("          WORKFLOW_PATH: .github/workflows/presubmit.yaml\n");
    b.push_str("        run: |\n");
    b.push_str("          if [ \"$EVENT_NAME\" != merge_group ]; then\n");
    b.push_str("            bash tools/ci/queue-fast-pass.sh tree\n");
    b.push_str("            exit 0\n");
    b.push_str("          fi\n");
    b.push_str("          bash tools/ci/queue-fast-pass.sh lookup presubmit | tee \"$RUNNER_TEMP/fastpass.out\"\n");
    b.push_str("          {\n");
    b.push_str("            echo \"### Already tested? (log only, nothing is skipped)\"\n");
    b.push_str("            echo \"\"\n");
    b.push_str("            echo \"- verdict: $(sed -n 's/^verdict=//p' \"$RUNNER_TEMP/fastpass.out\")\"\n");
    b.push_str(
        "            echo \"- why: $(sed -n 's/^reason=//p' \"$RUNNER_TEMP/fastpass.out\")\"\n",
    );
    b.push_str("          } >> \"$GITHUB_STEP_SUMMARY\"\n\n");
    b.push_str("      - name: Free up runner disk space\n");
    b.push_str("        if: ");
    b.push_str(PLAN_NEEDED);
    b.push('\n');
    b.push_str("        uses: ./.github/actions/free-disk-space\n\n");
    b.push_str("      - name: Set up Bazel\n");
    b.push_str("        if: ");
    b.push_str(PLAN_NEEDED);
    b.push('\n');
    b.push_str("        uses: ./.github/actions/setup-bazel\n\n");
    b.push_str("      - name: Restore the extracted LLVM toolchain\n");
    b.push_str("        id: llvm-contents\n");
    b.push_str("        if: ");
    b.push_str(PLAN_NEEDED);
    b.push('\n');
    b.push_str("        uses: ./.github/actions/llvm-cache-restore\n");
    b.push_str("        with:\n");
    b.push_str("          restore-only: \"true\"\n\n");
    // The map for a commit is saved 16-39 min after it lands, later than the
    // next merge-queue entry needs it (#2841), so the exact key missed in 8 of
    // 9 queue runs. Offer the base's recent ancestors as fallbacks, nearest
    // first; the planner (--rdeps-map-max-behind) decides whether an older map
    // is safe and plans against its commit. actions/cache allows 10 keys in
    // all: the exact one plus 9 here.
    // First choice: the map kept under a git ref (tools/ci/rdeps-map-ref.sh).
    // The Actions cache below evicts maps within the hour while the repo is
    // over its 10 GiB budget (#2841); a ref is never evicted. The cache steps
    // stay as the fallback, so nothing is lost if the ref is not there.
    b.push_str("      - name: Fetch the dependency map kept under a git ref\n");
    b.push_str("        id: mapref\n");
    b.push_str("        if: ");
    b.push_str(PLAN_NEEDED);
    b.push('\n');
    b.push_str("        continue-on-error: true\n");
    b.push_str("        env:\n");
    b.push_str("          BASE_SHA: ${{ github.event.pull_request.base.sha || github.event.merge_group.base_sha || github.event.before }}\n");
    b.push_str("          GH_TOKEN: ${{ github.token }}\n");
    b.push_str("        run: bash tools/ci/rdeps-map-ref.sh fetch \"$RUNNER_TEMP/pipeline-rdeps-map.json\" \"$BASE_SHA\"\n\n");
    b.push_str("      - name: List recent ancestors of the diff base\n");
    b.push_str("        id: mapkeys\n");
    b.push_str("        if: ");
    b.push_str(PLAN_NEEDED);
    b.push('\n');
    b.push_str("        env:\n");
    b.push_str("          BASE_SHA: ${{ github.event.pull_request.base.sha || github.event.merge_group.base_sha || github.event.before }}\n");
    b.push_str("        run: |\n");
    b.push_str("          keys=\"\"\n");
    b.push_str("          if [ -n \"$BASE_SHA\" ] && git rev-parse --verify --quiet \"${BASE_SHA}^{commit}\" >/dev/null; then\n");
    b.push_str("            keys=\"$(git rev-list --first-parent -n 10 \"$BASE_SHA\" | tail -n +2 | sed 's/^/pipeline-rdeps-map-v1-/')\"\n");
    b.push_str("          fi\n");
    b.push_str("          {\n");
    b.push_str("            echo \"fallback_keys<<FALLBACK_KEYS_EOF\"\n");
    b.push_str("            echo \"$keys\"\n");
    b.push_str("            echo \"FALLBACK_KEYS_EOF\"\n");
    b.push_str("          } >> \"$GITHUB_OUTPUT\"\n\n");
    // continue-on-error: the map is only ever a speed-up, so a cache problem
    // must not fail the plan; the planner copes with having no map.
    b.push_str("      - name: Restore the dependency map for the diff base\n");
    b.push_str("        if: ");
    b.push_str(PLAN_NEEDED);
    b.push_str(" && steps.mapref.outputs.commit == ''\n");
    b.push_str("        continue-on-error: true\n");
    b.push_str("        uses: ");
    b.push_str(&pin("actions/cache/restore")?);
    b.push('\n');
    b.push_str("        with:\n");
    b.push_str("          path: ${{ runner.temp }}/pipeline-rdeps-map.json\n");
    b.push_str("          key: pipeline-rdeps-map-v1-${{ github.event.pull_request.base.sha || github.event.merge_group.base_sha || github.event.before }}\n");
    b.push_str("          restore-keys: ${{ steps.mapkeys.outputs.fallback_keys }}\n\n");
    b.push_str("      - name: Work out which units this change affects\n");
    b.push_str("        id: plan\n");
    // SHAs come from the event payload, so they go through env rather than
    // being interpolated into the script body.
    b.push_str("        env:\n");
    b.push_str("          EVENT_NAME: ${{ github.event_name }}\n");
    b.push_str("          PR_BASE_SHA: ${{ github.event.pull_request.base.sha }}\n");
    b.push_str("          MQ_BASE_SHA: ${{ github.event.merge_group.base_sha }}\n");
    b.push_str("          PUSH_BEFORE: ${{ github.event.before }}\n");
    b.push_str("          RELEASE_SKIP: ${{ steps.release.outputs.skip }}\n");
    b.push_str("          QUEUED: ${{ steps.queued.outputs.verdict }}\n");
    b.push_str("          QUEUED_RUN: ${{ steps.queued.outputs.run }}\n");
    b.push_str("          FAST_LANE: ${{ steps.fastlane.outputs.verdict }}\n");
    b.push_str(&format!("          ALL_UNITS: '{all_names_json}'\n"));
    b.push_str("        run: |\n");
    // `set +e` is load-bearing and easy to lose. GitHub runs `run:` steps as
    // `bash -e -o pipefail`, so errexit is ALREADY ON before this script starts
    // -- writing `set -uo pipefail` does not turn it off, and every fail-open
    // branch below becomes unreachable: the step dies on the first non-zero
    // exit with none of its warnings printed. That is exactly what happened on
    // the first run of this job (3m18s of silence, then exit 1).
    b.push_str("          set +e -u -o pipefail\n");
    b.push_str("          if [ \"$RELEASE_SKIP\" = \"true\" ]; then\n");
    b.push_str("            echo \"Release-bot PR: no units run here; the merge queue runs them on the commit that lands.\"\n");
    b.push_str("            echo \"units=[]\" >> \"$GITHUB_OUTPUT\"\n");
    b.push_str("            echo \"degraded=false\" >> \"$GITHUB_OUTPUT\"\n");
    b.push_str("            printf '### Affected units\\n\\nRelease-bot PR: none on the pull request. The merge queue tests the exact commit that lands.\\n' >> \"$GITHUB_STEP_SUMMARY\"\n");
    b.push_str("            exit 0\n");
    b.push_str("          fi\n");
    b.push_str("          if [ \"$FAST_LANE\" = \"fast\" ]; then\n");
    b.push_str("            echo \"Agent PR in the fast lane: no units run here; the merge queue runs them on the commit that lands.\"\n");
    b.push_str("            echo \"units=[]\" >> \"$GITHUB_OUTPUT\"\n");
    b.push_str("            echo \"degraded=false\" >> \"$GITHUB_OUTPUT\"\n");
    b.push_str("            printf '### Affected units\\n\\nAgent PR in the fast lane: none on the pull request. The merge queue tests the exact commit that lands.\\n' >> \"$GITHUB_STEP_SUMMARY\"\n");
    b.push_str("            exit 0\n");
    b.push_str("          fi\n");
    b.push_str("          if [ \"$QUEUED\" = \"hit\" ]; then\n");
    b.push_str("            echo \"The merge queue already passed this exact code in run $QUEUED_RUN; no units run again on main.\"\n");
    b.push_str("            echo \"units=[]\" >> \"$GITHUB_OUTPUT\"\n");
    b.push_str("            echo \"degraded=false\" >> \"$GITHUB_OUTPUT\"\n");
    b.push_str("            printf '### Affected units\\n\\nNone on main: merge queue run %s already passed this exact code.\\n' \"$QUEUED_RUN\" >> \"$GITHUB_STEP_SUMMARY\"\n");
    b.push_str("            exit 0\n");
    b.push_str("          fi\n");
    b.push_str("          case \"$EVENT_NAME\" in\n");
    b.push_str("            pull_request) base=\"$PR_BASE_SHA\" ;;\n");
    b.push_str("            merge_group)  base=\"$MQ_BASE_SHA\" ;;\n");
    b.push_str("            push)         base=\"$PUSH_BEFORE\" ;;\n");
    b.push_str("            *)            base=\"\" ;;\n");
    b.push_str("          esac\n");
    b.push_str("          units=\"$ALL_UNITS\"\n");
    b.push_str("          degraded=unknown\n");
    b.push_str("          if [ -z \"$base\" ]; then\n");
    b.push_str("            echo \"::warning::No diff base for event '$EVENT_NAME'; running every unit.\"\n");
    b.push_str("          else\n");
    // Built to a standalone binary with `bazel build` (--config=remotecache-ci)
    // before invoking the planner so the Bazel server lock is released before
    // the planner spawns `bazel query` on a dependency-map miss. A build
    // failure fails open like any other planner failure. stderr goes to a file
    // rather than /dev/null so a failure here is diagnosable instead of three
    // silent minutes.
    //
    // --head=HEAD is load-bearing. Without it the planner diffs the base
    // against the WORKING TREE, and `bazel run` itself rewrites
    // MODULE.bazel.lock on a Linux runner whenever an os_dependent module
    // extension has no linux entry committed (tools/android_ndk, since #2414).
    // The dirty lockfile then reads as a global-impact change and every unit
    // runs on every diff, silently -- a genuine global change, not a degraded
    // plan, so no warning fires. Diff the commit, not the checkout.
    b.push_str("            planner=\"$RUNNER_TEMP/pipeline-plan\"\n");
    b.push_str("            cache_flags=()\n");
    b.push_str("            if [ -n \"${BUILDBUDDY_API_KEY:-}\" ]; then\n");
    b.push_str("              cache_flags=(--config=remotecache-ci \"--remote_header=x-buildbuddy-api-key=${BUILDBUDDY_API_KEY}\")\n");
    b.push_str("            fi\n");
    b.push_str("            if ! (bazel build \"${cache_flags[@]}\" //tools/pipeline/plan && cp -f bazel-bin/tools/pipeline/plan/plan \"$planner\" && chmod +x \"$planner\") 2>/tmp/plan-build.err; then\n");
    b.push_str(
        "              echo \"::warning::Could not build the planner; running every unit.\"\n",
    );
    b.push_str("              tail -n 30 /tmp/plan-build.err || true\n");
    b.push_str("            fi\n");
    b.push_str("            out=\"$(\"$planner\" \\\n");
    //
    // --timeout-sec=900: on a cold runner the rdeps query loads ~8,400
    // external repos and took 6-10 min (#2465). At the planner's 300s default
    // it timed out about half the time and every unit ran. Waiting longer for
    // a precise answer is cheaper than building all 20 units. A stopgap until
    // PR plans stop running the query live.
    b.push_str("                     --base=\"$base\" --head=HEAD --event=\"$EVENT_NAME\" --timeout-sec=900 \\\n");
    b.push_str("                     --rdeps-map=\"$RUNNER_TEMP/pipeline-rdeps-map.json\" --rdeps-map-max-behind=9 \\\n");
    b.push_str(
        "                     --format=github-matrix --repo-root=\"$PWD\" 2>/tmp/plan.err)\"\n",
    );
    b.push_str("            rc=$?\n");
    b.push_str("            if [ \"$rc\" -ne 0 ]; then\n");
    b.push_str(
        "              echo \"::warning::Planner exited $rc; running every unit. Last lines:\"\n",
    );
    b.push_str("              tail -n 30 /tmp/plan.err || true\n");
    b.push_str("            fi\n");
    b.push_str("            matrix=\"$(printf '%s\\n' \"$out\" | grep '^matrix=' | sed 's/^matrix=//')\"\n");
    b.push_str("            degraded=\"$(printf '%s\\n' \"$out\" | grep '^is_degraded=' | sed 's/^is_degraded=//')\"\n");
    b.push_str("            if [ -n \"$matrix\" ] && parsed=\"$(printf '%s' \"$matrix\" | jq -c '[.[].name]' 2>/dev/null)\"; then\n");
    b.push_str("              units=\"$parsed\"\n");
    b.push_str("            else\n");
    b.push_str("              echo \"::warning::Could not read an affected-unit list; running every unit.\"\n");
    b.push_str("              units=\"$ALL_UNITS\"\n");
    b.push_str("            fi\n");
    b.push_str("          fi\n");
    // Unanchored: bazel run prefixes stderr lines with terminal control
    // codes, so a ^-anchored match never fires.
    // Say where the answer came from, so a map that is never used (or a
    // live query that keeps running) is visible rather than silently slow.
    b.push_str("          echo \"plan source: $(printf '%s\\n' \"${out:-}\" | sed -n 's/^plan_source=//p')\"\n");
    b.push_str("          grep -E '(no dependency map for|dependency map not used|note: dependency map)' /tmp/plan.err 2>/dev/null || true\n");
    b.push_str("          echo \"affected units: $units\"\n");
    b.push_str("          echo \"units=$units\" >> \"$GITHUB_OUTPUT\"\n");
    b.push_str("          echo \"degraded=$degraded\" >> \"$GITHUB_OUTPUT\"\n");
    // A degraded plan is CORRECT but expensive, and the whole reason the
    // planner reports it separately from a genuine global change is so it
    // cannot hide. Capturing the flag and never printing it is the same
    // silence in a different place: a 15s default timeout once made every
    // plan a full sweep for months precisely because nothing said so.
    b.push_str("          if [ \"$degraded\" = \"true\" ]; then\n");
    b.push_str("            echo \"::warning::Affected-target analysis DEGRADED: could not work out what changed, so every unit is running. Safe but wasteful -- see the planner output below for the cause.\"\n");
    // The warning used to say "see the planner output above", but on exit 0
    // that output was never printed: it sat in /tmp/plan.err. The degraded
    // reason (a timed-out or failed query) is only in stderr, so show it.
    // The planner's own warning line carries the reason; echoing it turns it
    // into an annotation. Fall back to the raw tail if it is missing.
    b.push_str("            grep -m1 -A15 '^::warning title=Affected-target analysis degraded' /tmp/plan.err || tail -n 30 /tmp/plan.err || true\n");
    b.push_str("          fi\n");
    b.push_str("          {\n");
    b.push_str("            echo \"### Affected units\"\n");
    b.push_str("            echo \"\"\n");
    b.push_str("            if [ \"$degraded\" = \"true\" ]; then\n");
    b.push_str("              echo \"> **Degraded plan.** The affected-target query failed, so every unit is running. This is safe but wastes CI time; fix the cause rather than paying for it.\"\n");
    b.push_str("              echo \"\"\n");
    b.push_str("            fi\n");
    b.push_str("            printf '%s\\n' \"$units\" | jq -r '.[]' 2>/dev/null | sed 's/^/- /' || echo \"- (all)\"\n");
    b.push_str("          } >> \"$GITHUB_STEP_SUMMARY\"\n\n");

    // Render each unit job
    let mut job_names: Vec<String> = Vec::new();
    for u in &ordered_units {
        let job_name = format!("unit-{}", u.name);
        job_names.push(job_name.clone());

        b.push_str(&format!("  {job_name}:\n"));
        b.push_str(&format!("    name: {}\n", u.name));
        b.push_str(&format!("    runs-on: {}\n", u.runner));
        b.push_str(&format!("    timeout-minutes: {}\n", u.timeout_minutes));

        let mut needs: Vec<String> = vec!["plan".to_string()];
        for d in &u.depends_on {
            needs.push(format!("unit-{d}"));
        }
        b.push_str(&format!("    needs: [{}]\n", needs.join(", ")));

        // Run only when this change actually affects the unit.
        //
        // `always()` is required because an upstream unit may itself have been
        // skipped as unaffected, and a job whose needs were skipped is skipped
        // by default -- which would silently drop this one too. `!cancelled()`
        // keeps a cancelled run from resurrecting the whole matrix.
        //
        // `|| '[]'` guards fromJSON: if the plan job died before setting its
        // output the value is empty, and fromJSON('') is a hard expression
        // error that fails the job rather than skipping it. The first clause
        // then catches that case and runs the unit anyway -- fail open, never
        // fail quiet.
        b.push_str("    if: ${{ always() && !cancelled() && (needs.plan.result != 'success' || contains(fromJSON(needs.plan.outputs.units || '[]'), '");
        b.push_str(&u.name);
        b.push_str("')) }}\n");

        b.push_str("    env:\n");
        b.push_str("      BUILDBUDDY_API_KEY: ${{ secrets.BUILDBUDDY_API_KEY }}\n");
        if !u.env.is_empty() {
            // Sorted for the same reason as artifacts below: Go map order is
            // random and this file is diffed by tidy-check, so an unsorted
            // range regenerates differently every run.
            {}
            for (k, v) in &u.env {
                b.push_str(&format!("      {k}: {}\n", quote(v)));
            }
        }

        b.push_str("    steps:\n");
        b.push_str("      - uses: ");
        b.push_str(&pin("actions/checkout")?);
        b.push('\n');
        b.push_str("        with:\n");
        b.push_str("          persist-credentials: false\n");
        b.push_str("          fetch-depth: 0\n\n");

        if !is_mac_runner(&u.runner) {
            b.push_str("      - name: Free up runner disk space\n");
            b.push_str("        uses: ./.github/actions/free-disk-space\n\n");
        }

        if is_mac_runner(&u.runner) {
            b.push_str("      - name: Select the pinned Xcode\n");
            b.push_str("        uses: ./.github/actions/select-xcode\n\n");
        }

        b.push_str("      - name: Set up Bazel\n");
        b.push_str("        uses: ./.github/actions/setup-bazel\n\n");

        if !is_mac_runner(&u.runner) {
            b.push_str("      - name: Restore the extracted LLVM toolchain\n");
            b.push_str("        id: llvm-contents\n");
            b.push_str("        uses: ./.github/actions/llvm-cache-restore\n\n");
        }

        // A unit that drives a device needs one booted before its targets run.
        // The composite action leaves adb on PATH and ANDROID_HOME/ANDROID_SERIAL
        // exported, which is what the --test_env flags below forward into the
        // test: Bazel scrubs the environment for tests, so without them the
        // test cannot find adb or the device.
        if u.needs_emulator {
            b.push_str("      - name: Boot an Android emulator\n");
            b.push_str("        uses: ./.github/actions/android-emulator\n\n");
        }

        b.push_str(&format!("      - name: Build & Test Unit {}\n", u.name));
        b.push_str("        run: |\n");
        b.push_str("          set -euo pipefail\n");
        b.push_str("          cache_flags=()\n");
        b.push_str("          extra_flags=()\n");
        if is_mac_runner(&u.runner) {
            b.push_str("          extra_flags=(--config=macos-app)\n");
            b.push_str("          if [ -n \"${BUILDBUDDY_API_KEY}\" ]; then\n");
            b.push_str("            cache_flags=(--config=remotecache-ci \"--remote_header=x-buildbuddy-api-key=${BUILDBUDDY_API_KEY}\")\n");
            b.push_str("          fi\n");
        } else if !u.artifacts.is_empty() {
            // :remotecache-ci, not :remote, for a unit that publishes files.
            // :remote carries --remote_download_outputs=minimal, so on a cache
            // hit the outputs stay on the remote cache and never land in
            // bazel-bin -- the upload then finds nothing off a perfectly green
            // build. #1296 measured exactly that on the other artifact lanes,
            // and remote.bazelrc names :remotecache as the profile for lanes
            // that consume bazel-bin directly.
            b.push_str("          if [ -n \"${BUILDBUDDY_API_KEY}\" ]; then\n");
            b.push_str("            cache_flags=(--config=remotecache-ci \"--remote_header=x-buildbuddy-api-key=${BUILDBUDDY_API_KEY}\")\n");
            b.push_str("          fi\n");
        } else {
            b.push_str("          if [ -n \"${BUILDBUDDY_API_KEY}\" ]; then\n");
            b.push_str("            cache_flags=(--config=remote \"--remote_header=x-buildbuddy-api-key=${BUILDBUDDY_API_KEY}\")\n");
            b.push_str("          fi\n");
        }
        // A unit's own flags go last so they win over the shared configs above.
        //
        // Each flag is quoted individually: a value may legitimately contain a
        // comma (--fat_apk_cpu=arm64-v8a,x86_64), and unquoted that trips
        // shellcheck SC2054, which reads the comma as an array separator and
        // fails actionlint in CI.
        if !u.build_flags.is_empty() {
            let quoted: Vec<String> = u.build_flags.iter().map(|f| quote(f)).collect();
            {}
            b.push_str(&format!("          extra_flags+=({})\n", quoted.join(" ")));
        }
        if u.needs_emulator {
            // --test_output=all: a device test that fails is diagnosed from its
            // own log, and the default summary throws that away.
            b.push_str("          extra_flags+=(--test_env=ANDROID_HOME --test_env=ANDROID_SERIAL --test_env=PATH --test_output=all)\n");
        }
        let targets_str = u.targets().join(" ");
        b.push_str("          bazel test \"${extra_flags[@]}\" \"${cache_flags[@]}\" ");
        b.push_str(&targets_str);
        b.push_str(" || { rc=$?; if [ $rc -eq 4 ]; then bazel build \"${extra_flags[@]}\" \"${cache_flags[@]}\" ");
        b.push_str(&targets_str);
        b.push_str("; else exit $rc; fi; }\n");

        // Artifacts are copied HERE, inside the build step, because the flags
        // above are what decide where Bazel writes: --android_platforms puts
        // outputs in a different bin directory than the default one, and the
        // `bazel-bin` symlink in the workspace does not point at it. Asking
        // `bazel info` with the same flags is the only reliable answer, and a
        // later step cannot -- shell variables do not survive between steps.
        //
        // cp -L because bazel-bin is a symlink into the output base, which on
        // CI lives outside the checkout, where upload-artifact will not follow.
        if !u.artifacts.is_empty() {
            {}
            b.push_str("          bin=$(bazel info \"${extra_flags[@]}\" \"${cache_flags[@]}\" bazel-bin)\n");
            for (n, path) in &u.artifacts {
                b.push_str(&format!("          mkdir -p .pipeline-artifacts/{n}\n"));
                b.push_str(&format!(
                    "          cp -L \"$bin/{path}\" .pipeline-artifacts/{n}/\n"
                ));
            }
        }
        b.push_str("\n");

        // Artifacts upload after the targets and before the tripwire. Sorted
        // because Go map order is random and this file is diffed by tidy-check:
        // an unsorted range would regenerate differently every run and fail a
        // check that has nothing to do with what changed.
        if !u.artifacts.is_empty() {
            {}
            for n in u.artifacts.keys() {
                b.push_str(&format!("      - name: Upload {n}\n"));
                // success() only: an artifact salvaged from a failed build is
                // worse than no artifact, because it still looks installable.
                b.push_str("        if: success()\n");
                b.push_str("        uses: ");
                b.push_str(&pin("actions/upload-artifact")?);
                b.push('\n');
                b.push_str("        with:\n");
                b.push_str(&format!("          name: {n}\n"));
                b.push_str(&format!("          path: .pipeline-artifacts/{n}\n"));
                b.push_str("          if-no-files-found: error\n\n");
            }
        }

        if !is_mac_runner(&u.runner) {
            b.push_str("      - name: LLVM cache tripwire\n");
            b.push_str("        if: always()\n");
            b.push_str("        uses: ./.github/actions/llvm-cache-tripwire\n");
            b.push_str("        with:\n");
            b.push_str("          restore-outcome: ${{ steps.llvm-contents.outputs.outcome }}\n");
            b.push_str("          cache-hit: ${{ steps.llvm-contents.outputs.cache-hit }}\n");
            b.push_str("          pre-count: ${{ steps.llvm-contents.outputs.pre-count }}\n");
            b.push_str("          pin-path: ${{ steps.llvm-contents.outputs.pin-path }}\n\n");
        }
    }

    // Render Gate Aggregator job
    // On every push to main, compute the dependency map for that commit and
    // save it for the PRs that will be based on it. Off the critical path:
    // nothing needs this job, and a failure only means those PRs query live.
    b.push_str("  rdeps-map:\n");
    b.push_str("    name: plan/rdeps-map\n");
    b.push_str("    if: ${{ github.event_name == 'push' && github.ref == 'refs/heads/main' }}\n");
    b.push_str("    runs-on: ubuntu-26.04\n");
    b.push_str("    timeout-minutes: 45\n");
    // contents: write, for this job only: it pushes the map to
    // refs/rdeps-map/<sha> (see the save step). It runs on push to main only.
    b.push_str("    permissions:\n");
    b.push_str("      contents: write\n");
    b.push_str("    env:\n");
    b.push_str("      BUILDBUDDY_API_KEY: ${{ secrets.BUILDBUDDY_API_KEY }}\n");
    b.push_str("    steps:\n");
    b.push_str("      - uses: ");
    b.push_str(&pin("actions/checkout")?);
    b.push('\n');
    b.push_str("        with:\n");
    b.push_str("          persist-credentials: false\n\n");
    b.push_str("      - name: Free up runner disk space\n");
    b.push_str("        uses: ./.github/actions/free-disk-space\n\n");
    b.push_str("      - name: Set up Bazel\n");
    b.push_str("        uses: ./.github/actions/setup-bazel\n\n");
    b.push_str("      - name: Restore the extracted LLVM toolchain\n");
    b.push_str("        id: llvm-contents\n");
    b.push_str("        uses: ./.github/actions/llvm-cache-restore\n");
    b.push_str("        with:\n");
    b.push_str("          restore-only: \"true\"\n\n");
    b.push_str("      - name: Compute the dependency map for this commit\n");
    b.push_str("        run: |\n");
    b.push_str("          cache_flags=()\n");
    b.push_str("          if [ -n \"${BUILDBUDDY_API_KEY:-}\" ]; then\n");
    b.push_str("            cache_flags=(--config=remotecache-ci \"--remote_header=x-buildbuddy-api-key=${BUILDBUDDY_API_KEY}\")\n");
    b.push_str("          fi\n");
    b.push_str("          bazel build \"${cache_flags[@]}\" //tools/pipeline/plan\n");
    b.push_str(
        "          cp -f bazel-bin/tools/pipeline/plan/plan \"$RUNNER_TEMP/pipeline-plan\"\n",
    );
    b.push_str("          chmod +x \"$RUNNER_TEMP/pipeline-plan\"\n");
    b.push_str("          \"$RUNNER_TEMP/pipeline-plan\" --emit-rdeps-map=\"$RUNNER_TEMP/pipeline-rdeps-map.json\" --repo-root=\"$PWD\" --timeout-sec=2100\n\n");
    // The copy that is never evicted (#2841). continue-on-error: the cache
    // save below still happens, so a failed push only costs the speed-up.
    b.push_str("      - name: Keep it under a git ref\n");
    b.push_str("        continue-on-error: true\n");
    b.push_str("        env:\n");
    b.push_str("          GH_TOKEN: ${{ github.token }}\n");
    b.push_str("        run: |\n");
    b.push_str("          bash tools/ci/rdeps-map-ref.sh save \"$RUNNER_TEMP/pipeline-rdeps-map.json\" \"$GITHUB_SHA\"\n");
    b.push_str("          bash tools/ci/rdeps-map-ref.sh prune\n\n");
    b.push_str("      - name: Save it for PRs based on this commit\n");
    b.push_str("        uses: ");
    b.push_str(&pin("actions/cache/save")?);
    b.push('\n');
    b.push_str("        with:\n");
    b.push_str("          path: ${{ runner.temp }}/pipeline-rdeps-map.json\n");
    b.push_str("          key: pipeline-rdeps-map-v1-${{ github.sha }}\n\n");
    b.push_str("  gate:\n");
    b.push_str("    name: gate/all-required-passed\n");
    let mut gate_needs = vec!["plan".to_string()];
    gate_needs.extend(job_names.iter().cloned());
    b.push_str(&format!("    needs: [{}]\n", gate_needs.join(", ")));
    b.push_str("    if: always()\n");
    b.push_str("    runs-on: ubuntu-26.04\n");
    b.push_str("    timeout-minutes: 5\n");
    b.push_str("    steps:\n");
    b.push_str("      - name: Evaluate Monorepo Gate Verdict\n");
    // toJSON(needs) is the only way a fan-in job can see its upstreams'
    // results. Passed as env rather than interpolated into the script body so
    // a job name can never be read as shell.
    b.push_str("        env:\n");
    b.push_str("          NEEDS_JSON: ${{ toJSON(needs) }}\n");
    b.push_str("        run: |\n");
    b.push_str("          set -euo pipefail\n");
    b.push_str("          # `if: always()` makes this job run even when an upstream unit\n");
    b.push_str("          # failed, so the job's own success says NOTHING about theirs --\n");
    b.push_str("          # it has to read their results and decide. Skipping that check is\n");
    b.push_str("          # what let runs 34012010463 (2 units red) and 34010090082 (7 units\n");
    b.push_str("          # red) report this required gate green.\n");
    b.push_str("          echo \"$NEEDS_JSON\" | jq -r 'to_entries[] | \"\\(.value.result)\\t\\(.key)\"' | sort\n");
    b.push_str("          count=$(echo \"$NEEDS_JSON\" | jq -r 'length')\n");
    b.push_str("          if [ \"$count\" -eq 0 ]; then\n");
    b.push_str("            echo \"::error::Gate has no upstream units. Failing closed.\"\n");
    b.push_str("            exit 1\n");
    b.push_str("          fi\n");
    b.push_str("          # success and skipped pass; failure, cancelled and anything a\n");
    b.push_str("          # future GitHub adds do not. Allowlist, not denylist.\n");
    b.push_str("          bad=$(echo \"$NEEDS_JSON\" | jq -r 'to_entries[] | select(.value.result != \"success\" and .value.result != \"skipped\") | \"\\(.key)=\\(.value.result)\"')\n");
    b.push_str("          if [ -n \"$bad\" ]; then\n");
    b.push_str("            echo \"::error::Pipeline units did not pass: $(echo \"$bad\" | tr '\\n' ' ')\"\n");
    b.push_str("            exit 1\n");
    b.push_str("          fi\n");
    b.push_str("          echo \"✓ All $count pipeline units in DAG completed successfully.\"\n\n");
    // The marker queue-fast-pass.sh looks for (#2841): "a pull-request run of
    // this workflow passed on exactly these files". Written only after the
    // verdict above succeeded, and only on pull requests. The name carries
    // the tree hash, so the lookup is a single query. A failed upload costs
    // nothing but a later miss.
    b.push_str("      - name: Record that this exact code passed\n");
    b.push_str(
        "        if: ${{ github.event_name == 'pull_request' && needs.plan.outputs.tree != '' }}\n",
    );
    b.push_str("        continue-on-error: true\n");
    b.push_str("        env:\n");
    b.push_str("          TREE: ${{ needs.plan.outputs.tree }}\n");
    b.push_str("        run: printf '{\"check\":\"presubmit\",\"tree\":\"%s\",\"run\":\"%s\"}\\n' \"$TREE\" \"$GITHUB_RUN_ID\" > \"$RUNNER_TEMP/passed.json\"\n\n");
    b.push_str("      - name: Keep the record for the merge queue\n");
    b.push_str(
        "        if: ${{ github.event_name == 'pull_request' && needs.plan.outputs.tree != '' }}\n",
    );
    b.push_str("        continue-on-error: true\n");
    b.push_str("        uses: ");
    b.push_str(&pin("actions/upload-artifact")?);
    b.push('\n');
    b.push_str("        with:\n");
    b.push_str("          name: passed-presubmit-${{ needs.plan.outputs.tree }}\n");
    b.push_str("          path: ${{ runner.temp }}/passed.json\n");
    b.push_str("          retention-days: 7\n");
    b.push_str("          overwrite: true\n");

    Ok(b)
}
