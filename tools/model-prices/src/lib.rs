pub fn parse_cli_args<I, S>(args: I, base_dir: &Path) -> Result<CliParseResult, String>
where
    I: IntoIterator<Item = S>,
    S: AsRef<str>,
{
    let mut check = false;
    let mut offline: Option<PathBuf> = None;
    let mut max_change = MaxChange::parse(DEFAULT_MAX_CHANGE_STR).expect("default max-change");
    let mut markdown_out: Option<PathBuf> = None;

    let resolve_path = |raw: &str| -> PathBuf {
        let p = PathBuf::from(raw);
        if p.is_absolute() {
            p
        } else {
            base_dir.join(p)
        }
    };

    let mut iter = args.into_iter();
    while let Some(arg_raw) = iter.next() {
        let arg = arg_raw.as_ref();
        match arg {
            "-h" | "--help" => return Ok(CliParseResult::Help(usage().to_string())),
            "--check" => check = true,
            "--offline" => {
                let val = iter
                    .next()
                    .ok_or_else(|| "--offline requires a <file> argument".to_string())?;
                offline = Some(resolve_path(val.as_ref()));
            }
            _ if arg.starts_with("--offline=") => {
                let val = &arg["--offline=".len()..];
                if val.is_empty() {
                    return Err("--offline requires a non-empty <file> argument".to_string());
                }
                offline = Some(resolve_path(val));
            }
            "--max-change" => {
                let val = iter
                    .next()
                    .ok_or_else(|| "--max-change requires a <percent> argument".to_string())?;
                max_change = MaxChange::parse(val.as_ref())?;
            }
            _ if arg.starts_with("--max-change=") => {
                let val = &arg["--max-change=".len()..];
                max_change = MaxChange::parse(val)?;
            }
            "--markdown-out" => {
                let val = iter
                    .next()
                    .ok_or_else(|| "--markdown-out requires a <file> argument".to_string())?;
                markdown_out = Some(resolve_path(val.as_ref()));
            }
            _ if arg.starts_with("--markdown-out=") => {
                let val = &arg["--markdown-out=".len()..];
                if val.is_empty() {
                    return Err("--markdown-out requires a non-empty <file> argument".to_string());
                }
                markdown_out = Some(resolve_path(val));
            }
            other => {
                return Err(format!("unknown argument {other:?}\n\n{}", usage()));
            }
        }
    }

    Ok(CliParseResult::Run(CliOptions {
        check,
        offline,
        max_change,
        markdown_out,
    }))
}

pub fn parse_models_tsv(content: &str) -> Result<Vec<ModelSpec>, String> {
    parse_models_tsv_checked(content).map_err(|e| e.message)
}

fn parse_models_tsv_checked(content: &str) -> Result<Vec<ModelSpec>, PriceError> {
    const EXPECTED_HEADER: [&str; 6] = [
        "match",
        "openrouter_id",
        "fallback_input",
        "fallback_output",
        "fallback_cache_read",
        "fallback_cache_write",
    ];

    let syntax = |message: String| PriceError {
        kind: PriceErrorKind::InvalidSyntax,
        message,
    };

    let mut saw_header = false;
    let mut seen_matches = BTreeSet::new();
    let mut specs = Vec::new();

    for (idx, raw_line) in content.lines().enumerate() {
        let line_no = idx + 1;
        let line = raw_line.trim_end_matches('\r');
        if line.trim().is_empty() || line.trim_start().starts_with('#') {
            continue;
        }
        let cols: Vec<&str> = line.split('\t').collect();
        if !saw_header {
            if cols != EXPECTED_HEADER {
                return Err(syntax(format!(
                    "models.tsv:{line_no}: invalid header: expected {:?}, found {:?}",
                    EXPECTED_HEADER.join("\t"),
                    cols.join("\t")
                )));
            }
            saw_header = true;
            continue;
        }
        if cols.len() != 6 {
            return Err(syntax(format!(
                "models.tsv:{line_no}: expected 6 TAB-separated columns, found {}",
                cols.len()
            )));
        }

        let match_pattern = cols[0].trim();
        if match_pattern.is_empty() {
            return Err(syntax(format!(
                "models.tsv:{line_no}: empty `match` column"
            )));
        }
        if !seen_matches.insert(match_pattern.to_string()) {
            return Err(syntax(format!(
                "models.tsv:{line_no}: duplicate `match` pattern {match_pattern:?}"
            )));
        }

        let id_raw = cols[1].trim();
        if id_raw.is_empty() {
            return Err(syntax(format!(
                "models.tsv:{line_no}: empty `openrouter_id` (use '-' when none exists)"
            )));
        }
        let openrouter_id = if id_raw == "-" {
            None
        } else {
            Some(id_raw.to_string())
        };

        let parse_col = |col_idx: usize, name: &str| -> Result<Price, PriceError> {
            Price::from_per_million_str(cols[col_idx]).map_err(|e| PriceError {
                kind: e.kind,
                message: format!("models.tsv:{line_no}: invalid {name}: {}", e.message),
            })
        };

        specs.push(ModelSpec {
            match_pattern: match_pattern.to_string(),
            openrouter_id,
            fallback_input: parse_col(2, "fallback_input")?,
            fallback_output: parse_col(3, "fallback_output")?,
            fallback_cache_read: parse_col(4, "fallback_cache_read")?,
            fallback_cache_write: parse_col(5, "fallback_cache_write")?,
        });
    }

    if !saw_header {
        return Err(syntax("models.tsv: missing header row".to_string()));
    }
    if specs.is_empty() {
        return Err(syntax("models.tsv: contains 0 model rows".to_string()));
    }
    Ok(specs)
}

