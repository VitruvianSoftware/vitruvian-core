fn resolve_rows_checked(
    specs: &[ModelSpec],
    upstream: &BTreeMap<String, RawOpenRouterPricing>,
) -> Result<Vec<ResolvedRow>, PriceError> {
    let syntax = |message: String| PriceError {
        kind: PriceErrorKind::InvalidSyntax,
        message,
    };

    let mut out = Vec::with_capacity(specs.len());
    for spec in specs {
        let Some(id) = &spec.openrouter_id else {
            out.push(ResolvedRow {
                match_pattern: spec.match_pattern.clone(),
                openrouter_id: None,
                input: spec.fallback_input,
                output: spec.fallback_output,
                cache_read: spec.fallback_cache_read,
                cache_write: spec.fallback_cache_write,
                source: PriceSource::Fallback,
                fallback_reason: Some(FallbackReason::Unmapped),
            });
            continue;
        };

        let Some(pricing) = upstream.get(id) else {
            out.push(ResolvedRow {
                match_pattern: spec.match_pattern.clone(),
                openrouter_id: Some(id.clone()),
                input: spec.fallback_input,
                output: spec.fallback_output,
                cache_read: spec.fallback_cache_read,
                cache_write: spec.fallback_cache_write,
                source: PriceSource::Fallback,
                fallback_reason: Some(FallbackReason::MissingUpstream(id.clone())),
            });
            continue;
        };

        let prompt_raw = pricing
            .prompt
            .as_deref()
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .ok_or_else(|| syntax(format!("OpenRouter model {id:?} is missing pricing.prompt")))?;
        let completion_raw = pricing
            .completion
            .as_deref()
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .ok_or_else(|| {
                syntax(format!(
                    "OpenRouter model {id:?} is missing pricing.completion"
                ))
            })?;

        let input = Price::from_per_token_str(prompt_raw).map_err(|e| PriceError {
            kind: e.kind,
            message: format!(
                "OpenRouter model {id:?} invalid pricing.prompt: {}",
                e.message
            ),
        })?;
        let output = Price::from_per_token_str(completion_raw).map_err(|e| PriceError {
            kind: e.kind,
            message: format!(
                "OpenRouter model {id:?} invalid pricing.completion: {}",
                e.message
            ),
        })?;

        let cache_read = match pricing
            .input_cache_read
            .as_deref()
            .map(str::trim)
            .filter(|s| !s.is_empty())
        {
            Some(raw) => Price::from_per_token_str(raw).map_err(|e| PriceError {
                kind: e.kind,
                message: format!(
                    "OpenRouter model {id:?} invalid pricing.input_cache_read: {}",
                    e.message
                ),
            })?,
            None => spec.fallback_cache_read,
        };

        let cache_write = match pricing
            .input_cache_write
            .as_deref()
            .map(str::trim)
            .filter(|s| !s.is_empty())
        {
            Some(raw) => Price::from_per_token_str(raw).map_err(|e| PriceError {
                kind: e.kind,
                message: format!(
                    "OpenRouter model {id:?} invalid pricing.input_cache_write: {}",
                    e.message
                ),
            })?,
            None => spec.fallback_cache_write,
        };

        out.push(ResolvedRow {
            match_pattern: spec.match_pattern.clone(),
            openrouter_id: Some(id.clone()),
            input,
            output,
            cache_read,
            cache_write,
            source: PriceSource::OpenRouter,
            fallback_reason: None,
        });
    }
    Ok(out)
}

pub fn parse_prices_mjs(content: &str) -> Result<ExistingPricesFile, String> {
    parse_prices_mjs_checked(content).map_err(|e| e.message)
}

fn parse_prices_mjs_checked(content: &str) -> Result<ExistingPricesFile, PriceError> {
    let syntax = |message: String| PriceError {
        kind: PriceErrorKind::InvalidSyntax,
        message,
    };

    let mut prices_updated: Option<String> = None;
    for line in content.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("export const PRICES_UPDATED =") {
            let literal = rest.trim().trim_end_matches(';').trim();
            let parsed: String = serde_json::from_str(literal).map_err(|e| {
                syntax(format!(
                    "invalid PRICES_UPDATED string in prices.mjs: {:?}",
                    e.to_string()
                ))
            })?;
            prices_updated = Some(parsed);
            break;
        }
    }
    let prices_updated = prices_updated
        .ok_or_else(|| syntax("missing `export const PRICES_UPDATED` in prices.mjs".to_string()))?;

    let array_marker = "export const PRICES = [";
    let start_idx = content
        .find(array_marker)
        .ok_or_else(|| syntax("missing `export const PRICES = [` in prices.mjs".to_string()))?;
    let tail = &content[start_idx + array_marker.len()..];
    let end_idx = tail
        .rfind("];")
        .ok_or_else(|| syntax("missing closing `];` for PRICES in prices.mjs".to_string()))?;
    let body = &tail[..end_idx];

    let mut clean_lines = Vec::new();
    for line in body.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with("//") {
            continue;
        }
        clean_lines.push(trimmed);
    }
    let joined = clean_lines.join("\n");

    let mut rows = Vec::new();
    let mut cursor = joined.as_str();
    while let Some(open) = cursor.find('{') {
        let after_open = &cursor[open + 1..];
        let close = find_object_close(after_open)
            .ok_or_else(|| syntax("unterminated object literal in prices.mjs".to_string()))?;
        let obj_text = &after_open[..close];
        rows.push(parse_existing_row_checked(obj_text)?);
        cursor = &after_open[close + 1..];
    }

    Ok(ExistingPricesFile {
        prices_updated,
        rows,
    })
}

fn find_object_close(s: &str) -> Option<usize> {
    let mut in_str = false;
    let mut escaped = false;
    for (idx, b) in s.bytes().enumerate() {
        if in_str {
            if escaped {
                escaped = false;
            } else if b == b'\\' {
                escaped = true;
            } else if b == b'"' {
                in_str = false;
            }
        } else if b == b'"' {
            in_str = true;
        } else if b == b'}' {
            return Some(idx);
        }
    }
    None
}

fn parse_existing_row_checked(obj_text: &str) -> Result<ExistingRow, PriceError> {
    let syntax = |message: String| PriceError {
        kind: PriceErrorKind::InvalidSyntax,
        message,
    };

    let mut match_pattern: Option<String> = None;
    let mut input: Option<Price> = None;
    let mut output: Option<Price> = None;
    let mut cache_read: Option<Price> = None;
    let mut cache_write: Option<Price> = None;
    let mut source: Option<String> = None;

    for raw_field in split_top_level_commas(obj_text) {
        let field = raw_field.trim();
        if field.is_empty() {
            continue;
        }
        let (key, raw_val) = field
            .split_once(':')
            .ok_or_else(|| syntax(format!("malformed property {field:?} in prices.mjs")))?;
        let key = key.trim();
        let val = raw_val.trim();
        match key {
            "match" => {
                let parsed: String = serde_json::from_str(val).map_err(|e| {
                    syntax(format!(
                        "invalid `match` string {val:?} in prices.mjs: {:?}",
                        e.to_string()
                    ))
                })?;
                match_pattern = Some(parsed);
            }
            "input" => {
                input = Some(Price::from_per_million_str(val).map_err(|e| PriceError {
                    kind: e.kind,
                    message: format!("invalid `input` in prices.mjs: {}", e.message),
                })?);
            }
            "output" => {
                output = Some(Price::from_per_million_str(val).map_err(|e| PriceError {
                    kind: e.kind,
                    message: format!("invalid `output` in prices.mjs: {}", e.message),
                })?);
            }
            "cacheRead" => {
                cache_read = Some(Price::from_per_million_str(val).map_err(|e| PriceError {
                    kind: e.kind,
                    message: format!("invalid `cacheRead` in prices.mjs: {}", e.message),
                })?);
            }
            "cacheWrite" => {
                cache_write = Some(Price::from_per_million_str(val).map_err(|e| PriceError {
                    kind: e.kind,
                    message: format!("invalid `cacheWrite` in prices.mjs: {}", e.message),
                })?);
            }
            "source" => {
                let parsed: String = serde_json::from_str(val).map_err(|e| {
                    syntax(format!(
                        "invalid `source` string {val:?} in prices.mjs: {:?}",
                        e.to_string()
                    ))
                })?;
                source = Some(parsed);
            }
            other => {
                return Err(syntax(format!(
                    "unexpected property {other:?} in prices.mjs"
                )));
            }
        }
    }

    Ok(ExistingRow {
        match_pattern: match_pattern
            .ok_or_else(|| syntax("missing `match` in prices.mjs entry".to_string()))?,
        input: input.ok_or_else(|| syntax("missing `input` in prices.mjs entry".to_string()))?,
        output: output.ok_or_else(|| syntax("missing `output` in prices.mjs entry".to_string()))?,
        cache_read: cache_read
            .ok_or_else(|| syntax("missing `cacheRead` in prices.mjs entry".to_string()))?,
        cache_write: cache_write
            .ok_or_else(|| syntax("missing `cacheWrite` in prices.mjs entry".to_string()))?,
        source: source.ok_or_else(|| syntax("missing `source` in prices.mjs entry".to_string()))?,
    })
}

fn split_top_level_commas(s: &str) -> Vec<&str> {
    let mut parts = Vec::new();
    let mut start = 0;
    let mut in_str = false;
    let mut escaped = false;
    for (idx, b) in s.bytes().enumerate() {
        if in_str {
            if escaped {
                escaped = false;
            } else if b == b'\\' {
                escaped = true;
            } else if b == b'"' {
                in_str = false;
            }
        } else if b == b'"' {
            in_str = true;
        } else if b == b',' {
            parts.push(&s[start..idx]);
            start = idx + 1;
        }
    }
    parts.push(&s[start..]);
    parts
}

pub fn any_price_changed(existing: &ExistingPricesFile, resolved: &[ResolvedRow]) -> bool {
    if existing.rows.len() != resolved.len() {
        return true;
    }
    for (old, new) in existing.rows.iter().zip(resolved.iter()) {
        if old.match_pattern != new.match_pattern
            || old.input != new.input
            || old.output != new.output
            || old.cache_read != new.cache_read
            || old.cache_write != new.cache_write
            || old.source != new.source.as_str()
        {
            return true;
        }
    }
    false
}

pub fn check_max_change_violations(
    existing: &ExistingPricesFile,
    resolved: &[ResolvedRow],
    max_change: MaxChange,
) -> Vec<String> {
    let old_by_match: BTreeMap<&str, &ExistingRow> = existing
        .rows
        .iter()
        .map(|r| (r.match_pattern.as_str(), r))
        .collect();

    let mut violations = Vec::new();
    for row in resolved {
        let Some(old) = old_by_match.get(row.match_pattern.as_str()) else {
            continue;
        };
        for (field, old_p, new_p) in [
            ("input", old.input, row.input),
            ("output", old.output, row.output),
            ("cacheRead", old.cache_read, row.cache_read),
            ("cacheWrite", old.cache_write, row.cache_write),
        ] {
            if let Some(pct) = max_change.violation(old_p, new_p) {
                let sign = if new_p > old_p { "+" } else { "-" };
                violations.push(format!(
                    "  {} {}: {} -> {} ({}{:.2}% exceeds --max-change {}%)",
                    row.match_pattern, field, old_p, new_p, sign, pct, max_change
                ));
            }
        }
    }
    violations
}

pub fn render_prices_mjs(prices_updated: &str, rows: &[ResolvedRow]) -> String {
    let mut out = String::with_capacity(2048);
    out.push_str(LICENSE_AND_BANNER);
    out.push('\n');
    let updated_json = serde_json::to_string(prices_updated).expect("JSON string");
    out.push_str(&format!("export const PRICES_UPDATED = {updated_json};\n"));
    out.push_str("export const PRICES = [\n");
    out.push_str(
        "  // { match: <case-insensitive regex source>, input, output, cacheRead, cacheWrite, source }\n",
    );
    for row in rows {
        let match_json = serde_json::to_string(&row.match_pattern).expect("JSON string");
        let source_json = serde_json::to_string(row.source.as_str()).expect("JSON string");
        out.push_str("  {\n");
        out.push_str(&format!("    match: {match_json},\n"));
        out.push_str(&format!("    input: {},\n", row.input));
        out.push_str(&format!("    output: {},\n", row.output));
        out.push_str(&format!("    cacheRead: {},\n", row.cache_read));
        out.push_str(&format!("    cacheWrite: {},\n", row.cache_write));
        out.push_str(&format!("    source: {source_json},\n"));
        out.push_str("  },\n");
    }
    out.push_str("];\n");
    out
}

fn format_cell(old: Option<Price>, new: Price, arrow: &str) -> String {
    match old {
        Some(o) if o == new => new.to_string(),
        Some(o) => format!("{o} {arrow} {new}"),
        None => format!("(new) {arrow} {new}"),
    }
}

pub fn render_text_report(existing: &ExistingPricesFile, resolved: &[ResolvedRow]) -> String {
    let old_by_match: BTreeMap<&str, &ExistingRow> = existing
        .rows
        .iter()
        .map(|r| (r.match_pattern.as_str(), r))
        .collect();

    let headers = [
        "match",
        "source",
        "input",
        "output",
        "cacheRead",
        "cacheWrite",
    ];
    let mut table_rows: Vec<[String; 6]> = Vec::with_capacity(resolved.len());
    for row in resolved {
        let old = old_by_match.get(row.match_pattern.as_str()).copied();
        let new_src = row.source.as_str();
        let src_cell = match old {
            Some(o) if o.source != new_src => format!("{} -> {new_src}", o.source),
            _ => new_src.to_string(),
        };
        table_rows.push([
            row.match_pattern.clone(),
            src_cell,
            format_cell(old.map(|o| o.input), row.input, "->"),
            format_cell(old.map(|o| o.output), row.output, "->"),
            format_cell(old.map(|o| o.cache_read), row.cache_read, "->"),
            format_cell(old.map(|o| o.cache_write), row.cache_write, "->"),
        ]);
    }

    let mut widths = headers.map(str::len);
    for r in &table_rows {
        for (i, cell) in r.iter().enumerate() {
            widths[i] = widths[i].max(cell.len());
        }
    }

    let mut out = String::new();
    let push_row = |buf: &mut String, cols: &[&str; 6]| {
        for (i, col) in cols.iter().enumerate() {
            if i + 1 == cols.len() {
                buf.push_str(col);
            } else {
                buf.push_str(&format!("{:<width$}  ", col, width = widths[i]));
            }
        }
        buf.push('\n');
    };

    push_row(&mut out, &headers);
    for r in &table_rows {
        let refs = [
            r[0].as_str(),
            r[1].as_str(),
            r[2].as_str(),
            r[3].as_str(),
            r[4].as_str(),
            r[5].as_str(),
        ];
        push_row(&mut out, &refs);
    }

    let fallbacks: Vec<String> = resolved
        .iter()
        .filter_map(|r| {
            r.fallback_reason.as_ref().map(|reason| match reason {
                FallbackReason::Unmapped => format!("{} (unmapped: -)", r.match_pattern),
                FallbackReason::MissingUpstream(id) => {
                    format!("{} ({id} missing from OpenRouter)", r.match_pattern)
                }
            })
        })
        .collect();

    if fallbacks.is_empty() {
        out.push_str("fallback rows: none\n");
    } else {
        out.push_str(&format!("fallback rows: {}\n", fallbacks.join(", ")));
    }

    let resolved_matches: BTreeSet<&str> =
        resolved.iter().map(|r| r.match_pattern.as_str()).collect();
    let removed: Vec<&str> = existing
        .rows
        .iter()
        .map(|r| r.match_pattern.as_str())
        .filter(|m| !resolved_matches.contains(m))
        .collect();
    if !removed.is_empty() {
        out.push_str(&format!("removed rows: {}\n", removed.join(", ")));
    }

    out
}

pub fn render_markdown_report(existing: &ExistingPricesFile, resolved: &[ResolvedRow]) -> String {
    let old_by_match: BTreeMap<&str, &ExistingRow> = existing
        .rows
        .iter()
        .map(|r| (r.match_pattern.as_str(), r))
        .collect();

    let esc = |s: &str| s.replace('|', "\\|");
    let mut out = String::new();
    out.push_str(
        "| Match | OpenRouter ID | Source | Input ($/1M) | Output ($/1M) | Cache Read ($/1M) | Cache Write ($/1M) |\n",
    );
    out.push_str("| --- | --- | --- | --- | --- | --- | --- |\n");
    for row in resolved {
        let old = old_by_match.get(row.match_pattern.as_str()).copied();
        let id_cell = match &row.openrouter_id {
            Some(id) => format!("`{}`", esc(id)),
            None => "`-`".to_string(),
        };
        let new_src = row.source.as_str();
        let src_cell = match old {
            Some(o) if o.source != new_src => format!("`{}` → `{new_src}`", esc(&o.source)),
            _ => format!("`{new_src}`"),
        };
        out.push_str(&format!(
            "| `{}` | {} | {} | {} | {} | {} | {} |\n",
            esc(&row.match_pattern),
            id_cell,
            src_cell,
            format_cell(old.map(|o| o.input), row.input, "→"),
            format_cell(old.map(|o| o.output), row.output, "→"),
            format_cell(old.map(|o| o.cache_read), row.cache_read, "→"),
            format_cell(old.map(|o| o.cache_write), row.cache_write, "→"),
        ));
    }

    let fallbacks: Vec<String> = resolved
        .iter()
        .filter_map(|r| {
            r.fallback_reason.as_ref().map(|reason| match reason {
                FallbackReason::Unmapped => format!("`{}` (unmapped `-`)", esc(&r.match_pattern)),
                FallbackReason::MissingUpstream(id) => {
                    format!(
                        "`{}` (`{}` missing from OpenRouter)",
                        esc(&r.match_pattern),
                        esc(id)
                    )
                }
            })
        })
        .collect();

    out.push('\n');
    if fallbacks.is_empty() {
        out.push_str("Fallback rows: none.\n");
    } else {
        out.push_str(&format!("Fallback rows: {}.\n", fallbacks.join(", ")));
    }
    out
}

/// Format current UTC date as `YYYY-MM-DD` (Howard Hinnant's `civil_from_days`).
pub fn today_utc_ymd() -> String {
    let secs = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();
    unix_secs_to_ymd(secs)
}

fn unix_secs_to_ymd(secs: u64) -> String {
    let days = (secs / 86_400) as i64;
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = (z - era * 146_097) as u64;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = (yoe as i64) + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = if m <= 2 { y + 1 } else { y };
    format!("{year:04}-{m:02}-{d:02}")
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RunOutcome {
    pub exit_code: i32,
    pub stdout: String,
    pub stderr: String,
    pub price_changed: bool,
    pub wrote_prices_mjs: bool,
}

/// Execute `update` inside `workspace_root` using `fetch_live` when `--offline` is not set.
pub fn execute_in_workspace<F>(
    workspace_root: &Path,
    opts: &CliOptions,
    today_utc: &str,
    fetch_live: F,
) -> RunOutcome
where
    F: FnOnce() -> Result<String, String>,
{
    let models_path = workspace_root.join(MODELS_TSV_REL);
    let prices_path = workspace_root.join(PRICES_MJS_REL);

    let models_raw = match fs::read_to_string(&models_path) {
        Ok(s) => s,
        Err(e) => {
            return RunOutcome {
                exit_code: 1,
                stdout: String::new(),
                stderr: format!("error: cannot read {models_path:?}: {:?}\n", e.to_string()),
                price_changed: false,
                wrote_prices_mjs: false,
            };
        }
    };
    let specs = match parse_models_tsv_checked(&models_raw) {
        Ok(v) => v,
        Err(e) => {
            return RunOutcome {
                exit_code: e.exit_code(),
                stdout: String::new(),
                stderr: format!("error: {e}\n"),
                price_changed: false,
                wrote_prices_mjs: false,
            };
        }
    };

    let existing_raw = match fs::read_to_string(&prices_path) {
        Ok(s) => s,
        Err(e) => {
            return RunOutcome {
                exit_code: 1,
                stdout: String::new(),
                stderr: format!("error: cannot read {prices_path:?}: {:?}\n", e.to_string()),
                price_changed: false,
                wrote_prices_mjs: false,
            };
        }
    };
    let existing = match parse_prices_mjs_checked(&existing_raw) {
        Ok(v) => v,
        Err(e) => {
            return RunOutcome {
                exit_code: e.exit_code(),
                stdout: String::new(),
                stderr: format!("error: {e}\n"),
                price_changed: false,
                wrote_prices_mjs: false,
            };
        }
    };

    let response_json = match &opts.offline {
        Some(path) => match fs::read_to_string(path) {
            Ok(s) => s,
            Err(e) => {
                return RunOutcome {
                    exit_code: 1,
                    stdout: String::new(),
                    stderr: format!(
                        "error: cannot read --offline file {path:?}: {:?}\n",
                        e.to_string()
                    ),
                    price_changed: false,
                    wrote_prices_mjs: false,
                };
            }
        },
        None => match fetch_live() {
            Ok(s) => s,
            Err(e) => {
                return RunOutcome {
                    exit_code: 1,
                    stdout: String::new(),
                    stderr: format!("error: {}\n", escape_inline_for_log(&e)),
                    price_changed: false,
                    wrote_prices_mjs: false,
                };
            }
        },
    };

    let upstream = match parse_openrouter_response(&response_json) {
        Ok(m) => m,
        Err(e) => {
            return RunOutcome {
                exit_code: 1,
                stdout: String::new(),
                stderr: format!("error: {}\n", escape_inline_for_log(&e)),
                price_changed: false,
                wrote_prices_mjs: false,
            };
        }
    };

    let resolved = match resolve_rows_checked(&specs, &upstream) {
        Ok(r) => r,
        Err(e) => {
            return RunOutcome {
                exit_code: e.exit_code(),
                stdout: String::new(),
                stderr: format!("error: {e}\n"),
                price_changed: false,
                wrote_prices_mjs: false,
            };
        }
    };

    let mut stdout = render_text_report(&existing, &resolved);
    let changed = any_price_changed(&existing, &resolved);

    if opts.check {
        if let Some(md_path) = &opts.markdown_out {
            let md = render_markdown_report(&existing, &resolved);
            if let Err(e) = fs::write(md_path, md) {
                return RunOutcome {
                    exit_code: 1,
                    stdout,
                    stderr: format!(
                        "error: cannot write --markdown-out {md_path:?}: {:?}\n",
                        e.to_string()
                    ),
                    price_changed: changed,
                    wrote_prices_mjs: false,
                };
            }
        }
        if changed {
            stdout.push_str(
                "model-prices: prices differ from packages/orchestrator-core/src/prices.mjs (run `bazel run //tools/model-prices:update` followed by `bazel run //tools/agent-roster -- --write`).\n",
            );
            return RunOutcome {
                exit_code: 1,
                stdout,
                stderr: String::new(),
                price_changed: true,
                wrote_prices_mjs: false,
            };
        }
        stdout.push_str("model-prices: packages/orchestrator-core/src/prices.mjs is current.\n");
        return RunOutcome {
            exit_code: 0,
            stdout,
            stderr: String::new(),
            price_changed: false,
            wrote_prices_mjs: false,
        };
    }

    let violations = check_max_change_violations(&existing, &resolved, opts.max_change);
    if !violations.is_empty() {
        let stderr = format!(
            "error: refusing to write {} because {} price field(s) moved by more than {}%:\n{}\nPass a higher --max-change <percent> if this upstream price change is expected.\n",
            PRICES_MJS_REL,
            violations.len(),
            opts.max_change,
            violations.join("\n")
        );
        return RunOutcome {
            exit_code: 1,
            stdout,
            stderr,
            price_changed: changed,
            wrote_prices_mjs: false,
        };
    }

    let mut wrote_prices_mjs = false;
    if changed {
        let rendered = render_prices_mjs(today_utc, &resolved);
        if rendered != existing_raw {
            if let Err(e) = fs::write(&prices_path, &rendered) {
                return RunOutcome {
                    exit_code: 1,
                    stdout,
                    stderr: format!("error: cannot write {prices_path:?}: {:?}\n", e.to_string()),
                    price_changed: true,
                    wrote_prices_mjs: false,
                };
            }
            wrote_prices_mjs = true;
        }
        stdout.push_str(&format!(
            "model-prices: updated {PRICES_MJS_REL} (PRICES_UPDATED = {today_utc}); run `bazel run //tools/agent-roster -- --write` to sync vendored plugin copies.\n"
        ));
    } else {
        stdout.push_str(&format!(
            "model-prices: no price changes; {PRICES_MJS_REL} left unchanged (PRICES_UPDATED = {}).\n",
            existing.prices_updated
        ));
    }

    if let Some(md_path) = &opts.markdown_out {
        let md = render_markdown_report(&existing, &resolved);
        if let Err(e) = fs::write(md_path, md) {
            return RunOutcome {
                exit_code: 1,
                stdout,
                stderr: format!(
                    "error: cannot write --markdown-out {md_path:?}: {:?}\n",
                    e.to_string()
                ),
                price_changed: changed,
                wrote_prices_mjs,
            };
        }
    }

    RunOutcome {
        exit_code: 0,
        stdout,
        stderr: String::new(),
        price_changed: changed,
        wrote_prices_mjs,
    }
}

