#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PriceErrorKind {
    InvalidSyntax,
    OutOfRange,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PriceError {
    pub kind: PriceErrorKind,
    pub message: String,
}

impl PriceError {
    pub fn exit_code(&self) -> i32 {
        match self.kind {
            PriceErrorKind::InvalidSyntax => 1,
            PriceErrorKind::OutOfRange => EXIT_PRICE_OUT_OF_RANGE,
        }
    }
}

impl fmt::Display for PriceError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.message)
    }
}

/// Escape any non-newline control character so untrusted strings cannot emit
/// terminal escape codes or carriage-return spoofing into logs.
pub fn sanitize_log_output(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if c == '\n' || !c.is_control() {
            out.push(c);
        } else {
            for esc in c.escape_debug() {
                out.push(esc);
            }
        }
    }
    out
}

fn escape_inline_for_log(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if !c.is_control() {
            out.push(c);
        } else {
            for esc in c.escape_debug() {
                out.push(esc);
            }
        }
    }
    out
}

/// USD per 1,000,000 tokens stored in integer micro-dollars (`10^-6` USD / 1M tokens).
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct Price(u128);

impl Price {
    pub const ZERO: Self = Self(0);
    pub const MAX: Self = Self(MAX_PRICE_MICROS);

    /// Parse a non-negative per-million USD string (e.g. `"10"`, `"0.25"`, `"0.041667"`),
    /// rejecting values above `10000` USD per million tokens.
    pub fn from_per_million_str(raw: &str) -> Result<Self, PriceError> {
        parse_scaled_nonneg_decimal(
            raw,
            SCALE_DECIMALS,
            MAX_PRICE_MICROS,
            "10000 USD per million tokens",
        )
        .map(Self)
    }

    /// Parse a non-negative per-token USD string from OpenRouter (e.g. `"0.000004"`)
    /// and convert it to per-million USD, rounded half-up at 6 decimal places,
    /// rejecting values above `10000` USD per million tokens.
    pub fn from_per_token_str(raw: &str) -> Result<Self, PriceError> {
        parse_scaled_nonneg_decimal(
            raw,
            PER_MILLION_DECIMALS + SCALE_DECIMALS,
            MAX_PRICE_MICROS,
            "10000 USD per million tokens",
        )
        .map(Self)
    }

    pub fn micros(self) -> u128 {
        self.0
    }
}

impl fmt::Display for Price {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let whole = self.0 / SCALE_FACTOR;
        let frac = self.0 % SCALE_FACTOR;
        if frac == 0 {
            write!(f, "{whole}")
        } else {
            let padded = format!("{frac:06}");
            let trimmed = padded.trim_end_matches('0');
            write!(f, "{whole}.{trimmed}")
        }
    }
}

/// Parse a non-negative decimal string (optional `[eE][+-]?\d+`), multiply by
/// `10^shift_right`, round half-up to the nearest integer, and enforce `max_scaled`.
fn parse_scaled_nonneg_decimal(
    raw: &str,
    shift_right: i32,
    max_scaled: u128,
    max_desc: &str,
) -> Result<u128, PriceError> {
    let syntax_err = |message: String| PriceError {
        kind: PriceErrorKind::InvalidSyntax,
        message,
    };
    let range_err = || PriceError {
        kind: PriceErrorKind::OutOfRange,
        message: format!("price {raw:?} exceeds maximum allowed {max_desc}"),
    };

    let s = raw.trim();
    if s.is_empty() {
        return Err(syntax_err("empty price string".to_string()));
    }
    if s.starts_with('-') {
        return Err(syntax_err(format!("negative price {raw:?}")));
    }
    let s = s.strip_prefix('+').unwrap_or(s);

    let (mantissa, exp): (&str, i64) = match s.find(['e', 'E']) {
        Some(idx) => {
            let exp_raw = &s[idx + 1..];
            let (neg_exp, exp_digits) = if let Some(rest) = exp_raw.strip_prefix('-') {
                (true, rest)
            } else if let Some(rest) = exp_raw.strip_prefix('+') {
                (false, rest)
            } else {
                (false, exp_raw)
            };
            if exp_digits.is_empty() || !exp_digits.bytes().all(|b| b.is_ascii_digit()) {
                return Err(syntax_err(format!("invalid exponent in price {raw:?}")));
            }
            const EXP_CAP: i64 = 1_000_000_000;
            let abs_exp = exp_digits.parse::<i64>().unwrap_or(EXP_CAP).min(EXP_CAP);
            let signed_exp = if neg_exp { -abs_exp } else { abs_exp };
            (&s[..idx], signed_exp)
        }
        None => (s, 0),
    };

    let (int_part, frac_part) = match mantissa.split_once('.') {
        Some((lhs, rhs)) => {
            if rhs.contains('.') {
                return Err(syntax_err(format!("invalid decimal price {raw:?}")));
            }
            (lhs, rhs)
        }
        None => (mantissa, ""),
    };

    if int_part.is_empty() && frac_part.is_empty() {
        return Err(syntax_err(format!("invalid decimal price {raw:?}")));
    }
    if !int_part.bytes().all(|b| b.is_ascii_digit())
        || !frac_part.bytes().all(|b| b.is_ascii_digit())
    {
        return Err(syntax_err(format!("invalid decimal price {raw:?}")));
    }

    let mut digits = String::with_capacity(int_part.len() + frac_part.len());
    digits.push_str(int_part);
    digits.push_str(frac_part);
    let sig_digits = digits.trim_start_matches('0');
    if sig_digits.is_empty() {
        return Ok(0);
    }

    let frac_len = i64::try_from(frac_part.len()).unwrap_or(i64::MAX / 4);
    let sig_len = i64::try_from(sig_digits.len()).unwrap_or(i64::MAX / 4);
    let net_exp = i64::from(shift_right)
        .saturating_add(exp)
        .saturating_sub(frac_len);

    let magnitude = sig_len.saturating_add(net_exp);
    if magnitude > 39 {
        return Err(range_err());
    }
    if magnitude < 0 {
        return Ok(0);
    }

    let scaled = if net_exp >= 0 {
        let exp_u32 = u32::try_from(net_exp).map_err(|_| range_err())?;
        let base = sig_digits.parse::<u128>().map_err(|_| range_err())?;
        let mul = 10u128.checked_pow(exp_u32).ok_or_else(range_err)?;
        base.checked_mul(mul).ok_or_else(range_err)?
    } else {
        let drop = (-net_exp) as usize;
        if drop > sig_digits.len() {
            0
        } else if drop == sig_digits.len() {
            u128::from(sig_digits.as_bytes()[0] >= b'5')
        } else {
            let split = sig_digits.len() - drop;
            let base = sig_digits[..split]
                .parse::<u128>()
                .map_err(|_| range_err())?;
            let round_up = u128::from(sig_digits.as_bytes()[split] >= b'5');
            base.checked_add(round_up).ok_or_else(range_err)?
        }
    };

    if scaled > max_scaled {
        return Err(range_err());
    }
    Ok(scaled)
}

/// Threshold in micro-percent (`50%` -> `50_000_000`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct MaxChange(u128);

impl MaxChange {
    pub fn parse(raw: &str) -> Result<Self, String> {
        let micros =
            parse_scaled_nonneg_decimal(raw, SCALE_DECIMALS, MAX_CHANGE_MAX_MICROS, "1000000%")
                .map_err(|e| format!("invalid --max-change {raw:?}: {e}"))?;
        Ok(Self(micros))
    }

    /// Returns `Some(percent_change)` if moving from `old` to `new` exceeds `self`,
    /// if either price exceeds the 10,000 USD/1M ceiling, or if arithmetic overflows.
    /// When `old == 0`, populating a previously unpriced (`0`) cache field is allowed
    /// up to `Price::MAX` (10,000 USD/1M).
    pub fn violation(self, old: Price, new: Price) -> Option<f64> {
        if old.0 > MAX_PRICE_MICROS || new.0 > MAX_PRICE_MICROS {
            let pct = if old == Price::ZERO {
                f64::INFINITY
            } else {
                (old.0.abs_diff(new.0) as f64 / old.0 as f64) * 100.0
            };
            return Some(pct);
        }
        if old == new || old == Price::ZERO {
            return None;
        }
        let diff = old.0.abs_diff(new.0);
        // Compare |new - old| / old * 100 > max_change_micros / 1_000_000
        // => diff * 100_000_000 > old * max_change_micros
        let pct = (diff as f64 / old.0 as f64) * 100.0;
        let Some(lhs) = diff.checked_mul(100 * SCALE_FACTOR) else {
            return Some(pct);
        };
        let Some(rhs) = old.0.checked_mul(self.0) else {
            return Some(pct);
        };
        if lhs > rhs {
            Some(pct)
        } else {
            None
        }
    }
}

impl fmt::Display for MaxChange {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        Price(self.0).fmt(f)
    }
}

