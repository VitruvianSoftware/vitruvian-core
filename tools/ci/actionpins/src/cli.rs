//! `actionpins-rs`, with the same subcommands and output as the Go package's
//! command-line probe (//tools/ci/actionpins/goprobe):
//!
//!   check [--manifest PATH] [WORKFLOW_FILE_OR_DIR...]
//!       Generated workflows (those saying `# GENERATED by`) may use only the
//!       manifest's pins, exactly. Directories contribute their *.yaml and
//!       *.yml files. Defaults: the repository's manifest and workflows.
//!       Exit 0 clean, 1 violations (one per stdout line), 2 setup errors.
//!   list PATH              every pin, sorted: `action<TAB>pin`
//!   resolve PATH ACTION    one action's pin; exit 1 if unpinned
//!   default-path           where the manifest is found
//!   parse-lines < lines    each stdin line through the `uses:` parser

use crate::gostd::{self, base, join, path_error, scan_lines, ERR_TOO_LONG};
use crate::{
    check_workflow, find_default_path, find_workflows_dir, is_generated, load, parse_pin_line,
};
use std::io::{self, Read, Write};
use std::os::unix::ffi::OsStrExt;

pub const USAGE: &str = "usage: actionpins check [--manifest PATH] [WORKFLOW_FILE_OR_DIR...]
       actionpins list PATH
       actionpins resolve PATH ACTION
       actionpins default-path
       actionpins parse-lines < lines
";

struct Out {
    stdout: Vec<u8>,
    stderr: Vec<u8>,
}

impl Out {
    fn say(&mut self, code: i32, msg: &[u8]) -> i32 {
        self.stderr.extend_from_slice(b"actionpins: ");
        self.stderr.extend_from_slice(msg);
        self.stderr.push(b'\n');
        code
    }

    fn usage(&mut self) -> i32 {
        self.stderr.extend_from_slice(USAGE.as_bytes());
        2
    }
}

fn check(args: &[Vec<u8>], out: &mut Out) -> i32 {
    let mut manifest: Vec<u8> = Vec::new();
    let mut paths: Vec<Vec<u8>> = Vec::new();
    let mut i = 0;
    while i < args.len() {
        if args[i] == b"--manifest" {
            match args.get(i + 1) {
                Some(m) => manifest = m.clone(),
                None => return out.usage(),
            }
            i += 2;
            continue;
        }
        paths.push(args[i].clone());
        i += 1;
    }
    if manifest.is_empty() {
        match find_default_path() {
            Ok(p) => manifest = p,
            Err(e) => return out.say(2, &e),
        }
    }
    let pins = match load(&manifest) {
        Ok(p) => p,
        Err(e) => return out.say(2, &e),
    };

    if paths.is_empty() {
        match find_workflows_dir() {
            Some(d) => paths.push(d),
            None => return out.say(2, b"failed to find workflows dir: file does not exist"),
        }
    }
    let mut files: Vec<(Vec<u8>, Vec<u8>)> = Vec::new();
    for p in &paths {
        let meta = match std::fs::metadata(gostd::as_path(p)) {
            Ok(m) => m,
            Err(e) => return out.say(2, &path_error("stat", p, &e)),
        };
        if !meta.is_dir() {
            files.push((base(p), p.clone()));
            continue;
        }
        let entries = match std::fs::read_dir(gostd::as_path(p)) {
            Ok(e) => e,
            Err(e) => {
                let mut msg = b"failed to read workflows dir: ".to_vec();
                msg.extend(path_error("open", p, &e));
                return out.say(2, &msg);
            }
        };
        let mut listed: Vec<(Vec<u8>, bool)> = Vec::new();
        for entry in entries.flatten() {
            let is_dir = entry.file_type().map(|t| t.is_dir()).unwrap_or(false);
            listed.push((entry.file_name().as_bytes().to_vec(), is_dir));
        }
        listed.sort();
        for (name, is_dir) in listed {
            if is_dir || !(name.ends_with(b".yaml") || name.ends_with(b".yml")) {
                continue;
            }
            let path = join(&[p, &name]);
            files.push((name, path));
        }
    }

    let mut checked = 0;
    let mut violations = 0;
    for (name, path) in &files {
        let text = match read_file(path) {
            Ok(t) => t,
            Err(e) => {
                let mut msg = b"failed to read ".to_vec();
                msg.extend_from_slice(path);
                msg.extend_from_slice(b": ");
                msg.extend(e);
                return out.say(2, &msg);
            }
        };
        if !is_generated(&text) {
            continue;
        }
        checked += 1;
        for problem in check_workflow(name, &text, &pins) {
            out.stdout.extend(problem);
            out.stdout.push(b'\n');
            violations += 1;
        }
    }
    if checked == 0 {
        return out.say(
            1,
            b"no generated workflows were checked; expected at least delivery-*.yaml and presubmit.yaml",
        );
    }
    if violations > 0 {
        return out.say(
            1,
            format!("{violations} violation(s) in {checked} generated workflow(s)").as_bytes(),
        );
    }
    let mut msg = format!(
        "{checked} generated workflow(s) use only the {} pins in ",
        pins.all().len()
    )
    .into_bytes();
    msg.extend_from_slice(&manifest);
    out.say(0, &msg)
}

/// `os.ReadFile`, with Go's error text.
fn read_file(path: &[u8]) -> Result<Vec<u8>, Vec<u8>> {
    let mut file =
        std::fs::File::open(gostd::as_path(path)).map_err(|e| path_error("open", path, &e))?;
    let mut data = Vec::new();
    file.read_to_end(&mut data)
        .map_err(|e| path_error("read", path, &e))?;
    Ok(data)
}

fn list(args: &[Vec<u8>], out: &mut Out) -> i32 {
    if args.len() != 1 {
        return out.usage();
    }
    match load(&args[0]) {
        Err(e) => out.say(2, &e),
        Ok(pins) => {
            for (action, pin) in pins.all() {
                out.stdout.extend_from_slice(action);
                out.stdout.push(b'\t');
                out.stdout.extend_from_slice(pin);
                out.stdout.push(b'\n');
            }
            0
        }
    }
}

fn resolve(args: &[Vec<u8>], out: &mut Out) -> i32 {
    if args.len() != 2 {
        return out.usage();
    }
    let pins = match load(&args[0]) {
        Ok(p) => p,
        Err(e) => return out.say(2, &e),
    };
    match pins.lookup(&args[1]) {
        Ok(pin) => {
            out.stdout.extend_from_slice(pin);
            out.stdout.push(b'\n');
            0
        }
        Err(e) => {
            out.stderr.extend(e);
            out.stderr.push(b'\n');
            1
        }
    }
}

fn default_path(out: &mut Out) -> i32 {
    match find_default_path() {
        Ok(p) => {
            out.stdout.extend(p);
            out.stdout.push(b'\n');
            0
        }
        Err(e) => out.say(2, &e),
    }
}

fn parse_lines(input: &[u8], out: &mut Out) -> i32 {
    let (lines, too_long) = scan_lines(input);
    for (n, line) in lines.iter().enumerate() {
        let n = n + 1;
        match parse_pin_line(line) {
            Err(e) => {
                out.stdout
                    .extend_from_slice(format!("{n}\terr\t").as_bytes());
                out.stdout.extend(e);
            }
            Ok(None) => out
                .stdout
                .extend_from_slice(format!("{n}\tnone").as_bytes()),
            Ok(Some(p)) => {
                out.stdout
                    .extend_from_slice(format!("{n}\tpin\t").as_bytes());
                out.stdout.extend(p.action);
                out.stdout.push(b'\t');
                out.stdout.extend(p.pin);
            }
        }
        out.stdout.push(b'\n');
    }
    if too_long {
        out.stdout
            .extend_from_slice(format!("scan error: {ERR_TOO_LONG}\n").as_bytes());
    }
    0
}

/// Run with `args` (no program name); the exit status.
pub fn run(args: &[Vec<u8>]) -> i32 {
    let mut out = Out {
        stdout: Vec::new(),
        stderr: Vec::new(),
    };
    let rest = args.get(1..).unwrap_or(&[]);
    let code = match args.first().map(Vec::as_slice) {
        Some(b"check") => check(rest, &mut out),
        Some(b"list") => list(rest, &mut out),
        Some(b"resolve") => resolve(rest, &mut out),
        Some(b"default-path") => default_path(&mut out),
        Some(b"parse-lines") => {
            let mut input = Vec::new();
            let _ = io::stdin().read_to_end(&mut input);
            parse_lines(&input, &mut out)
        }
        _ => out.usage(),
    };
    let _ = io::stdout().write_all(&out.stdout);
    let _ = io::stdout().flush();
    let _ = io::stderr().write_all(&out.stderr);
    code
}
