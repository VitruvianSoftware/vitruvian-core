"""actionpins-rs against the Go actionpins package, side by side.

goprobe is a small Go program that calls the package (Load, Lookup,
ParsePinLine, FindDefaultPath) and runs the Go test's workflow check, with
the same subcommands and output as actionpins-rs. Every case runs through
both, and exit code, stdout and stderr must match byte for byte:

  - the repository's real manifest (//:pins_manifest) and workflows
    (//:workflow_files): list, resolve every action, check them all
  - about 140,000 synthetic `uses:` lines (prefixes, spacing, actions, refs and
    comments in combination, invalid UTF-8, control and Unicode space
    characters) plus every real line mutated at random, through the parser
  - manifests: the real one with each line mutated, duplicates, bad refs,
    CRLF, bufio.Scanner's 64 KiB line limit on both sides, unreadable,
    missing, a directory
  - workflow trees: real generated workflows with pins changed, comments
    changed, actions added, the marker removed, odd directory entries
  - default lookups through BUILD_WORKSPACE_DIRECTORY, TEST_SRCDIR and the
    working directory, including a symlinked $PWD
"""

import concurrent.futures
import os
import random
import shutil
import subprocess
import tempfile
import unittest

SHA = "3d3c42e5aac5ba805825da76410c181273ba90b1"


def runfile(name):
    return os.path.abspath(os.environ[name])


class Parity(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.go = runfile("ACTIONPINS_GO")
        cls.rs = runfile("ACTIONPINS_RS")
        cls.manifest = runfile("PINS_MANIFEST")
        cls.workflows = [
            os.path.abspath(p) for p in os.environ["WORKFLOW_FILES"].split()
        ]
        cls.tmp = tempfile.mkdtemp()
        cls.pool = concurrent.futures.ThreadPoolExecutor(
            max_workers=os.cpu_count() or 4
        )
        with open(cls.manifest, "rb") as f:
            cls.manifest_bytes = f.read()
        cls.generated = []
        for p in cls.workflows:
            with open(p, "rb") as f:
                data = f.read()
            if b"# GENERATED by" in data:
                cls.generated.append((os.path.basename(p), data))
        assert cls.generated, "no generated workflows among //:workflow_files"

    @classmethod
    def tearDownClass(cls):
        cls.pool.shutdown()
        subprocess.run(["chmod", "-R", "u+rwx", cls.tmp])
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def run_both(self, args, stdin=None, env=None, cwd=None):
        env = env if env is not None else {"PATH": "/usr/bin:/bin"}
        out = []
        for binary in (self.go, self.rs):
            p = subprocess.run(
                [binary] + list(args),
                input=stdin,
                env=env,
                cwd=cwd or self.tmp,
                capture_output=True,
                timeout=120,
            )
            out.append((p.returncode, p.stdout, p.stderr))
        return out[0], out[1]

    def same(self, args, stdin=None, env=None, cwd=None, label=None):
        go, rs = self.run_both(args, stdin, env, cwd)
        self.assertEqual(rs, go, label or args)
        return go

    def mkdir(self):
        return tempfile.mkdtemp(dir=self.tmp)

    def write(self, path, data, mode=None):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
        if mode is not None:
            os.chmod(path, mode)
        return path

    # -- the generated table --------------------------------------------------

    def test_print_tables_is_current(self):
        got = subprocess.run(
            [self.go, "print-tables"], capture_output=True, check=True
        ).stdout
        here = os.path.dirname(os.path.abspath(__file__))
        with open(os.path.join(here, "src", "goprint.rs"), "rb") as f:
            self.assertEqual(
                got, f.read(), "regenerate src/goprint.rs with goprobe print-tables"
            )

    # -- the repository's own files ---------------------------------------------

    def test_real_manifest_and_workflows(self):
        go = self.same(["list", self.manifest])
        self.assertEqual(go[0], 0)
        actions = [line.split(b"\t")[0] for line in go[1].splitlines()]
        self.assertGreater(len(actions), 10)
        for action in actions + [b"unknown/action", b"actions/checkout@x", b""]:
            self.same(["resolve", self.manifest, action])
        go = self.same(["check", "--manifest", self.manifest] + self.workflows)
        self.assertEqual(go[0], 0, go)  # what the Go test asserts
        print("real:", len(actions), "pins;", go[2].decode().strip())
        for p in self.workflows:
            self.same(["check", "--manifest", self.manifest, p])
        text = self.manifest_bytes + b"\n" + b"\n".join(d for _, d in self.generated)
        self.same(["parse-lines"], stdin=text)

    # -- ParsePinLine ---------------------------------------------------------------

    def synthetic_lines(self):
        prefixes = [
            b"",
            b" ",
            b"\t",
            b"    - ",
            b"-",
            b"- ",
            b"\f",
            b"\r",
            b"\v",
            " ".encode(),
            b"- -",
        ]
        keywords = [b"uses:", b"uses :", b"Uses:", b"uses"]
        spacers = [b"", b" ", b"\t"]
        actions = [
            b"actions/checkout",
            b"a",
            b"./local",
            b"/abs",
            b"a@b",
            "é/x".encode(),
            b"\xff",
            b"x\x7f",
            b'a"b',
            b"a\\b",
            b"x\x01y",
            "​".encode(),
        ]
        refs = [
            SHA.encode(),
            SHA.upper().encode(),
            SHA[:39].encode(),
            (SHA + "0").encode(),
            b"v4",
            b"main",
            (SHA + "@x").encode(),
            b"",
            b"#",
            "é".encode() * 20,
        ]
        tails = [
            b"",
            b" # v1",
            b"#v1",
            b"  #   v1  ",
            b" # ",
            b" ",
            b" trailing",
            b"\t# v1\t",
            b" # v1 # v2",
            " # v1　".encode(),
            b" # \xff",
            b" #\v v1 \v",
            b" # \xe2\x80",
        ]
        out = []
        for p in prefixes:
            for k in keywords:
                for s in spacers:
                    for a in actions:
                        for r in refs:
                            for t in tails:
                                out.append(p + k + s + a + b"@" + r + t)
        return out

    def mutate(self, rng, line, n):
        line = bytearray(line)
        alphabet = b" \t\r\f\v#@-:/.aZ09\x00\x7f\xff\xc3\xa9\xe2\x80\x8b"
        for _ in range(n):
            op = rng.random()
            at = rng.randint(0, len(line))
            if op < 0.4 or not line:
                line[at:at] = bytes([rng.choice(alphabet)])
            elif op < 0.7:
                del line[min(at, len(line) - 1)]
            else:
                line[min(at, len(line) - 1)] = rng.choice(alphabet)
        return bytes(line).replace(b"\n", b"")

    def test_parse_pin_line(self):
        rng = random.Random(20261025)
        lines = self.synthetic_lines()
        real = self.manifest_bytes.split(b"\n")
        for _, data in self.generated:
            real += [line for line in data.split(b"\n") if b"uses" in line]
        uses = [line for line in real if b"uses" in line]
        for _ in range(20000):
            lines.append(self.mutate(rng, rng.choice(uses), rng.randint(1, 4)))
        stdin = b"\n".join(lines) + b"\n"
        go = self.same(["parse-lines"], stdin=stdin, label="parse-lines corpus")
        kinds = {}
        for rec in go[1].split(b"\n")[:-1]:
            kind = rec.split(b"\t")[1]
            kinds[kind] = kinds.get(kind, 0) + 1
        print(
            "parse-lines:",
            len(lines),
            "lines",
            {k.decode(): v for k, v in kinds.items()},
        )
        self.assertGreater(kinds.get(b"pin", 0), 3000)
        self.assertGreater(kinds.get(b"err", 0), 5000)
        # CRLF, and bufio.Scanner's 64 KiB limit either side of the line.
        self.same(
            ["parse-lines"],
            stdin=b"- uses: a@" + SHA.encode() + b" # v1\r\n\r\nx\r\r\n",
        )
        for n in range(65532, 65539):
            for tail in (b"", b"\n", b"\r\n", b"\nuses: a@b\n"):
                self.same(
                    ["parse-lines"],
                    stdin=b"uses: a@b\n" + b"x" * n + tail,
                    label=(n, tail),
                )

    # -- Load ----------------------------------------------------------------------

    def test_load(self):
        rng = random.Random(7)
        d = self.mkdir()
        cases = []
        lines = self.manifest_bytes.split(b"\n")
        for i in range(len(lines)):
            for k in range(6):
                mutated = list(lines)
                mutated[i] = self.mutate(rng, lines[i], rng.randint(1, 3))
                cases.append(b"\n".join(mutated))
        pin = b"    - uses: actions/checkout@" + SHA.encode() + b" # v7.0.1\n"
        cases += [
            b"",
            b"\n",
            b"# only a comment\nruns:\n  steps: []\n",
            pin + pin,
            pin + b"    - uses: actions/checkout@" + SHA.encode() + b" # v8\n",
            pin + b"    - uses: actions/setup-go@v4 # tag\n",
            self.manifest_bytes.replace(b"\n", b"\r\n"),
            self.manifest_bytes.rstrip(b"\n"),
            b"\xef\xbb\xbf" + self.manifest_bytes,
            pin + b"x" * 65535 + b"\n" + pin.replace(b"checkout", b"cache"),
            pin + b"x" * 65536 + b"\n" + pin.replace(b"checkout", b"cache"),
            pin + b"x" * 65536,
            b"- uses: bad@ref\n" + b"x" * 70000,
            b"x" * 70000 + b"\n" + pin,
            b"- uses: ./local@"
            + SHA.encode()
            + b"\n- uses: \xff\x01@"
            + SHA.encode()
            + b" # \xe2\x80\x8b v\n",
        ]
        paths = [
            self.write(os.path.join(d, "m%d.yml" % i), c) for i, c in enumerate(cases)
        ]
        paths.append(os.path.join(d, "missing.yml"))
        paths.append(d)
        paths.append(self.write(os.path.join(d, "locked.yml"), pin, 0o000))
        loop = os.path.join(d, "loop.yml")
        os.symlink(loop, loop)
        paths.append(loop)
        paths.append(os.path.join(d, "m0.yml", "under-a-file"))
        results = list(self.pool.map(lambda p: (p, self.run_both(["list", p])), paths))
        failures = [(p, go, rs) for p, (go, rs) in results if go != rs]
        codes = {}
        for _, (go, _) in results:
            codes[go[0]] = codes.get(go[0], 0) + 1
        print("load:", len(paths), "manifests, exit codes", codes)
        self.assertEqual(failures[:5], [])
        self.assertGreater(codes.get(0, 0), 50)
        self.assertGreater(codes.get(2, 0), 40)
        for action in [b"actions/checkout", b"actions/cache", b"nope", b"\xff\x01"]:
            for p in paths[-12:]:
                self.same(["resolve", p, action])

    # -- the workflow check -----------------------------------------------------------

    def test_check_workflows(self):
        rng = random.Random(11)
        trees = []
        for name, data in self.generated:
            lines = data.split(b"\n")
            uses_at = [i for i, line in enumerate(lines) if b"uses:" in line]
            edits = [
                lambda ls: ls,
                lambda ls: [line.replace(SHA.encode()[:6], b"ffffff") for line in ls],
                lambda ls: [
                    line.split(b" #")[0] if b"uses:" in line else line for line in ls
                ],
                lambda ls: [line.replace(b"# v", b"# V") for line in ls],
                lambda ls: ls + [b"      - uses: someone/unpinned@" + SHA.encode()],
                lambda ls: (
                    ls + [b"      - uses: ./.github/actions/local@" + SHA.encode()]
                ),
                lambda ls: ls + [b"      - uses: actions/checkout@v4"],
                lambda ls: [
                    line.replace(b"# GENERATED by", b"# generated by") for line in ls
                ],
                lambda ls: ls[:3] + [b"x" * 70000] + ls[3:],
                lambda ls: [line + b"\r" for line in ls],
            ]
            for edit in edits:
                trees.append((name, b"\n".join(edit(list(lines)))))
            for _ in range(40):
                mutated = list(lines)
                for i in rng.sample(uses_at, min(len(uses_at), rng.randint(1, 3))):
                    mutated[i] = self.mutate(rng, mutated[i], rng.randint(1, 3))
                trees.append((name, b"\n".join(mutated)))

        def check_tree(item):
            i, (name, data) = item
            d = self.mkdir()
            self.write(os.path.join(d, name), data)
            return self.run_both(["check", "--manifest", self.manifest, d])

        results = list(self.pool.map(check_tree, enumerate(trees)))
        failures = [
            (trees[i][0], go, rs) for i, (go, rs) in enumerate(results) if go != rs
        ]
        codes = {}
        for go, _ in results:
            codes[go[0]] = codes.get(go[0], 0) + 1
        print("check:", len(trees), "workflow trees, exit codes", codes)
        self.assertEqual(failures[:3], [])
        self.assertGreater(codes.get(1, 0), 100)

        # Directory entries: only *.yaml / *.yml files, sorted; a directory
        # named like one is skipped, a symlink to one is read (and fails).
        d = self.mkdir()
        name, data = self.generated[0]
        self.write(os.path.join(d, "b.yaml"), data)
        self.write(os.path.join(d, "a.yml"), data.replace(SHA.encode()[:4], b"0000"))
        self.write(os.path.join(d, "c.txt"), b"# GENERATED by\n- uses: x/y@v1\n")
        self.write(
            os.path.join(d, "Z.yaml"),
            b"# GENERATED by\n- uses: x/y@" + SHA.encode() + b"\n",
        )
        os.makedirs(os.path.join(d, "dir.yaml"))
        self.same(["check", "--manifest", self.manifest, d])
        os.symlink(os.path.join(d, "dir.yaml"), os.path.join(d, "link.yaml"))
        self.same(["check", "--manifest", self.manifest, d])
        self.write(os.path.join(d, "locked.yaml"), data, 0o000)
        self.same(["check", "--manifest", self.manifest, d])
        empty = self.mkdir()
        self.same(["check", "--manifest", self.manifest, empty])
        self.same(
            [
                "check",
                "--manifest",
                self.manifest,
                os.path.join(d, "b.yaml"),
                os.path.join(d, "Z.yaml"),
            ]
        )
        self.same(["check", "--manifest", self.manifest, os.path.join(d, "missing")])
        self.same(["check", "--manifest", os.path.join(d, "missing"), d])
        locked_dir = self.mkdir()
        os.chmod(locked_dir, 0)
        self.same(["check", "--manifest", self.manifest, locked_dir])
        os.chmod(locked_dir, 0o755)

    # -- defaults ---------------------------------------------------------------------

    def test_default_lookups(self):
        repo = self.mkdir()
        self.write(
            os.path.join(repo, ".github", "actions", "pins", "action.yml"),
            self.manifest_bytes,
        )
        for name, data in self.generated:
            self.write(os.path.join(repo, ".github", "workflows", name), data)
        deep = os.path.join(repo, "a", "b", "c")
        os.makedirs(deep)
        alias = os.path.join(self.tmp, "alias-%d" % os.getpid())
        os.symlink(repo, alias)
        bare = self.mkdir()
        runfiles = self.mkdir()
        shutil.copytree(
            os.path.join(repo, ".github"), os.path.join(runfiles, "ws", ".github")
        )
        shutil.copytree(
            os.path.join(repo, ".github"), os.path.join(runfiles, ".github")
        )
        base = {"PATH": "/usr/bin:/bin"}
        envs = [
            ({}, repo),
            ({}, deep),
            ({}, bare),
            ({"BUILD_WORKSPACE_DIRECTORY": repo}, bare),
            ({"BUILD_WORKSPACE_DIRECTORY": repo + "/"}, bare),
            ({"BUILD_WORKSPACE_DIRECTORY": bare}, deep),
            ({"BUILD_WORKSPACE_DIRECTORY": ""}, deep),
            ({"TEST_SRCDIR": runfiles, "TEST_WORKSPACE": "ws"}, bare),
            ({"TEST_SRCDIR": runfiles}, bare),
            ({"TEST_SRCDIR": runfiles, "TEST_WORKSPACE": "nope"}, bare),
            ({"TEST_SRCDIR": runfiles, "BUILD_WORKSPACE_DIRECTORY": repo}, bare),
            ({"PWD": alias + "/a/b/c"}, deep),
            ({"PWD": "/nonexistent"}, deep),
            ({"PWD": "relative"}, deep),
            # filepath.Join cleans: "..", "." and doubled slashes.
            ({"BUILD_WORKSPACE_DIRECTORY": deep + "/../../.."}, bare),
            ({"BUILD_WORKSPACE_DIRECTORY": repo + "//a/./../"}, bare),
            ({"BUILD_WORKSPACE_DIRECTORY": os.path.relpath(repo, bare)}, bare),
            ({"BUILD_WORKSPACE_DIRECTORY": "../" + os.path.basename(repo)}, bare),
            ({"TEST_SRCDIR": runfiles + "/x/..", "TEST_WORKSPACE": "./ws/"}, bare),
            (
                {
                    "TEST_SRCDIR": runfiles,
                    "TEST_WORKSPACE": "../" + os.path.basename(runfiles) + "/ws",
                },
                bare,
            ),
            ({"PWD": alias + "/a/b/c/../c"}, deep),
            ({"PWD": alias + "//a/./b/c"}, deep),
        ]
        for extra, cwd in envs:
            env = dict(base, **extra)
            for args in (
                ["default-path"],
                ["check"],
                ["check", "--manifest", self.manifest],
            ):
                self.same(args, env=env, cwd=cwd, label=(args, extra, cwd))

    def test_usage(self):
        for args in [
            [],
            ["bogus"],
            ["list"],
            ["list", "a", "b"],
            ["resolve", "x"],
            ["check", "--manifest"],
            ["print"],
        ]:
            self.same(args)


