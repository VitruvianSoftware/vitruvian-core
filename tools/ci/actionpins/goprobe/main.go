// Command goprobe drives the Go actionpins package from the command line, with
// the same subcommands and output as the Rust port (actionpins-rs), so the
// parity test can hold the two to the same answers. The check subcommand is
// TestGeneratedWorkflowsOnlyUseManifestPins as a program.
//
//	goprobe check [--manifest PATH] [WORKFLOW_FILE_OR_DIR...]
//	goprobe list PATH
//	goprobe resolve PATH ACTION
//	goprobe default-path
//	goprobe parse-lines < lines
//	goprobe print-tables > tools/ci/actionpins/src/goprint.rs
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/VitruvianSoftware/vitruvian-core/tools/ci/actionpins"
)

const usage = `usage: actionpins check [--manifest PATH] [WORKFLOW_FILE_OR_DIR...]
       actionpins list PATH
       actionpins resolve PATH ACTION
       actionpins default-path
       actionpins parse-lines < lines
`

// say prints an "actionpins: ..." line on stderr and returns code.
func say(code int, format string, args ...any) int {
	fmt.Fprintf(os.Stderr, "actionpins: "+format+"\n", args...)
	return code
}

// findWorkflowsDir is the Go test's lookup of .github/workflows.
func findWorkflowsDir() (string, error) {
	relPath := filepath.Join(".github", "workflows")
	if srcdir := os.Getenv("TEST_SRCDIR"); srcdir != "" {
		ws := os.Getenv("TEST_WORKSPACE")
		if ws == "" {
			ws = "_main"
		}
		candidates := []string{
			filepath.Join(srcdir, ws, relPath),
			filepath.Join(srcdir, relPath),
		}
		for _, c := range candidates {
			if fi, err := os.Stat(c); err == nil && fi.IsDir() {
				return c, nil
			}
		}
	}
	if ws := os.Getenv("BUILD_WORKSPACE_DIRECTORY"); ws != "" {
		candidate := filepath.Join(ws, relPath)
		if fi, err := os.Stat(candidate); err == nil && fi.IsDir() {
			return candidate, nil
		}
	}
	dir, err := os.Getwd()
	if err == nil {
		for {
			candidate := filepath.Join(dir, relPath)
			if fi, err := os.Stat(candidate); err == nil && fi.IsDir() {
				return candidate, nil
			}
			parent := filepath.Dir(dir)
			if parent == dir {
				break
			}
			dir = parent
		}
	}
	return "", os.ErrNotExist
}

func check(args []string) int {
	manifest := ""
	var paths []string
	for i := 0; i < len(args); i++ {
		if args[i] == "--manifest" {
			if i+1 >= len(args) {
				fmt.Fprint(os.Stderr, usage)
				return 2
			}
			manifest = args[i+1]
			i++
			continue
		}
		paths = append(paths, args[i])
	}
	if manifest == "" {
		p, err := actionpins.FindDefaultPath()
		if err != nil {
			return say(2, "%v", err)
		}
		manifest = p
	}
	pins, err := actionpins.Load(manifest)
	if err != nil {
		return say(2, "%v", err)
	}
	allPins := pins.All()

	if len(paths) == 0 {
		d, err := findWorkflowsDir()
		if err != nil {
			return say(2, "failed to find workflows dir: %v", err)
		}
		paths = []string{d}
	}
	type workflow struct{ name, path string }
	var files []workflow
	for _, p := range paths {
		fi, err := os.Stat(p)
		if err != nil {
			return say(2, "%v", err)
		}
		if !fi.IsDir() {
			files = append(files, workflow{filepath.Base(p), p})
			continue
		}
		entries, err := os.ReadDir(p)
		if err != nil {
			return say(2, "failed to read workflows dir: %v", err)
		}
		for _, entry := range entries {
			if entry.IsDir() || (!strings.HasSuffix(entry.Name(), ".yaml") && !strings.HasSuffix(entry.Name(), ".yml")) {
				continue
			}
			files = append(files, workflow{entry.Name(), filepath.Join(p, entry.Name())})
		}
	}

	checkedCount := 0
	violations := 0
	report := func(format string, args ...any) {
		fmt.Printf(format+"\n", args...)
		violations++
	}
	for _, f := range files {
		content, err := os.ReadFile(f.path)
		if err != nil {
			return say(2, "failed to read %s: %v", f.path, err)
		}
		text := string(content)
		if !strings.Contains(text, "# GENERATED by") {
			continue
		}
		checkedCount++
		scanner := bufio.NewScanner(strings.NewReader(text))
		lineNo := 0
		for scanner.Scan() {
			lineNo++
			line := scanner.Text()
			action, parsedPin, err := actionpins.ParsePinLine(line)
			if err != nil {
				report("%s:%d: invalid action pin syntax: %v", f.name, lineNo, err)
				continue
			}
			if action == "" {
				continue
			}
			if strings.HasPrefix(action, ".") || strings.HasPrefix(action, "/") {
				continue
			}
			manifestPin, ok := allPins[action]
			if !ok {
				report("%s:%d: unpinned third-party action %q in generated workflow (must be added to .github/actions/pins/action.yml)", f.name, lineNo, action)
				continue
			}
			if parsedPin != manifestPin {
				report("%s:%d: mismatched pin for action %q in %s:\n  got:  %s\n  want: %s", f.name, lineNo, action, f.name, parsedPin, manifestPin)
			}
		}
	}
	if checkedCount == 0 {
		return say(1, "no generated workflows were checked; expected at least delivery-*.yaml and presubmit.yaml")
	}
	if violations > 0 {
		return say(1, "%d violation(s) in %d generated workflow(s)", violations, checkedCount)
	}
	return say(0, "%d generated workflow(s) use only the %d pins in %s", checkedCount, len(allPins), manifest)
}

func list(args []string) int {
	if len(args) != 1 {
		fmt.Fprint(os.Stderr, usage)
		return 2
	}
	pins, err := actionpins.Load(args[0])
	if err != nil {
		return say(2, "%v", err)
	}
	all := pins.All()
	keys := make([]string, 0, len(all))
	for k := range all {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Printf("%s\t%s\n", k, all[k])
	}
	return 0
}

func resolve(args []string) int {
	if len(args) != 2 {
		fmt.Fprint(os.Stderr, usage)
		return 2
	}
	pins, err := actionpins.Load(args[0])
	if err != nil {
		return say(2, "%v", err)
	}
	pin, err := pins.Lookup(args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	fmt.Println(pin)
	return 0
}

func defaultPath() int {
	p, err := actionpins.FindDefaultPath()
	if err != nil {
		return say(2, "%v", err)
	}
	fmt.Println(p)
	return 0
}

func parseLines() int {
	scanner := bufio.NewScanner(os.Stdin)
	w := bufio.NewWriter(os.Stdout)
	defer w.Flush()
	n := 0
	for scanner.Scan() {
		n++
		action, pin, err := actionpins.ParsePinLine(scanner.Text())
		switch {
		case err != nil:
			fmt.Fprintf(w, "%d\terr\t%v\n", n, err)
		case action == "":
			fmt.Fprintf(w, "%d\tnone\n", n)
		default:
			fmt.Fprintf(w, "%d\tpin\t%s\t%s\n", n, action, pin)
		}
	}
	if err := scanner.Err(); err != nil {
		fmt.Fprintf(w, "scan error: %v\n", err)
	}
	return 0
}

// printTables writes the Rust table of the runes strconv.IsPrint accepts
// (what %q leaves unescaped) and of unicode.IsSpace (what strings.TrimSpace
// trims).
func printTables() int {
	w := bufio.NewWriter(os.Stdout)
	defer w.Flush()
	fmt.Fprint(w, licenseHeader)
	fmt.Fprintf(w, "// GENERATED by `bazel run //tools/ci/actionpins/goprobe -- print-tables` from Go's\n")
	fmt.Fprintf(w, "// strconv and unicode packages (Unicode %s). Do not edit.\n\n", unicode.Version)
	ranges := func(name, doc string, in func(rune) bool) {
		fmt.Fprintf(w, "/// %s\n", doc)
		fmt.Fprintf(w, "pub const %s: &[(u32, u32)] = &[\n", name)
		start := rune(-1)
		for r := rune(0); r <= unicode.MaxRune+1; r++ {
			ok := r <= unicode.MaxRune && in(r)
			if ok && start < 0 {
				start = r
			} else if !ok && start >= 0 {
				fmt.Fprintf(w, "    (0x%04X, 0x%04X),\n", start, r-1)
				start = -1
			}
		}
		fmt.Fprintf(w, "];\n")
	}
	ranges("PRINTABLE", "Inclusive ranges of the runes strconv.IsPrint accepts.", strconv.IsPrint)
	fmt.Fprintln(w)
	ranges("SPACE", "Inclusive ranges of the runes unicode.IsSpace accepts.", unicode.IsSpace)
	return 0
}

