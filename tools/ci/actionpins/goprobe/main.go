func main() {
	if len(os.Args) < 2 {
		fmt.Fprint(os.Stderr, usage)
		os.Exit(2)
	}
	args := os.Args[2:]
	var code int
	switch os.Args[1] {
	case "check":
		code = check(args)
	case "list":
		code = list(args)
	case "resolve":
		code = resolve(args)
	case "default-path":
		code = defaultPath()
	case "parse-lines":
		code = parseLines()
	case "print-tables":
		code = printTables()
	default:
		fmt.Fprint(os.Stderr, usage)
		code = 2
	}
	os.Exit(code)
}
