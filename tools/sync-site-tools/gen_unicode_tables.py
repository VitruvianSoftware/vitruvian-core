"""Writes src/unicode_tables.rs: the two character classes the Rust port of
sync.py gets from Python, so it strips, matches and repr()s the same way.

    python3 tools/sync-site-tools/gen_unicode_tables.py > tools/sync-site-tools/src/unicode_tables.rs

Run it with the Python sync.py runs on under Bazel (3.12).
sync_site_tools_rs_parity_test regenerates the file and fails when it
differs, so a Python whose Unicode data moved shows up as a failing test.
"""

import re
import sys
import unicodedata

with open(__file__, encoding="utf-8") as _own:
    HERE_LICENSE = _own.read().split('"""', 1)[0]


def ranges(test):
    out, start = [], None
    for c in range(0x110000):
        if test(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, pairs, what):
    # One pair a line: the layout rustfmt gives it.
    lines = [f"/// {what}", f"pub static {name}: &[(u32, u32)] = &["]
    lines += [f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in pairs]
    lines.append("];")
    return "\n".join(lines)


def render():
    space = re.compile(r"\s")
    spaces = ranges(lambda c: chr(c).isspace())
    if spaces != ranges(lambda c: bool(space.match(chr(c)))):
        raise SystemExit(
            "str.isspace and re's \\s disagree; the port assumes they agree"
        )
    parts = [
        HERE_LICENSE.replace("#!/usr/bin/env python3\n", "")
        .replace("# ", "// ")
        .replace("#\n", "//\n")
        .rstrip(),
        "",
        "// GENERATED by tools/sync-site-tools/gen_unicode_tables.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor}, Unicode "
        f"{unicodedata.unidata_version}. Do not edit by hand.",
        "",
        table("SPACE", spaces, "str.isspace(), which is also re's \\s."),
        "",
        table(
            "PRINTABLE",
            ranges(lambda c: chr(c).isprintable()),
            "str.isprintable(), which decides what repr() escapes.",
        ),
        "",
    ]
    return "\n".join(parts)


if __name__ == "__main__":
    sys.stdout.write(render())
