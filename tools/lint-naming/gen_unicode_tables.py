"""Writes src/unicode_tables.rs: the character classes lint_naming.py gets
from Python, so the Rust port can answer them the same way.

    python3 tools/lint-naming/gen_unicode_tables.py > tools/lint-naming/src/unicode_tables.rs

Run it with the Python the linter runs on under Bazel (3.12).
lint_naming_rs_parity_test regenerates the file and fails when it differs, so
a Python whose Unicode data moved shows up as a failing test, not as a quiet
disagreement.
"""

import re
import sys
import unicodedata

HERE_LICENSE = open(__file__, encoding="utf-8").read().split('"""', 1)[0]


def ranges(test):
    out, start = [], None
    for c in range(0x110000):
        if test(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, pairs, what):
    # One pair a line: the layout rustfmt gives it, so formatting the
    # repository leaves the file as generated.
    lines = [f"/// {what}", f"pub static {name}: &[(u32, u32)] = &["]
    lines += [f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in pairs]
    lines.append("];")
    return "\n".join(lines)


def _surrogate(c):
    return 0xD800 <= c <= 0xDFFF


def render():
    space = re.compile(r"\s")
    digit = re.compile(r"\d")
    spaces = ranges(lambda c: chr(c).isspace())
    if spaces != ranges(lambda c: bool(space.match(chr(c)))):
        raise SystemExit(
            "str.isspace and re's \\s disagree; the port assumes they agree"
        )
    decimal = ranges(lambda c: bool(digit.match(chr(c))))
    if decimal != ranges(lambda c: chr(c).isdecimal()):
        raise SystemExit(
            "re's \\d and str.isdecimal disagree; the port assumes they agree"
        )
    # int() reads a digit as its distance from the start of its run of ten.
    for lo, hi in decimal:
        for c in range(lo, hi + 1):
            if unicodedata.decimal(chr(c)) != (c - lo) % 10:
                raise SystemExit(f"U+{c:04X}: decimal digits are not in runs of ten")
    parts = [
        HERE_LICENSE.replace("#!/usr/bin/env python3\n", "")
        .replace("# ", "// ")
        .replace("#\n", "//\n")
        .rstrip(),
        "",
        "// GENERATED by tools/lint-naming/gen_unicode_tables.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor}, Unicode "
        f"{unicodedata.unidata_version}. Do not edit by hand.",
        "",
        table("SPACE", spaces, "str.isspace(), which is also re's \\s."),
        "",
        table(
            "DECIMAL", decimal, "re's \\d and str.isdecimal(), in runs counting from 0."
        ),
        "",
        table("DIGIT", ranges(lambda c: chr(c).isdigit()), "str.isdigit()."),
        "",
        table(
            "PRINTABLE",
            ranges(lambda c: chr(c).isprintable()),
            "str.isprintable(), which decides what repr() escapes.",
        ),
        "",
        table(
            "XID_START",
            ranges(lambda c: not _surrogate(c) and chr(c).isidentifier()),
            "Characters a Python identifier may start with.",
        ),
        "",
        table(
            "XID_CONTINUE",
            ranges(lambda c: not _surrogate(c) and ("a" + chr(c)).isidentifier()),
            "Characters a Python identifier may continue with.",
        ),
        "",
    ]
    return "\n".join(parts)


if __name__ == "__main__":
    sys.stdout.write(render())
