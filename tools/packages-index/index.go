package main

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	// BeginMarker marks the start of the generated table block in packages/README.md.
	BeginMarker = "<!-- BEGIN GENERATED: packages index -->"
	// EndMarker marks the end of the generated table block in packages/README.md.
	EndMarker = "<!-- END GENERATED -->"
	// GeneratedComment warns readers not to edit the generated section manually.
	GeneratedComment = "<!-- Generated by //tools/packages-index from packages/**/catalog-info.yaml. Do not edit by hand; run `bazel run //tools/packages-index -- --write`. -->"
	// ReadmeRelPath is the repository-relative path to the packages index README.
	ReadmeRelPath = "packages/README.md"
)

var languageTags = map[string]struct{}{
	"rust":       {},
	"swift":      {},
	"go":         {},
	"typescript": {},
	"kotlin":     {},
	"javascript": {},
	"python":     {},
	"cpp":        {},
}

var skippedDirs = map[string]struct{}{
	"node_modules": {},
	"testdata":     {},
	"vendor":       {},
	"target":       {},
}

type catalogDoc struct {
	Kind     string `yaml:"kind"`
	Metadata struct {
		Name        string            `yaml:"name"`
		Description string            `yaml:"description"`
		Tags        []string          `yaml:"tags"`
		Annotations map[string]string `yaml:"annotations"`
	} `yaml:"metadata"`
	Spec struct {
		Type  string `yaml:"type"`
		Owner string `yaml:"owner"`
	} `yaml:"spec"`
}

// PackageEntry holds one indexed library row extracted from a catalog-info.yaml document.
type PackageEntry struct {
	Name        string
	ReadmeLink  string
	Description string
	Languages   string
	BazelTarget string
	Owner       string
	CatalogPath string
}

// DiscoverPackages walks packages/ under repoRoot and returns every Component with
// spec.type == "library", sorted by package name.
func DiscoverPackages(repoRoot string) ([]PackageEntry, error) {
	packagesRoot := filepath.Join(repoRoot, "packages")
	info, statErr := os.Stat(packagesRoot)
	if statErr != nil {
		return nil, fmt.Errorf("stat %s: %w", packagesRoot, statErr)
	}
	if !info.IsDir() {
		return nil, fmt.Errorf("%s is not a directory", packagesRoot)
	}

	var catalogFiles []string
	walkErr := filepath.WalkDir(packagesRoot, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		name := d.Name()
		if d.IsDir() {
			if path != packagesRoot && shouldSkipDir(name) {
				return filepath.SkipDir
			}
			return nil
		}
		if name == "catalog-info.yaml" {
			catalogFiles = append(catalogFiles, path)
		}
		return nil
	})
	if walkErr != nil {
		return nil, fmt.Errorf("walk %s: %w", packagesRoot, walkErr)
	}
	sort.Strings(catalogFiles)

	var entries []PackageEntry
	seenNames := make(map[string]string)

	for _, absPath := range catalogFiles {
		relCatalog, relErr := filepath.Rel(repoRoot, absPath)
		if relErr != nil {
			return nil, fmt.Errorf("relative path for %s: %w", absPath, relErr)
		}
		relCatalog = filepath.ToSlash(relCatalog)

		raw, readErr := os.ReadFile(absPath)
		if readErr != nil {
			return nil, fmt.Errorf("read %s: %w", relCatalog, readErr)
		}

		docs, decodeErr := decodeCatalogDocs(raw)
		if decodeErr != nil {
			return nil, fmt.Errorf("parse %s: %w", relCatalog, decodeErr)
		}

		catalogDir := filepath.Dir(absPath)
		for _, doc := range docs {
			if doc.Kind != "Component" || doc.Spec.Type != "library" {
				continue
			}
			name := strings.TrimSpace(doc.Metadata.Name)
			if name == "" {
				return nil, fmt.Errorf("%s: library Component has empty metadata.name", relCatalog)
			}
			if prev, dup := seenNames[name]; dup {
				return nil, fmt.Errorf("duplicate library package name %q in %s and %s", name, prev, relCatalog)
			}
			seenNames[name] = relCatalog

			entries = append(entries, PackageEntry{
				Name:        name,
				ReadmeLink:  resolveReadmeLink(packagesRoot, catalogDir, doc.Metadata.Annotations),
				Description: normalizeWhitespace(doc.Metadata.Description),
				Languages:   extractLanguages(doc.Metadata.Tags),
				BazelTarget: formatBazelTargets(doc.Metadata.Annotations["vitruvian.dev/bazel-target"]),
				Owner:       strings.TrimSpace(doc.Spec.Owner),
				CatalogPath: relCatalog,
			})
		}
	}

	sort.Slice(entries, func(i, j int) bool {
		if entries[i].Name != entries[j].Name {
			return entries[i].Name < entries[j].Name
		}
		return entries[i].CatalogPath < entries[j].CatalogPath
	})

	return entries, nil
}

func shouldSkipDir(name string) bool {
	if strings.HasPrefix(name, ".") || strings.HasPrefix(name, "bazel-") {
		return true
	}
	_, skip := skippedDirs[name]
	return skip
}

func decodeCatalogDocs(raw []byte) ([]catalogDoc, error) {
	dec := yaml.NewDecoder(bytes.NewReader(raw))
	var docs []catalogDoc
	for {
		var doc catalogDoc
		err := dec.Decode(&doc)
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, err
		}
		if doc.Kind == "" && doc.Metadata.Name == "" && doc.Spec.Type == "" {
			continue
		}
		docs = append(docs, doc)
	}
	return docs, nil
}

func resolveReadmeLink(packagesRoot, catalogDir string, annotations map[string]string) string {
	targetDir := catalogDir
	if ref, ok := annotations["backstage.io/techdocs-ref"]; ok {
		ref = strings.TrimSpace(ref)
		if strings.HasPrefix(ref, "dir:") {
			relRef := strings.TrimSpace(strings.TrimPrefix(ref, "dir:"))
			if relRef != "" {
				cand := filepath.Clean(filepath.Join(catalogDir, filepath.FromSlash(relRef)))
				if isWithinDir(packagesRoot, cand) && isRegularFile(filepath.Join(cand, "README.md")) {
					targetDir = cand
				}
			}
		}
	}

	readmePath := filepath.Join(targetDir, "README.md")
	rel, err := filepath.Rel(packagesRoot, readmePath)
	if err != nil {
		return "./README.md"
	}
	return "./" + filepath.ToSlash(rel)
}

func isWithinDir(root, candidate string) bool {
	rel, err := filepath.Rel(root, candidate)
	if err != nil {
		return false
	}
	if rel == "." {
		return true
	}
	return rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

func isRegularFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

func normalizeWhitespace(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

func extractLanguages(tags []string) string {
	seen := make(map[string]struct{}, len(tags))
	var langs []string
	for _, raw := range tags {
		tag := strings.ToLower(strings.TrimSpace(raw))
		if _, ok := languageTags[tag]; !ok {
			continue
		}
		if _, dup := seen[tag]; dup {
			continue
		}
		seen[tag] = struct{}{}
		langs = append(langs, tag)
	}
	return strings.Join(langs, ", ")
}

func formatBazelTargets(raw string) string {
	if strings.TrimSpace(raw) == "" {
		return ""
	}
	parts := strings.Split(raw, ",")
	var formatted []string
	for _, part := range parts {
		target := strings.TrimSpace(part)
		if target == "" {
			continue
		}
		formatted = append(formatted, "`"+escapeTableCell(target)+"`")
	}
	return strings.Join(formatted, ", ")
}

func escapeTableCell(s string) string {
	return strings.ReplaceAll(s, "|", "\\|")
}

// RenderGeneratedSection builds the Markdown block between BeginMarker and EndMarker.
func RenderGeneratedSection(entries []PackageEntry) string {
	var b strings.Builder
	b.WriteString(BeginMarker)
	b.WriteByte('\n')
	b.WriteString(GeneratedComment)
	b.WriteString("\n\n")
	b.WriteString("| Package | What it gives you | Languages | Depend on it | Owner |\n")
	b.WriteString("| --- | --- | --- | --- | --- |\n")
	for _, entry := range entries {
		fmt.Fprintf(
			&b,
			"| [%s](%s) | %s | %s | %s | %s |\n",
			escapeTableCell(entry.Name),
			entry.ReadmeLink,
			escapeTableCell(entry.Description),
			escapeTableCell(entry.Languages),
			entry.BazelTarget,
			escapeTableCell(entry.Owner),
		)
	}
	b.WriteString(EndMarker)
	return b.String()
}

// ReplaceGeneratedSection replaces the region from BeginMarker through EndMarker
// (inclusive) while preserving all surrounding hand-written content byte-for-byte.
func ReplaceGeneratedSection(existing, generated string) (string, error) {
	beginCount := strings.Count(existing, BeginMarker)
	if beginCount == 0 {
		return "", fmt.Errorf("missing marker %q in %s", BeginMarker, ReadmeRelPath)
	}
	if beginCount > 1 {
		return "", fmt.Errorf("found %d occurrences of %q in %s (expected 1)", beginCount, BeginMarker, ReadmeRelPath)
	}

	endCount := strings.Count(existing, EndMarker)
	if endCount == 0 {
		return "", fmt.Errorf("missing marker %q in %s", EndMarker, ReadmeRelPath)
	}
	if endCount > 1 {
		return "", fmt.Errorf("found %d occurrences of %q in %s (expected 1)", endCount, EndMarker, ReadmeRelPath)
	}

	beginIdx := strings.Index(existing, BeginMarker)
	endIdx := strings.Index(existing, EndMarker)
	if endIdx < beginIdx {
		return "", fmt.Errorf("%q appears before %q in %s", EndMarker, BeginMarker, ReadmeRelPath)
	}

	return existing[:beginIdx] + generated + existing[endIdx+len(EndMarker):], nil
}

// FormatDriftDiff produces a compact line diff between actual and expected content.
func FormatDriftDiff(actual, expected string) string {
	actualLines := strings.Split(actual, "\n")
	expectedLines := strings.Split(expected, "\n")

	actualSet := make(map[string]struct{}, len(actualLines))
	for _, line := range actualLines {
		actualSet[line] = struct{}{}
	}
	expectedSet := make(map[string]struct{}, len(expectedLines))
	for _, line := range expectedLines {
		expectedSet[line] = struct{}{}
	}

	const maxLines = 20
	var diff []string
	for _, line := range actualLines {
		if _, ok := expectedSet[line]; !ok {
			diff = append(diff, "- "+line)
		}
	}
	for _, line := range expectedLines {
		if _, ok := actualSet[line]; !ok {
			diff = append(diff, "+ "+line)
		}
	}
	if len(diff) > maxLines {
		omitted := len(diff) - maxLines
		diff = append(diff[:maxLines], fmt.Sprintf("... (%d more differing line(s))", omitted))
	}
	return strings.Join(diff, "\n")
}

// Run executes check or write mode against repoRoot and returns a process exit code.
func Run(repoRoot string, writeMode bool, stdout, stderr io.Writer) int {
	entries, err := DiscoverPackages(repoRoot)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "packages-index: %v\n", err)
		return 1
	}

	readmePath := filepath.Join(repoRoot, filepath.FromSlash(ReadmeRelPath))
	existingBytes, err := os.ReadFile(readmePath)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "packages-index: read %s: %v\n", ReadmeRelPath, err)
		return 1
	}
	existing := string(existingBytes)

	rendered := RenderGeneratedSection(entries)
	expected, err := ReplaceGeneratedSection(existing, rendered)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "packages-index: %v\n", err)
		return 1
	}

	if writeMode {
		if existing != expected {
			if err := os.WriteFile(readmePath, []byte(expected), 0o644); err != nil {
				_, _ = fmt.Fprintf(stderr, "packages-index: write %s: %v\n", ReadmeRelPath, err)
				return 1
			}
			_, _ = fmt.Fprintf(stdout, "packages-index: updated %s (%d packages)\n", ReadmeRelPath, len(entries))
			return 0
		}
		_, _ = fmt.Fprintf(stdout, "packages-index: %s is already up to date (%d packages)\n", ReadmeRelPath, len(entries))
		return 0
	}

	if existing == expected {
		_, _ = fmt.Fprintf(stdout, "packages-index: %s is up to date (%d packages)\n", ReadmeRelPath, len(entries))
		return 0
	}

	_, _ = fmt.Fprintf(stderr, "packages-index: drift detected in %s\n", ReadmeRelPath)
	if diff := FormatDriftDiff(existing, expected); diff != "" {
		_, _ = fmt.Fprintln(stderr, diff)
	}
	_, _ = fmt.Fprintln(stderr, "run: bazel run //tools/packages-index -- --write")
	return 1
}
