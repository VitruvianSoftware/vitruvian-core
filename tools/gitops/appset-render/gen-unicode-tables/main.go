func ranges(name, doc string, pred func(rune) bool) {
	fmt.Printf("\n/// %s\n", doc)
	fmt.Printf("pub static %s: &[(u32, u32)] = &[\n", name)
	start := rune(-1)
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		in := r <= unicode.MaxRune && pred(r)
		if in && start < 0 {
			start = r
		}
		if !in && start >= 0 {
			fmt.Printf("    (0x%04X, 0x%04X),\n", start, r-1)
			start = -1
		}
	}
	fmt.Println("];")
}

func main() {
	fmt.Printf(header, runtime.Version(), unicode.Version)
	for _, table := range os.Args[1:] {
		switch table {
		case "letter":
			ranges("LETTER", "unicode.IsLetter: inclusive code-point ranges.", unicode.IsLetter)
		case "digit":
			ranges("DIGIT", "unicode.IsDigit: inclusive code-point ranges.", unicode.IsDigit)
		case "print":
			ranges("PRINT", "strconv.IsPrint: inclusive code-point ranges.", strconv.IsPrint)
		case "upper":
			fmt.Println("\n/// unicode.ToUpper where it changes the rune: (from, to), sorted.")
			fmt.Println("pub static TO_UPPER: &[(u32, u32)] = &[")
			for r := rune(0); r <= unicode.MaxRune; r++ {
				if u := unicode.ToUpper(r); u != r {
					fmt.Printf("    (0x%04X, 0x%04X),\n", r, u)
				}
			}
			fmt.Println("];")
		default:
			fmt.Fprintf(os.Stderr, "unknown table %q (want letter, digit, print or upper)\n", table)
			os.Exit(2)
		}
	}
}
