// gen-unicode-tables writes the Unicode tables the Rust ports of the Go tools
// need, taken from the Go standard library itself so the two agree on every
// code point. Rust's std has no general-category data and a different case
// mapping, so the ports carry these instead.
//
//	T=//tools/gitops/appset-render/gen-unicode-tables
//	bazel run $T -- letter digit print > tools/gitops/appset-render/src/unicode_tables.rs
//	bazel run $T -- print > tools/copybara/sync/src/unicode_tables.rs
//	bazel run $T -- upper > tools/copybara/conflict-precheck/src/unicode_tables.rs
//
// Re-run with the Go version the repo pins (go.mod) whenever it moves; the
// parity tests compare the ports against the Go binaries and fail if the
// tables fall behind.
