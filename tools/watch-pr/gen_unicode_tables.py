"""Writes src/pyprint.rs: the code points Python's str.isprintable() rejects.

watch-pr.sh's check parser runs under python3 and prints values with str(),
whose repr() of a nested string escapes every character that is not
printable. The Rust port reads this table to escape the same ones.

  python3 tools/watch-pr/gen_unicode_tables.py > tools/watch-pr/src/pyprint.rs

The parity test regenerates it with the pinned interpreter and fails if the
committed file differs.
"""

import sys
import unicodedata

HEADER = (
    open(__file__).read().split('"""', 1)[0].replace("# ", "// ").replace("#\n", "//\n")
)


def ranges():
    out = []
    start = None
    for cp in range(0x80, 0x110000):
        bad = not chr(cp).isprintable()
        if bad and start is None:
            start = cp
        elif not bad and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    rows = ranges()
    w = sys.stdout.write
    w(HEADER)
    w(
        "// GENERATED by tools/watch-pr/gen_unicode_tables.py from Python %d.%d "
        "(Unicode %s). Do not edit.\n\n"
        % (sys.version_info[0], sys.version_info[1], unicodedata.unidata_version)
    )
    w("/// Inclusive ranges of non-ASCII code points str.isprintable() rejects.\n")
    w("pub const NOT_PRINTABLE: &[(u32, u32)] = &[\n")
    for lo, hi in rows:
        w("    (0x%04X, 0x%04X),\n" % (lo, hi))
    w("];\n")


if __name__ == "__main__":
    main()
