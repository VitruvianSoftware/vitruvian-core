"""Writes src/unicode_tables.rs: the character classes release_scope.py gets
from Python, so the Rust port can answer them the same way.

    python3 tools/release-scope/gen_unicode_tables.py > tools/release-scope/src/unicode_tables.rs

Run it with the Python the check runs on (3.12). release_scope_rs_parity_test
regenerates the file and fails when it differs, so a Python whose Unicode
data moved shows up as a failing test, not as a quiet disagreement.
"""

import re
import sys
import unicodedata

HERE_LICENSE = open(__file__, encoding="utf-8").read().split('"""', 1)[0]


def ranges(test):
    out, start = [], None
    for c in range(0x110000):
        if test(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, pairs, what):
    # One pair a line: the layout rustfmt gives it, so formatting the
    # repository leaves the file as generated.
    lines = [f"/// {what}", f"pub static {name}: &[(u32, u32)] = &["]
    lines += [f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in pairs]
    lines.append("];")
    return "\n".join(lines)


def render():
    word = re.compile(r"\w")
    space = re.compile(r"\s")
    spaces = ranges(lambda c: chr(c).isspace())
    if spaces != ranges(lambda c: bool(space.match(chr(c)))):
        raise SystemExit(
            "str.isspace and re's \\s disagree; the port assumes they agree"
        )
    decimal_runs = ranges(lambda c: unicodedata.decimal(chr(c), None) is not None)
    # Each run of decimal digits counts 0 to 9 from its start; the port reads
    # a digit's value as its distance from the start of its run of ten.
    for lo, hi in decimal_runs:
        for c in range(lo, hi + 1):
            if unicodedata.decimal(chr(c)) != (c - lo) % 10:
                raise SystemExit(f"U+{c:04X}: decimal digits are not in runs of ten")
    ignorecase = []
    for letter in dict.fromkeys("releas"):
        pattern = re.compile(re.escape(letter), re.I)
        found = [c for c in range(0x110000) if pattern.fullmatch(chr(c))]
        ignorecase.append(
            f"    ('{letter}', &[{', '.join(f'0x{c:X}' for c in found)}]),"
        )
    parts = [
        HERE_LICENSE.replace("#!/usr/bin/env python3\n", "")
        .replace("# ", "// ")
        .replace("#\n", "//\n")
        .rstrip(),
        "",
        "// GENERATED by tools/release-scope/gen_unicode_tables.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor}, Unicode "
        f"{unicodedata.unidata_version}. Do not edit by hand.",
        "",
        table("SPACE", spaces, "str.isspace(), which is also re's \\s."),
        "",
        table("WORD", ranges(lambda c: bool(word.match(chr(c)))), "re's \\w on a str."),
        "",
        table(
            "PRINTABLE",
            ranges(lambda c: chr(c).isprintable()),
            "str.isprintable(), which decides what repr() escapes.",
        ),
        "",
        table(
            "DECIMAL",
            decimal_runs,
            "Characters int() reads as a digit, in runs counting from 0.",
        ),
        "",
        "/// The characters re.IGNORECASE lets each letter of `release-as` match.",
        "pub static IGNORECASE: &[(char, &[u32])] = &[",
        *ignorecase,
        "];",
        "",
    ]
    return "\n".join(parts)


if __name__ == "__main__":
    sys.stdout.write(render())
