    def test_unwritable_outputs(self):
        units = load_fixtures()

        def out_is_file(root, ws, out):
            shutil.rmtree(out)
            with open(out, "w") as f:
                f.write("x")

        def target_is_dir(root, ws, out):
            os.makedirs(os.path.join(out, "delivery-charts.yaml"))

        def target_unreadable(root, ws, out):
            p = os.path.join(out, "delivery-charts.yaml")
            with open(p, "w") as f:
                f.write(BANNER + "\n")
            os.chmod(p, 0)

        def stale_unreadable(root, ws, out):
            p = os.path.join(out, "delivery-zzz.yaml")
            with open(p, "w") as f:
                f.write(BANNER + "\n")
            os.chmod(p, 0)

        def read_only_dir(root, ws, out):
            os.chmod(out, 0o555)

        cases = [out_is_file, target_is_dir]
        if os.geteuid() != 0:
            cases += [target_unreadable, stale_unreadable, read_only_dir]
        for setup in cases:
            with self.subTest(setup=setup.__name__):
                rc, _, _, _ = self.both(Scenario(units=units, setup=setup))
                self.assertNotEqual(rc, 0)
        # Parent of the out dir is a file: MkdirAll's error.
        rc, _, _, _ = self.both(
            Scenario(
                units=units,
                args=["-out-dir", "{ws}/file/sub"],
                setup=lambda r, w, o: open(os.path.join(w, "file"), "w").close(),
            )
        )
        self.assertNotEqual(rc, 0)


