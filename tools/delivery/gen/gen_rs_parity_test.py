"""Side-by-side parity: the Rust delivery generator against the Go one.

Both binaries run as the real CLI, one after the other, in an identical
scenario rebuilt at the same path: a workspace (with or without an action pin
manifest), an output directory (empty, or seeded with committed, stale,
hand-written and odd files), and a fake `bazel` (GEN_BAZEL) that answers
`query`, `build` and `info bazel-bin` from delivery() JSON laid out like
bazel-bin. For every case the two must agree on the exit code, stdout,
stderr and every byte of every file left behind.

Coverage:
  * the REAL repository: every real delivery() unit, the real pin manifest,
    at the committed phase and the others; the result must also equal the
    committed .github/workflows/delivery-*.yaml, byte for byte;
  * every testdata fixture at phases -1..3, and rendered as one app so the
    output must equal testdata/golden*.yaml;
  * the flags, including Go's flag-package errors and usage text;
  * every refusal in main_test.go, plus malformed JSON, broken pin
    manifests, a failing / missing / killed bazel and unwritable outputs.

Two normalisations, both for output the Go runtime makes non-deterministic:
the goroutine trace under a panic's first line, and the random digits in a
temp file's name.
"""

