def load_fixtures():
    out = []
    for n in FIXTURE_NAMES:
        with open(os.path.join(TESTDATA, "units", n + ".delivery.json"), "rb") as f:
            out.append(json.loads(f.read()))
    return out


def load_real_units():
    """(package, json bytes) for every real delivery() unit."""
    out = []
    for p in REAL_UNITS:
        rel = os.path.relpath(p, RUNFILES)
        pkg, base = os.path.split(rel)
        name = base[: -len(".delivery.json")]
        with open(p, "rb") as f:
            out.append((pkg, name, f.read()))
    return out


def committed_delivery_workflows():
    out = {}
    for name in sorted(os.listdir(WORKFLOWS)):
        if name.startswith("delivery") and name.endswith(".yaml"):
            with open(os.path.join(WORKFLOWS, name), "rb") as f:
                out[name] = f.read()
    return out


class Scenario:
    """Everything one CLI run sees. Built afresh, at the same path, for each
    binary, so every path in every message is identical."""

    def __init__(
        self,
        units=None,
        raw_units=None,
        pins=FIXTURE_PINS,
        pins_text=None,
        out_files=None,
        args=(),
        query_extra="",
        query_override=None,
        rc=None,
        signal=None,
        env=None,
        cwd=None,
        setup=None,
        bazel=None,
        info_override=None,
        out_dir_rel=".github/workflows",
    ):
        # units: list of dicts (json-encoded) or raw: list of (pkg, name, bytes)
        self.units = units
        self.raw_units = raw_units
        self.pins = pins
        self.pins_text = pins_text
        self.out_files = out_files or {}
        self.args = list(args)
        self.query_extra = query_extra
        self.query_override = query_override
        self.rc = rc or {}
        self.signal = signal
        self.env = env or {}
        self.cwd = cwd
        self.setup = setup
        self.bazel = bazel
        self.info_override = info_override
        self.out_dir_rel = out_dir_rel


def build(root, sc):
    if os.path.exists(root):
        make_writable(root)
        shutil.rmtree(root)
    ws = os.path.join(root, "ws")
    binr = os.path.join(root, "bazel-bin")
    fake = os.path.join(root, "fake")
    for d in (ws, binr, fake):
        os.makedirs(d)
    if sc.pins_text is not None:
        os.makedirs(os.path.join(ws, ".github", "actions", "pins"))
        with open(
            os.path.join(ws, ".github", "actions", "pins", "action.yml"), "wb"
        ) as f:
            f.write(
                sc.pins_text
                if isinstance(sc.pins_text, bytes)
                else sc.pins_text.encode()
            )
    elif sc.pins:
        os.makedirs(os.path.join(ws, ".github", "actions", "pins"))
        shutil.copy(
            sc.pins, os.path.join(ws, ".github", "actions", "pins", "action.yml")
        )
    out = os.path.join(ws, sc.out_dir_rel)
    os.makedirs(out, exist_ok=True)
    for name, body in sc.out_files.items():
        p = os.path.join(out, name)
        if body is None:
            os.makedirs(p)
            continue
        with open(p, "wb") as f:
            f.write(body if isinstance(body, bytes) else body.encode())

    labels = []
    raw = list(sc.raw_units or [])
    for i, u in enumerate(sc.units or []):
        name = "u%02d" % i
        body = (
            u
            if isinstance(u, (bytes, str))
            else json.dumps(u, indent=2, ensure_ascii=False)
        )
        raw.append(
            ("pkg/%02d" % i, name, body.encode() if isinstance(body, str) else body)
        )
    for pkg, name, body in raw:
        d = os.path.join(binr, pkg)
        os.makedirs(d, exist_ok=True)
        if body is None:
            pass  # a label whose JSON was never built
        elif body == "DIR":
            os.makedirs(os.path.join(d, name + ".delivery.json"))
        else:
            with open(os.path.join(d, name + ".delivery.json"), "wb") as f:
                f.write(body)
        labels.append("//%s:%s.delivery_unit" % (pkg, name))
        labels.append("//%s:%s.delivery" % (pkg, name))  # filtered out by suffix
    query = "\n".join(labels) + "\n" + sc.query_extra
    if sc.query_override is not None:
        query = sc.query_override
    with open(os.path.join(fake, "query.txt"), "w") as f:
        f.write(query)
    info = sc.info_override if sc.info_override is not None else binr + "\n"
    with open(os.path.join(fake, "info.txt"), "w") as f:
        f.write(info)
    script = ["#!/bin/sh"]
    for verb in ("query", "build", "info"):
        rc = sc.rc.get(verb, 0)
        body = {
            "query": 'cat "%s/query.txt"' % fake,
            "build": "echo building >&2",
            "info": 'cat "%s/info.txt"' % fake,
        }[verb]
        if sc.signal == verb:
            script.append('[ "$1" = %s ] && kill -%s $$' % (verb, "TERM"))
        script.append('if [ "$1" = %s ]; then %s; exit %d; fi' % (verb, body, rc))
    script.append('echo unexpected bazel "$@" >&2; exit 99')
    fb = os.path.join(fake, "bazel")
    with open(fb, "w") as f:
        f.write("\n".join(script) + "\n")
    os.chmod(fb, 0o755)
    if sc.setup:
        sc.setup(root, ws, out)
    return ws, out, fb


def make_writable(root):
    for dp, dns, _ in os.walk(root):
        for d in dns:
            try:
                os.chmod(os.path.join(dp, d), 0o755)
            except OSError:
                pass
    try:
        os.chmod(root, 0o755)
    except OSError:
        pass


def snapshot(root):
    tree = {}
    for dp, dns, fns in os.walk(root):
        dns.sort()
        for d in dns:
            tree[os.path.relpath(os.path.join(dp, d), root) + "/"] = None
        for fn in sorted(fns):
            p = os.path.join(dp, fn)
            rel = os.path.relpath(p, root)
            rel = re.sub(r"\.delivery-gen-\d+", ".delivery-gen-N", rel)
            try:
                with open(p, "rb") as f:
                    tree[rel] = (f.read(), stat.S_IMODE(os.lstat(p).st_mode))
            except OSError as e:
                tree[rel] = ("unreadable", e.errno)
    return tree


def normalize_stderr(s):
    # A Go panic: keep its first line, drop the goroutine trace below it.
    p = s.find(b"panic: ")
    if p == 0 or (p > 0 and s[p - 1 : p] == b"\n"):
        i = s.find(b"\n\ngoroutine ", p)
        if i >= 0:
            s = s[:i] + b"\n"
    return re.sub(rb"\.delivery-gen-\d+", b".delivery-gen-N", s)


ROOT = os.path.join(tempfile.mkdtemp(prefix="gen-parity-"), "s")


def run_one(binary, sc):
    ws, out, fake = build(ROOT, sc)
    env = {
        "PATH": "/usr/bin:/bin",
        "HOME": ROOT,
        "GEN_BAZEL": fake,
        "BUILD_WORKSPACE_DIRECTORY": ws,
    }
    if sc.bazel is not None:
        env.pop("GEN_BAZEL")
        if sc.bazel:
            env["GEN_BAZEL"] = sc.bazel
    for k, v in sc.env.items():
        if v is None:
            env.pop(k, None)
        else:
            env[k] = (
                v.replace("{ws}", ws).replace("{root}", ROOT).replace("{fake}", fake)
            )
    cwd = (sc.cwd or "{ws}").replace("{ws}", ws).replace("{root}", ROOT)
    env["PWD"] = cwd
    args = [a.replace("{ws}", ws).replace("{root}", ROOT) for a in sc.args]
    p = subprocess.run(
        ["gen"] + args,
        executable=binary,
        cwd=cwd,
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=120,
    )
    tree = snapshot(ROOT)
    make_writable(ROOT)
    return p.returncode, p.stdout, normalize_stderr(p.stderr), tree


def diff_trees(a, b):
    lines = []
    for k in sorted(set(a) | set(b)):
        if a.get(k) != b.get(k):
            lines.append(
                "  %s: go=%s rs=%s" % (k, summarize(a.get(k)), summarize(b.get(k)))
            )
    return "\n".join(lines[:20])


def summarize(v):
    if v is None:
        return "<absent/dir>"
    if isinstance(v, tuple) and isinstance(v[0], bytes):
        return "%d bytes mode %o" % (len(v[0]), v[1])
    return repr(v)


class ParityTest(unittest.TestCase):
    maxDiff = None

    def both(self, sc):
        go = run_one(GEN_GO, sc)
        rs = run_one(GEN_RS, sc)
        self.assertEqual(
            go[0],
            rs[0],
            "exit codes differ\ngo stderr: %r\nrs stderr: %r" % (go[2], rs[2]),
        )
        self.assertEqual(
            go[1].decode(errors="replace"),
            rs[1].decode(errors="replace"),
            "stdout differs",
        )
        self.assertEqual(
            go[2].decode(errors="replace"),
            rs[2].decode(errors="replace"),
            "stderr differs",
        )
        self.assertTrue(go[3] == rs[3], "files differ:\n" + diff_trees(go[3], rs[3]))
        return go

    def assertFails(self, sc, needle):
        rc, _, err, _ = self.both(sc)
        self.assertNotEqual(rc, 0, "want a failure containing %r" % needle)
        self.assertIn(needle, err.decode(errors="replace"))

    # ------------------------------------------------------------------
    # The real repository.
    # ------------------------------------------------------------------

    def test_real_repository_matches_committed_workflows(self):
        committed = committed_delivery_workflows()
        generated = {k: v for k, v in committed.items() if BANNER.encode() in v}
        self.assertGreaterEqual(
            len(generated), 6, "expected the committed generated workflows in runfiles"
        )
        units = load_real_units()
        self.assertEqual(len(units), len(REAL_UNITS))

        # Seeded with the committed files: a no-op regenerate, as tidy-check runs it.
        rc, out, err, tree = self.both(
            Scenario(raw_units=units, pins=REAL_PINS, out_files=committed)
        )
        self.assertEqual(rc, 0, err)
        self.assertEqual(out.count(b"unchanged"), len(generated), out)
        self.assertNotIn(b"REGENERATED", out)
        self.assertNotIn(b"REMOVED", out)

        # From empty: every generated workflow must come out byte-identical to
        # the committed one, and no other workflow may appear.
        rc, out, err, tree = self.both(Scenario(raw_units=units, pins=REAL_PINS))
        self.assertEqual(rc, 0, err)
        got = {
            k.split("/")[-1]: v[0]
            for k, v in tree.items()
            if k.startswith("ws/.github/workflows/") and v
        }
        self.assertEqual(sorted(got), sorted(generated))
        for name, body in generated.items():
            self.assertEqual(
                got[name], body, "%s differs from the committed workflow" % name
            )

    def test_real_repository_other_phases(self):
        units = load_real_units()
        for phase in ("0", "1", "3", "-1"):
            with self.subTest(phase=phase):
                rc, _, err, _ = self.both(
                    Scenario(raw_units=units, pins=REAL_PINS, args=["-phase", phase])
                )
                self.assertEqual(rc, 0, err)

