        files["delivery-gone.yaml"] = BANNER + "\nname: delivery-gone\n"
        files["delivery-old.yaml"] = BANNER + "\n"
        files["delivery-notes.yml"] = BANNER + "\n"
        files["deliveryless.yaml"] = BANNER + "\n"
        files["ci.yaml"] = BANNER + "\n"
        files["delivery-dir.yaml"] = None
        files["delivery-charts.yaml"] = BANNER + "\n# stale\n"
        rc, out, err, _ = self.both(
            Scenario(raw_units=load_real_units(), pins=REAL_PINS, out_files=files)
        )
        self.assertEqual(rc, 0, err)
        self.assertIn(b"REMOVED", out)
        self.assertIn(b"REGENERATED", out)

