    def test_phase1_rejections(self):
        companion = {
            "schema": 1,
            "name": "zitadel-apps",
            "kind": "pulumi",
            "run": "//z:up",
            "app": "app",
            "environments": ["development"],
            "github_environment": "app-{env}",
        }

        def with_(**kw):
            u = self.cloud_run_base()
            u.update(kw)
            return u

        def drop_input(k):
            u = self.cloud_run_base()
            del u["workflow_inputs"][k]
            return u

        def add_input(k, v):
            u = self.cloud_run_base()
            u["workflow_inputs"][k] = v
            return u

        other = dict(companion, name="other")
        prod_only = dict(companion, environments=["production"])
        cases = [
            ([with_(companions=["nope"])], "not a declared delivery() unit"),
            ([with_(companions=["other"]), other], "no reusable workflow registered"),
            (
                [with_(companions=["zitadel-apps"]), prod_only],
                'declares no "development" rung',
            ),
            (
                [with_(build_context="")],
                "needs build_context and image_repository_path",
            ),
            ([with_(build="//app:image_push")], "renders the Docker path only"),
            ([drop_input("pulumi-dir")], "missing required workflow_inputs"),
            ([with_(workflow_inputs={})], "missing required workflow_inputs"),
            ([add_input("extra", ["a"])], "is not a scalar"),
            ([add_input("extra", None)], "value is null"),
            (
                [add_input("extra", {"b": [1, None, 0.5, 1e21, True, "s"], "a": {}})],
                "is not a scalar",
            ),
            (
                [add_input("extra", [1e6, 123456, 1234567, 0.0001, 0.00001, -2.5])],
                "is not a scalar",
            ),
        ]
        for units, want in cases:
            with self.subTest(want=want):
                self.assertFails(Scenario(units=units, args=["-phase=1"]), want)
                self.both(Scenario(units=units, args=["-phase=2"]))

