/// One app's units and the workflow file they render into.
#[derive(Clone, Debug)]
pub struct AppGroup {
    pub app: String,
    pub file: String,
    pub units: Vec<Unit>,
}

/// appNameRE: ^[a-z0-9]+(-[a-z0-9]+)*$
fn valid_app_name(s: &str) -> bool {
    !s.is_empty()
        && s.split('-').all(|p| {
            !p.is_empty()
                && p.bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit())
        })
}

/// companionUnitName: "zitadel-apps", ":zitadel-apps" and "//pkg:zitadel-apps"
/// all name the unit "zitadel-apps".
pub fn companion_unit_name(c: &str) -> &str {
    match c.rfind(':') {
        Some(i) => &c[i + 1..],
        None => c,
    }
}

pub fn group_by_app(units: &[Unit]) -> Result<Vec<AppGroup>, String> {
    let by_name: HashMap<&str, &Unit> = units.iter().map(|u| (u.name.as_str(), u)).collect();
    let mut shared_app: HashMap<&str, &Unit> = HashMap::new();
    let mut by_app: BTreeMap<String, Vec<Unit>> = BTreeMap::new();
    for u in units {
        if u.app.is_empty() {
            return Err(format!(
                "unit {} declares no app — delivery(app = ...) names the workflow it delivers through (.github/workflows/{}<app>.yaml)",
                q(&u.name),
                WORKFLOW_FILE_PREFIX
            ));
        }
        if !valid_app_name(&u.app) {
            return Err(format!(
                "unit {}: app {} must be lowercase letters, digits and single dashes — it becomes a file name and a workflow name",
                q(&u.name),
                q(&u.app)
            ));
        }
        if !u.shared_build.is_empty() {
            if let Some(first) = shared_app.get(u.shared_build.as_str()) {
                if first.app != u.app {
                    return Err(format!(
                        "units {} (app {}) and {} (app {}) consume shared build {} — one build job feeds both deploys through `needs:`, which cannot cross workflows, so they must declare the same app",
                        q(&first.name),
                        q(&first.app),
                        q(&u.name),
                        q(&u.app),
                        q(&u.shared_build)
                    ));
                }
            }
            shared_app.insert(u.shared_build.as_str(), u);
        }
        for c in &u.companions {
            if let Some(cu) = by_name.get(companion_unit_name(c)) {
                if cu.app != u.app {
                    return Err(format!(
                        "unit {} (app {}) has companion {} (app {}) — a companion applies inside its consumer's ladder, so it must declare the consumer's app",
                        q(&u.name),
                        q(&u.app),
                        q(&cu.name),
                        q(&cu.app)
                    ));
                }
            }
        }
        by_app.entry(u.app.clone()).or_default().push(u.clone());
    }
    Ok(by_app
        .into_iter()
        .map(|(app, units)| AppGroup {
            file: format!("{}{}.yaml", WORKFLOW_FILE_PREFIX, app),
            app,
            units,
        })
        .collect())
}

/// workflowName: a generated workflow's `name:` is its file's stem.
fn workflow_name(workflow_file: &str) -> &str {
    let e = gostd::ext(workflow_file);
    &workflow_file[..workflow_file.len() - e.len()]
}

fn promotion_note(u: &Unit) -> &str {
    if u.promotion.is_empty() {
        "push-all"
    } else {
        &u.promotion
    }
}

