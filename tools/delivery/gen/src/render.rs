/// A render failure: an ordinary error (the Go renderer's `error`), or the
/// message Go PANICKED with (an unpinned action) — which the CLI must die
/// with the way a Go panic does.
#[derive(Debug, Clone, PartialEq)]
pub enum GenError {
    Msg(String),
    Panic(String),
}

impl GenError {
    pub fn text(&self) -> &str {
        match self {
            GenError::Msg(s) | GenError::Panic(s) => s,
        }
    }
}

impl From<String> for GenError {
    fn from(s: String) -> Self {
        GenError::Msg(s)
    }
}

type R<T = ()> = Result<T, GenError>;

macro_rules! w {
    ($b:expr, $($arg:tt)*) => {{
        $b.push_str(&format!($($arg)*));
    }};
}

macro_rules! fail {
    ($($arg:tt)*) => {
        return Err(GenError::Msg(format!($($arg)*)))
    };
}

