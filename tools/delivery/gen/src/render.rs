//! render: the complete text of one app's .github/workflows/delivery-<app>.yaml.
//!
//! A line-for-line port of main.go's renderer. The WHY of every rendered
//! line — the incidents (#1759, #1763, #1794, #1351, #1607) and the GitHub
//! behaviours each clause defends against — is documented on the Go
//! functions this mirrors (same names, snake_cased); it is not repeated here,
//! because the Go file is the one a reviewer reads next to the generated YAML
//! and two copies of the reasoning would drift. What IS here is the contract:
//! byte-for-byte the same output, and the same error for every declaration
//! the Go renderer refuses (//tools/delivery/gen:gen_rs_parity_test).

