/// What every job renderer needs to know about the FILE it renders into.
pub struct Opts<'a> {
    phase: i64,
    workflow_file: String,
    dispatch: bool,
    release: bool,
    pins: &'a Pins,
}

impl<'a> Opts<'a> {
    fn pin(&self, action: &str) -> R<String> {
        self.pins.lookup(action).map_err(GenError::Panic)
    }
}

fn promotion_units(units: &[Unit]) -> Vec<&Unit> {
    units
        .iter()
        .filter(|u| !u.promotion.is_empty() && u.environments.len() > 1)
        .collect()
}

fn dispatch_units(units: &[Unit]) -> Vec<&Unit> {
    units
        .iter()
        .filter(|u| u.kind == KIND_CLOUD_RUN || !u.render.is_empty())
        .collect()
}

/// dispatchEnvironments: the union of the dispatchable ladders,
/// development/nonproduction first and production last.
pub fn dispatch_environments(units: &[Unit]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for u in dispatch_units(units) {
        for env in &u.environments {
            if !out.contains(env) {
                out.push(env.clone());
            }
        }
    }
    let rank = |env: &str| match env {
        "development" => 0,
        "nonproduction" => 1,
        "production" => 3,
        _ => 2,
    };
    out.sort_by_key(|e| rank(e));
    out
}

