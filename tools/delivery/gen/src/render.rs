fn identity_rung_inputs(u: &Unit, env: &str) -> BTreeMap<String, Value> {
    let mut m = BTreeMap::new();
    m.insert("stack".to_string(), Value::Str(env.to_string()));
    m.insert(
        "gh-environment".to_string(),
        Value::Str(u.github_environment.replace("{env}", env)),
    );
    m
}

