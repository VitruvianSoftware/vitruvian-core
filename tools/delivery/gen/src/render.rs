type TranscribedSteps = fn(&mut String, &Unit, &str, &Opts) -> R;

struct TranscribedSpec {
    timeout_minutes: i64,
    permissions: &'static [&'static str],
    env: &'static [&'static str],
    runs_on: &'static str,
    render_steps: TranscribedSteps,
}

fn transcribed_job(name: &str) -> Option<TranscribedSpec> {
    let spec = |timeout_minutes, permissions, env, runs_on, render_steps| TranscribedSpec {
        timeout_minutes,
        permissions,
        env,
        runs_on,
        render_steps,
    };
    match name {
        "tabula-dev-latest" => Some(spec(
            45,
            &["contents: write"],
            &[],
            "",
            render_tabula_dev_latest_steps,
        )),
        "charts" => Some(spec(
            45,
            &["contents: read", "packages: write"],
            &[],
            "",
            render_charts_publish_steps,
        )),
        "esp32-s3" => Some(spec(
            30,
            &["contents: write"],
            &[],
            "",
            render_esp32_s3_publish_steps,
        )),
        "vitruvian" => Some(spec(
            60,
            &["contents: write"],
            &[],
            "xcode-27",
            render_vitruvian_publish_steps,
        )),
        "gravastar-mouse-publish" => Some(spec(
            45,
            &["contents: write"],
            &[],
            "xcode-27",
            render_gravastar_mouse_publish_steps,
        )),
        "tabula-build-stack" => Some(spec(
            60,
            &["contents: read", "id-token: write"],
            &["GOWORK: off", "GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}"],
            "",
            render_tabula_build_stack_steps,
        )),
        _ => None,
    }
}

