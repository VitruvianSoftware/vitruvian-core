fn render_fan_out(b: &mut String, units: &[Unit], opts: &Opts) -> R {
    let by_name: HashMap<&str, &Unit> = units.iter().map(|u| (u.name.as_str(), u)).collect();
    let mut rendered: HashSet<String> = HashSet::new();
    let consumers = shared_build_consumers(units);

    for u in units {
        if u.kind != KIND_CLOUD_RUN {
            if u.render.is_empty() || opts.phase < 2 {
                continue;
            }
            render_declared_mode_unit(b, u, opts)?;
            continue;
        }
        check_cloud_run_inputs(u)?;
        let mut rungs: &[String] = &u.environments[..1];
        if opts.phase >= 2 {
            if u.environments.len() > 1 && u.promotion.is_empty() {
                fail!(
                    "unit {} declares {} environments and no promotion — every rung would then deliver on a PUSH, i.e. a merge to main would walk into {}. Declare promotion = \"release:<tag-prefix>\", or drop the extra environments",
                    q(&u.name),
                    u.environments.len(),
                    q(&u.environments[u.environments.len() - 1])
                );
            }
            rungs = &u.environments;
        }

        w!(
            b,
            "\n  # ======== unit: {} → {} ========\n",
            u.name,
            rungs.join(" → ")
        );
        w!(
            b,
            "  # Declared in {}/BUILD; break-glass target: {}\n",
            u.package,
            u.run
        );
        w!(
            b,
            "  # GitHub Environments: {} (approvals + keyless-WIF vars live there)\n",
            github_environments(u, rungs).join(", ")
        );
        let prefix = u.promotion.strip_prefix("release:").unwrap_or(&u.promotion);
        if !u.promotion.is_empty() && opts.phase >= 2 {
            w!(
                b,
                "  # Promotion to {}: on a published release tagged {}* (release-please).\n",
                u.environments[1..].join("/"),
                prefix
            );
        } else if !u.promotion.is_empty() {
            w!(
                b,
                "  # Promotion to {}: still the legacy ladder, on {}* (Phase 2 migrates it).\n",
                u.environments[1..].join("/"),
                prefix
            );
        }

        render_changelog_job(b, u)?;

        let (build_job, digest_output) = render_unit_build(b, u, &consumers, &mut rendered, opts)?;

        let mut soak_job = String::new();
        if u.soak && opts.phase >= 2 {
            if u.environments.len() <= SOAK_RUNG {
                fail!(
                    "unit {} declares soak but only {} environment(s) — there is no promotion rung to hold back (delivery() enforces this too)",
                    q(&u.name),
                    u.environments.len()
                );
            }
            soak_job = format!("{}-require-dev-soak", u.name);
        }

        for (i, env) in rungs.iter().enumerate() {
            if i == SOAK_RUNG && !soak_job.is_empty() {
                render_soak_job(b, &soak_job, u, opts)?;
            }
            let companion_jobs =
                render_rung_companions(b, u, &by_name, &mut rendered, i, env, opts)?;
            render_deploy_job(
                b,
                u,
                i,
                env,
                &build_job,
                &digest_output,
                &soak_job,
                &companion_jobs,
                opts,
            )?;
        }
    }
    Ok(())
}

fn github_environments(u: &Unit, rungs: &[String]) -> Vec<String> {
    rungs
        .iter()
        .map(|env| u.github_environment.replace("{env}", env))
        .collect()
}

fn shared_build_consumers(units: &[Unit]) -> HashMap<String, Vec<Unit>> {
    let mut out: HashMap<String, Vec<Unit>> = HashMap::new();
    for u in units {
        if !u.shared_build.is_empty() {
            out.entry(u.shared_build.clone())
                .or_default()
                .push(u.clone());
        }
    }
    out
}

fn render_unit_build(
    b: &mut String,
    u: &Unit,
    consumers: &HashMap<String, Vec<Unit>>,
    rendered: &mut HashSet<String>,
    opts: &Opts,
) -> R<(String, String)> {
    if u.shared_build.is_empty() {
        let job = format!("{}-build", u.name);
        if rendered.contains(&job) {
            return Ok((job, "image-digest".into()));
        }
        rendered.insert(job.clone());
        render_build_job(b, &job, u, opts)?;
        return Ok((job, "image-digest".into()));
    }

    let spec = match shared_build(&u.shared_build) {
        Some(s) => s,
        None => fail!(
            "unit {} declares shared_build {}, which //tools/delivery/gen has no registered build job for — register it in sharedBuilds (a derived-but-unverified build job pushes nothing, and is discovered at deploy time)",
            q(&u.name),
            q(&u.shared_build)
        ),
    };
    if !spec.outputs.contains(&u.image_digest_output.as_str()) {
        fail!(
            "unit {} reads image_digest_output {} from the {} build, which declares [{}] — GitHub resolves an unknown `needs.<job>.outputs.<name>` to the EMPTY STRING, so this would deploy an empty image ref instead of failing",
            q(&u.name),
            q(&u.image_digest_output),
            q(&u.shared_build),
            spec.outputs.join(" ")
        );
    }
    let derived = u.github_environment.replace("{env}", BUILD_RUNG);
    if derived != spec.environment {
        fail!(
            "unit {}'s github_environment {} resolves the build rung to {}, but the {} build job binds {} — one of them is wrong, and a non-existent Environment fails the whole run at startup",
            q(&u.name),
            q(&u.github_environment),
            q(&derived),
            q(&u.shared_build),
            q(spec.environment)
        );
    }

    let job = format!("{}-build", u.shared_build);
    if rendered.contains(&job) {
        return Ok((job, u.image_digest_output.clone()));
    }
    rendered.insert(job.clone());
    let cons = consumers.get(&u.shared_build).cloned().unwrap_or_default();
    render_shared_build_job(b, &job, &u.shared_build, &spec, &cons, opts)?;
    Ok((job, u.image_digest_output.clone()))
}

fn render_shared_build_job(
    b: &mut String,
    job: &str,
    name: &str,
    spec: &SharedBuildSpec,
    consumers: &[Unit],
    opts: &Opts,
) -> R {
    b.push('\n');
    w!(
        b,
        "  # BUILD ONCE for every {} unit, promote by digest: one job pushes the\n",
        name
    );
    b.push_str("  # images into the shared Artifact Registry owned by the build\n");
    b.push_str("  # Environment's project, and every rung of every consuming unit deploys\n");
    b.push_str("  # those immutable @sha256 refs. Rebuilding per environment is what made\n");
    b.push_str("  # what reached production not be the artifact that was smoke-tested.\n");
    w!(b, "  # Consumed by: {}\n", unit_names(consumers).join(", "));
    w!(b, "  {}:\n", job);
    b.push_str("    needs: [orchestrate]\n");
    let cons: Vec<&Unit> = consumers.iter().collect();
    w!(b, "    if: {}\n", build_condition(&cons, opts));
    b.push_str("    concurrency:\n");
    w!(b, "      group: delivery-{}-build\n", name);
    b.push_str("      cancel-in-progress: false\n");
    b.push_str("    runs-on: ubuntu-26.04\n");
    w!(b, "    timeout-minutes: {}\n", spec.timeout_minutes);
    b.push_str("    permissions:\n");
    for p in CALLER_PERMISSIONS {
        w!(b, "      {}\n", p);
    }
    w!(b, "    environment: {}\n", spec.environment);
    b.push_str("    env:\n");
    for e in &spec.env {
        w!(b, "      {}\n", e);
    }
    b.push_str("    outputs:\n");
    for out in spec.outputs {
        w!(
            b,
            "      {}: ${{{{ steps.{}.outputs.{} }}}}\n",
            out,
            shared_build_step_id(out),
            shared_build_step_output(out)
        );
    }
    (spec.render_steps)(b, opts)
}

fn shared_build_step_id(output: &str) -> &str {
    if output == "web-image-digest" {
        "web-image"
    } else {
        "push"
    }
}

fn shared_build_step_output(output: &str) -> &str {
    if output == "web-image-digest" {
        "digest"
    } else {
        output
    }
}

