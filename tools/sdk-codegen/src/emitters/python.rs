const FOLDER: &str = "kits/python/vitruvian_tool_kit/generated";

pub fn header(source: &str) -> String {
    let mut lines: Vec<String> = LICENCE
        .iter()
        .map(|l| pystr::rstrip(&format!("# {}", l)).to_string())
        .collect();
    lines.push(String::new());
    lines.push(format!(
        "# GENERATED by tools/sdk-codegen from {}. Do not edit it:",
        source
    ));
    lines.push("# change the schema, then run".into());
    lines.push("#   bazel run //tools/sdk-codegen".into());
    lines.push(String::new());
    lines.join("\n")
}

/// A name Python can take as an attribute or an argument.
pub fn safe(name: &str) -> String {
    let name = camel_to_snake(name);
    if pystr::is_keyword(&name) {
        format!("{}_", name)
    } else {
        name
    }
}

/// `model.title(name)` where the name may be missing (None).
pub fn title_opt(model: &Model, name: &Option<String>) -> PyResult<String> {
    match name {
        Some(n) => model.title(n),
        None => Err(PyErr::new("KeyError", "None")),
    }
}

fn item(kind: &Type) -> &Type {
    kind.item.as_deref().unwrap()
}

fn py_type(kind: &Type, model: &Model) -> PyResult<String> {
    Ok(match kind.kind {
        Kind::String => "str".into(),
        Kind::Boolean => "bool".into(),
        Kind::Integer => "int".into(),
        Kind::Number => "float".into(),
        Kind::Scalar => "Scalar".into(),
        Kind::Any => "Any".into(),
        Kind::Object => "Dict[str, Any]".into(),
        Kind::Array => format!("List[{}]", py_type(item(kind), model)?),
        Kind::Map => format!("Dict[str, {}]", py_type(item(kind), model)?),
        Kind::Ref => model.title(kind.reference())?,
        Kind::Enum => kind.name().to_string(),
        Kind::Const => format!("Literal[\"{}\"]", kind.values[0].py_str()),
        Kind::Text => format!("Union[str, {}]", model.title(kind.reference())?),
    })
}

fn reader(kind: &Type, value: &str, place: &str, model: &Model) -> PyResult<String> {
    let simple = match kind.kind {
        Kind::String => Some("_string"),
        Kind::Boolean => Some("_boolean"),
        Kind::Integer => Some("_integer"),
        Kind::Number => Some("_number"),
        Kind::Scalar => Some("_scalar"),
        Kind::Any => Some("_any"),
        Kind::Object => Some("_json_object"),
        _ => None,
    };
    if let Some(s) = simple {
        return Ok(format!("{}({}, {})", s, value, place));
    }
    Ok(match kind.kind {
        Kind::Array => {
            let inner = reader(
                item(kind),
                "item",
                &format!("{} + f\"[{{index}}]\"", place),
                model,
            )?;
            format!(
                "[{} for index, item in enumerate(_array({}, {}))]",
                inner, value, place
            )
        }
        Kind::Map => {
            let inner = reader(
                item(kind),
                "item",
                &format!("{} + \".\" + key", place),
                model,
            )?;
            format!(
                "{{key: {} for key, item in _object({}, {}).items()}}",
                inner, value, place
            )
        }
        Kind::Ref => {
            let definition = model.definition(kind.reference())?;
            match &definition.alias {
                Some(alias) => reader(alias, value, place, model)?,
                None => format!("{}.from_json({}, {})", definition.title, value, place),
            }
        }
        Kind::Enum => format!("_one_of({}, {}, {})", value, place, constant(kind.name())),
        Kind::Const => format!(
            "_one_of({}, {}, (\"{}\",))",
            value,
            place,
            kind.values[0].py_str()
        ),
        Kind::Text => format!("_text({}, {})", value, place),
        _ => unreachable!(),
    })
}

fn writer(kind: &Type, value: &str, model: &Model) -> PyResult<String> {
    Ok(match kind.kind {
        Kind::Array => {
            let inner = writer(item(kind), "item", model)?;
            if inner == "item" {
                value.to_string()
            } else {
                format!("[{} for item in {}]", inner, value)
            }
        }
        Kind::Map => {
            let inner = writer(item(kind), "item", model)?;
            if inner == "item" {
                format!("dict({})", value)
            } else {
                format!("{{key: {} for key, item in {}.items()}}", inner, value)
            }
        }
        Kind::Ref => match &model.definition(kind.reference())?.alias {
            None => format!("{}.to_json()", value),
            Some(alias) => writer(alias, value, model)?,
        },
        Kind::Object => format!("dict({})", value),
        _ => value.to_string(),
    })
}

/// Service -> SERVICES, UIEventKind -> UI_EVENT_KINDS.
pub fn constant(enum_name: &str) -> String {
    format!("{}S", pystr::upper(&camel_to_snake(enum_name)))
}

fn ordered(fields: &[crate::model::Field]) -> Vec<&crate::model::Field> {
    fields
        .iter()
        .filter(|f| f.required)
        .chain(fields.iter().filter(|f| !f.required))
        .collect()
}

fn dataclass_field(
    lines: &mut Vec<String>,
    field: &crate::model::Field,
    model: &Model,
) -> PyResult<()> {
    let kind = py_type(&field.ty, model)?;
    if field.required {
        lines.push(format!("    {}: {}", safe(&field.name), kind));
    } else {
        lines.push(format!(
            "    {}: Optional[{}] = None",
            safe(&field.name),
            kind
        ));
    }
    if !field.description.is_empty() {
        lines.push(format!("    \"\"\"{}\"\"\"", field.description));
    }
    Ok(())
}

fn from_json_field(
    lines: &mut Vec<String>,
    field: &crate::model::Field,
    model: &Model,
) -> PyResult<()> {
    let path = format!("where + \".{}\"", field.name);
    let read = reader(
        &field.ty,
        &format!("found[\"{}\"]", field.name),
        &path,
        model,
    )?;
    if field.required {
        let required = reader(
            &field.ty,
            &format!("_required(found, \"{}\", where)", field.name),
            &path,
            model,
        )?;
        lines.push(format!("            {}={},", safe(&field.name), required));
    } else {
        lines.push(format!(
            "            {}=None if found.get(\"{}\") is None else {},",
            safe(&field.name),
            field.name,
            read
        ));
    }
    Ok(())
}

fn to_json_field(
    lines: &mut Vec<String>,
    field: &crate::model::Field,
    model: &Model,
) -> PyResult<()> {
    let value = writer(&field.ty, &format!("self.{}", safe(&field.name)), model)?;
    if field.required {
        lines.push(format!("        out[\"{}\"] = {}", field.name, value));
    } else {
        lines.push(format!(
            "        if self.{} is not None:",
            safe(&field.name)
        ));
        lines.push(format!("            out[\"{}\"] = {}", field.name, value));
    }
    Ok(())
}

fn variant_lines(definition: &Definition, model: &Model) -> PyResult<Vec<String>> {
    let title = &definition.title;
    let tag = definition.tag.clone().unwrap();
    let common: Vec<crate::model::Field> = definition
        .fields
        .iter()
        .filter(|f| f.name != tag)
        .cloned()
        .collect();
    let mut kinds = Vec::new();
    for (_, reference) in &definition.variants {
        kinds.push(model.title(reference)?);
    }
    let mut lines = vec![
        "@dataclass(frozen=True)".to_string(),
        format!("class {}:", title),
    ];
    if !definition.description.is_empty() {
        lines.push(format!("    \"\"\"{}\"\"\"", definition.description));
    }
    lines.push(String::new());
    let tag_field = definition
        .fields
        .iter()
        .find(|f| f.name == tag)
        .ok_or_else(|| PyErr::new("StopIteration", ""))?;
    lines.push(format!("    {}: str", safe(&tag)));
    if !tag_field.description.is_empty() {
        lines.push(format!("    \"\"\"{}\"\"\"", tag_field.description));
    }
    lines.push(format!(
        "    content: Union[{}, Dict[str, Any]]",
        kinds.join(", ")
    ));
    lines.push(format!(
        "    \"\"\"The kind's own fields: the one `{}` names, or, for a kind these types do not have, its fields as they came.\"\"\"",
        tag
    ));
    let order = ordered(&common);
    for field in &order {
        dataclass_field(&mut lines, field, model)?;
    }
    lines.push(String::new());
    lines.push("    @classmethod".into());
    lines.push(format!(
        "    def from_json(cls, value: Any, where: str = \"{}\") -> \"{}\":",
        definition.name, title
    ));
    lines.push("        found = _object(value, where)".into());
    lines.push(format!(
        "        kind = _string(_required(found, \"{}\", where), where + \".{}\")",
        tag, tag
    ));
    lines.push("        content: Any".into());
    for (number, (value, reference)) in definition.variants.iter().enumerate() {
        lines.push(format!(
            "        {} kind == \"{}\":",
            if number == 0 { "if" } else { "elif" },
            value
        ));
        lines.push(format!(
            "            content = {}.from_json(value, where)",
            model.title(reference)?
        ));
    }
    lines.push("        else:".into());
    let mut names = vec![format!("\"{}\"", tag)];
    names.extend(common.iter().map(|f| format!("\"{}\"", f.name)));
    lines.push(format!(
        "            content = {{key: item for key, item in found.items() if key not in ({},)}}",
        names.join(", ")
    ));
    lines.push("        return cls(".into());
    lines.push(format!("            {}=kind,", safe(&tag)));
    lines.push("            content=content,".into());
    for field in &order {
        from_json_field(&mut lines, field, model)?;
    }
    lines.push("        )".into());
    lines.push(String::new());
    lines.push("    def to_json(self) -> Dict[str, Any]:".into());
    lines.push(format!(
        "        out: Dict[str, Any] = {{\"{}\": self.{}}}",
        tag,
        safe(&tag)
    ));
    lines.push(
        "        out.update(dict(self.content) if isinstance(self.content, dict) else self.content.to_json())"
            .into(),
    );
    for field in &common {
        to_json_field(&mut lines, field, model)?;
    }
    lines.push("        return out".into());
    Ok(lines)
}

fn definition_lines(definition: &Definition, model: &Model) -> PyResult<Vec<String>> {
    if !definition.variants.is_empty() {
        return variant_lines(definition, model);
    }
    if let Some(alias) = &definition.alias {
        return Ok(vec![
            format!("{} = {}", definition.title, py_type(alias, model)?),
            if definition.description.is_empty() {
                String::new()
            } else {
                format!("\"\"\"{}\"\"\"", definition.description)
            },
        ]);
    }
    let mut lines = vec![
        "@dataclass(frozen=True)".to_string(),
        format!("class {}:", definition.title),
    ];
    if !definition.description.is_empty() {
        lines.push(format!("    \"\"\"{}\"\"\"", definition.description));
    }
    let order = ordered(&definition.fields);
    if !order.is_empty() {
        lines.push(String::new());
    }
    for field in &order {
        dataclass_field(&mut lines, field, model)?;
    }
    lines.push(String::new());
    lines.push("    @classmethod".into());
    lines.push(format!(
        "    def from_json(cls, value: Any, where: str = \"{}\") -> \"{}\":",
        definition.name, definition.title
    ));
    lines.push("        found = _object(value, where)".into());
    if order.is_empty() {
        lines.push("        return cls()".into());
    } else {
        lines.push("        return cls(".into());
        for field in &order {
            from_json_field(&mut lines, field, model)?;
        }
        lines.push("        )".into());
    }
    lines.push(String::new());
    lines.push("    def to_json(self) -> Dict[str, Any]:".into());
    lines.push("        out: Dict[str, Any] = {}".into());
    for field in &definition.fields {
        to_json_field(&mut lines, field, model)?;
    }
    lines.push("        return out".into());
    Ok(lines)
}

fn quoted(values: &[Value]) -> String {
    values
        .iter()
        .map(|v| format!("\"{}\"", v.py_str()))
        .collect::<Vec<_>>()
        .join(", ")
}

fn enum_lines(e: &Enum) -> Vec<String> {
    let values = quoted(&e.values);
    let mut lines = vec![format!("{} = Literal[{}]", e.name, values)];
    if !e.description.is_empty() {
        lines.push(format!("\"\"\"{}\"\"\"", e.description));
    }
    lines.push(format!(
        "{}: Tuple[str, ...] = ({},)",
        constant(&e.name),
        values
    ));
    lines
}

fn finish(parts: &[String]) -> String {
    format!("{}\n", parts.join("\n\n").trim_end_matches('\n'))
}

fn messages_file(model: &Model) -> PyResult<String> {
    let mut parts = vec![header("protocol/messages.schema.json"), SHAPES.to_string()];
    for e in &model.enums {
        parts.push(format!("{}\n", enum_lines(e).join("\n")));
    }
    for d in &model.messages {
        parts.push(format!("{}\n", definition_lines(d, model)?.join("\n")));
    }
    Ok(finish(&parts))
}

fn kinds_of(field: &crate::model::Field) -> Vec<&Type> {
    let mut out = vec![&field.ty];
    if let Some(i) = field.ty.item.as_deref() {
        out.push(i);
    }
    out
}

fn manifest_file(model: &Model) -> PyResult<String> {
    let mut used: BTreeSet<String> = BTreeSet::new();
    let messages: Vec<&str> = model.messages.iter().map(|d| d.name.as_str()).collect();
    for definition in &model.manifest {
        for field in &definition.fields {
            for kind in kinds_of(field) {
                if kind.kind == Kind::Enum {
                    used.insert(kind.name().to_string());
                    used.insert(constant(kind.name()));
                }
                if matches!(kind.kind, Kind::Ref | Kind::Text)
                    && messages.contains(&kind.reference())
                {
                    used.insert(model.title(kind.reference())?);
                }
                if kind.kind == Kind::Text {
                    used.insert("_text".into());
                    used.insert("Union".into());
                }
                if kind.kind == Kind::Boolean {
                    used.insert("_boolean".into());
                }
                if kind.kind == Kind::Number {
                    used.insert("_number".into());
                }
            }
        }
    }
    for n in [
        "Any",
        "Dict",
        "List",
        "Literal",
        "Optional",
        "dataclass",
        "_array",
        "_integer",
        "_any",
        "_object",
        "_one_of",
        "_required",
        "_string",
    ] {
        used.insert(n.to_string());
    }
    let names: Vec<String> = used.into_iter().collect();
    let mut typing: Vec<&str> = vec!["Any", "Dict", "List", "Literal", "Optional"];
    if names.iter().any(|n| n == "Union") {
        typing.push("Union");
    }
    let mut imports = vec![
        "from __future__ import annotations".to_string(),
        String::new(),
        "from dataclasses import dataclass".into(),
        format!("from typing import {}", typing.join(", ")),
        String::new(),
        "from .messages import (".into(),
    ];
    let skip = [
        "Any",
        "Dict",
        "List",
        "Literal",
        "Optional",
        "Union",
        "dataclass",
    ];
    for name in &names {
        if !skip.contains(&name.as_str()) {
            imports.push(format!("    {},", name));
        }
    }
    imports.push(")".into());
    let mut parts = vec![header("protocol/manifest.schema.json"), imports.join("\n")];
    for d in &model.manifest {
        parts.push(format!("{}\n", definition_lines(d, model)?.join("\n")));
    }
    Ok(finish(&parts))
}

/// `repr(value)` of a str-or-None cell.
fn repr_opt(value: &Option<String>) -> String {
    match value {
        None => "None".into(),
        Some(s) => pystr::repr_str(s),
    }
}

/// Requests and notices a tool sends, grouped by the first part of their name.
pub fn groups(members: &[&Method]) -> PyResult<Vec<(Option<String>, Vec<Method>)>> {
    let mut groups: Vec<(Option<String>, Vec<Method>)> = Vec::new();
    for m in members {
        let path = m.path()?;
        if path.len() > 2 {
            return Err(PyErr::new(
                "ValueError",
                format!("{}: a name of more than two parts", m.method.py_str()),
            ));
        }
        let key = if path.len() == 2 {
            Some(path[0].clone())
        } else {
            None
        };
        match groups.iter_mut().find(|(k, _)| *k == key) {
            Some((_, list)) => list.push((*m).clone()),
            None => groups.push((key, vec![(*m).clone()])),
        }
    }
    Ok(groups)
}

fn truthy(name: &Option<String>) -> Option<&str> {
    name.as_deref().filter(|n| !n.is_empty())
}

fn describe(model: &Model, m: &Method) -> PyResult<String> {
    let what = match truthy(&m.params) {
        Some(p) => model.definition(p)?.description.clone(),
        None => String::new(),
    };
    let mut tail = if m.uses.truthy() {
        format!("Needs `{}` in the manifest's `uses`.", m.uses.py_str())
    } else {
        String::new()
    };
    if m.kind.as_str() == Some("notice") {
        tail = format!(
            "{}A notice: the app does not answer it.",
            if tail.is_empty() {
                String::new()
            } else {
                format!("{} ", tail)
            }
        );
    }
    let rest: Vec<&str> = [what.as_str(), tail.as_str()]
        .into_iter()
        .filter(|t| !t.is_empty())
        .collect();
    Ok(format!("`{}`. {}", m.method.py_str(), rest.join(" ")))
}

fn method_lines(model: &Model, m: &Method, name: &str, indent: &str) -> PyResult<Vec<String>> {
    let mut out = Vec::new();
    let (signature, build);
    if let Some(params) = truthy(&m.params) {
        let fields = &model.definition(params)?.fields;
        let order = ordered(fields);
        let mut arguments = vec!["self".to_string()];
        for field in &order {
            let kind = py_type(&field.ty, model)?;
            arguments.push(if field.required {
                format!("{}: {}", safe(&field.name), kind)
            } else {
                format!("{}: Optional[{}] = None", safe(&field.name), kind)
            });
        }
        signature = arguments.join(", ");
        let assigns: Vec<String> = order
            .iter()
            .map(|f| format!("{}={}", safe(&f.name), safe(&f.name)))
            .collect();
        build = format!("{}({}).to_json()", model.title(params)?, assigns.join(", "));
    } else {
        signature = "self".into();
        build = "None".into();
    }
    let returns = if m.kind.as_str() == Some("request") {
        title_opt(model, &m.result)?
    } else {
        "None".into()
    };
    out.push(format!(
        "{}def {}({}) -> {}:",
        indent,
        safe(name),
        signature,
        returns
    ));
    out.push(format!(
        "{}    \"\"\"{}\"\"\"",
        indent,
        pystr::strip(&describe(model, m)?)
    ));
    if m.kind.as_str() == Some("notice") {
        out.push(format!(
            "{}    self._notice(\"{}\", {})",
            indent,
            m.method.py_str(),
            build
        ));
    } else {
        out.push(format!(
            "{}    return {}.from_json(self._request(\"{}\", {}), \"the answer to {}\")",
            indent,
            title_opt(model, &m.result)?,
            m.method.py_str(),
            build,
            m.method.py_str()
        ));
    }
    Ok(out)
}

fn methods_file(model: &Model) -> PyResult<String> {
    let requests: Vec<&Method> = model
        .methods
        .iter()
        .filter(|m| m.is("tool", "request"))
        .collect();
    let notices: Vec<&Method> = model
        .methods
        .iter()
        .filter(|m| m.is("tool", "notice"))
        .collect();
    let both: Vec<&Method> = requests.iter().chain(notices.iter()).copied().collect();
    let mut titles: BTreeSet<String> = BTreeSet::new();
    for m in &both {
        for n in [&m.params, &m.result] {
            if let Some(n) = truthy(n) {
                titles.insert(model.title(n)?);
            }
        }
    }
    let mut extra: BTreeSet<String> = BTreeSet::new();
    for m in &both {
        if let Some(params) = truthy(&m.params) {
            for field in &model.definition(params)?.fields {
                for kind in kinds_of(field) {
                    if kind.kind == Kind::Ref {
                        extra.insert(model.title(kind.reference())?);
                    }
                    if kind.kind == Kind::Scalar {
                        extra.insert("Scalar".into());
                    }
                    if kind.kind == Kind::Enum {
                        extra.insert(kind.name().to_string());
                    }
                }
            }
        }
    }
    let mut lines = vec![header("protocol/methods.json")];
    for l in [
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from typing import Any, Callable, Dict, List, Optional, Tuple",
        "",
        "from .messages import (",
    ] {
        lines.push(l.into());
    }
    let imported: BTreeSet<String> = titles.union(&extra).cloned().collect();
    for title in &imported {
        lines.push(format!("    {},", title));
    }
    lines.push(")".into());
    lines.push(String::new());
    lines.push(format!(
        "PROTOCOL_VERSION = \"{}\"",
        model.protocol.py_str()
    ));
    for l in [
        "\"\"\"The protocol version this file was made from.\"\"\"",
        "",
        "",
        "@dataclass(frozen=True)",
        "class MethodInfo:",
        "    \"\"\"One message of the protocol: who sends it, whether it is answered, and what it carries.\"\"\"",
        "",
        "    method: str",
        "    sender: str",
        "    kind: str",
        "    uses: Optional[str]",
        "    params: Optional[str]",
        "    result: Optional[str]",
        "",
        "",
        "METHODS: Tuple[MethodInfo, ...] = (",
    ] {
        lines.push(l.into());
    }
    for m in &model.methods {
        let line = format!(
            "    MethodInfo({}, {}, {}, {}, {}, {}),",
            m.method.py_repr(),
            m.sender.py_repr(),
            m.kind.py_repr(),
            m.uses.py_repr(),
            repr_opt(&m.params),
            repr_opt(&m.result)
        );
        lines.push(line.replace('\'', "\""));
    }
    for l in [
        ")",
        "\"\"\"Every message of the protocol, as methods.json lists them.\"\"\"",
        "",
        "Requester = Callable[[str, Optional[Dict[str, Any]]], Any]",
        "\"\"\"Sends a request and returns what its answer carries, or raises.\"\"\"",
        "Noticer = Callable[[str, Dict[str, Any]], None]",
        "\"\"\"Sends a notice.\"\"\"",
    ] {
        lines.push(l.into());
    }
    let grouped = groups(&both)?;
    for (group, members) in &grouped {
        let group = match group {
            None => continue,
            Some(g) => g,
        };
        lines.push(String::new());
        lines.push(String::new());
        lines.push(format!("class _{}:", pystr::capitalize(group)));
        lines.push(format!("    \"\"\"The `{}/...` messages.\"\"\"", group));
        lines.push(String::new());
        lines.push("    def __init__(self, request: Requester, notice: Noticer) -> None:".into());
        lines.push("        self._request = request".into());
        lines.push("        self._notice = notice".into());
        for m in members {
            lines.push(String::new());
            let path = m.path()?;
            lines.extend(method_lines(model, m, &path[1], "    ")?);
        }
    }
    for l in [
        "",
        "",
        "class AppCalls:",
        "    \"\"\"What a tool may ask of the app: one call per message, by its name.\"\"\"",
        "",
        "    def __init__(self, request: Requester, notice: Noticer) -> None:",
        "        self._request = request",
        "        self._notice = notice",
    ] {
        lines.push(l.into());
    }
    for (group, _) in &grouped {
        if let Some(g) = group {
            lines.push(format!(
                "        self.{} = _{}(request, notice)",
                safe(g),
                pystr::capitalize(g)
            ));
        }
    }
    if let Some((_, members)) = grouped.iter().find(|(g, _)| g.is_none()) {
        for m in members {
            lines.push(String::new());
            let path = m.path()?;
            lines.extend(method_lines(model, m, &path[0], "    ")?);
        }
    }
    Ok(format!("{}\n", lines.join("\n")))
}

pub fn emit(model: &Model) -> PyResult<Vec<(String, String)>> {
    let init = format!(
        "{}\"\"\"Types made from the protocol's schemas. See tools/sdk-codegen.\"\"\"\n",
        header("protocol/")
    );
    let messages = messages_file(model)?;
    let manifest = manifest_file(model)?;
    let methods = methods_file(model)?;
    Ok(vec![
        (format!("{}/__init__.py", FOLDER), init),
        (format!("{}/messages.py", FOLDER), messages),
        (format!("{}/manifest.py", FOLDER), manifest),
        (format!("{}/methods.py", FOLDER), methods),
    ])
}

/// The readers messages.py starts with, as python.py writes them.
pub const SHAPES: &str = r##"from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Dict, List, Literal, Optional, Tuple, Union

Scalar = Union[str, bool, int, float]
"""What a preference holds: text, yes or no, or a number."""


class ShapeError(ValueError):
    """A value that is not what its type in the protocol says. `where` names the field."""

    def __init__(self, where: str, wanted: str) -> None:
        super().__init__(f"{where} is not {wanted}")
        self.where = where


def _object(value: Any, where: str) -> Dict[str, Any]:
    if not isinstance(value, dict):
        raise ShapeError(where, "an object")
    return value


def _required(found: Dict[str, Any], key: str, where: str) -> Any:
    if key not in found:
        raise ShapeError(f"{where}.{key}", "there")
    return found[key]


def _string(value: Any, where: str) -> str:
    if not isinstance(value, str):
        raise ShapeError(where, "text")
    return value


def _boolean(value: Any, where: str) -> bool:
    if not isinstance(value, bool):
        raise ShapeError(where, "true or false")
    return value


def _integer(value: Any, where: str) -> int:
    if isinstance(value, bool) or not (isinstance(value, int) or (isinstance(value, float) and value.is_integer())):
        raise ShapeError(where, "a whole number")
    return int(value)


def _number(value: Any, where: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ShapeError(where, "a number")
    return value


def _scalar(value: Any, where: str) -> Scalar:
    if isinstance(value, (str, bool)):
        return value
    return _number(value, where)


def _any(value: Any, where: str) -> Any:
    return value


def _json_object(value: Any, where: str) -> Dict[str, Any]:
    return dict(_object(value, where))


def _array(value: Any, where: str) -> List[Any]:
    if not isinstance(value, list):
        raise ShapeError(where, "a list")
    return value


def _one_of(value: Any, where: str, names: Tuple[str, ...]) -> Any:
    if value not in names:
        raise ShapeError(where, "one of " + ", ".join(names))
    return value


def _text(value: Any, where: str) -> Union[str, Dict[str, str]]:
    if isinstance(value, str):
        return value
    return {key: _string(item, where + "." + key) for key, item in _object(value, where).items()}
"##;
