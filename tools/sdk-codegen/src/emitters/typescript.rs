const FOLDER: &str = "kits/typescript/src/generated";

fn header(source: &str) -> String {
    let mut lines: Vec<String> = LICENCE
        .iter()
        .map(|l| pystr::rstrip(&format!("// {}", l)).to_string())
        .collect();
    lines.push(String::new());
    lines.push(format!(
        "// GENERATED by tools/sdk-codegen from {}. Do not edit it:",
        source
    ));
    lines.push("// change the schema, then run".into());
    lines.push("//   bazel run //tools/sdk-codegen".into());
    lines.push(String::new());
    lines.join("\n")
}

fn doc(text: &str, indent: &str) -> Vec<String> {
    if text.is_empty() {
        Vec::new()
    } else {
        vec![format!("{}/** {} */", indent, text)]
    }
}

fn item(kind: &Type) -> &Type {
    kind.item.as_deref().unwrap()
}

fn ts_type(kind: &Type, model: &Model) -> PyResult<String> {
    Ok(match kind.kind {
        Kind::String => "string".into(),
        Kind::Boolean => "boolean".into(),
        Kind::Integer | Kind::Number => "number".into(),
        Kind::Scalar => "string | boolean | number".into(),
        Kind::Any => "JSONValue".into(),
        Kind::Object => "{ [key: string]: JSONValue }".into(),
        Kind::Array => {
            let inner = ts_type(item(kind), model)?;
            if inner.contains('|') {
                format!("({})[]", inner)
            } else {
                format!("{}[]", inner)
            }
        }
        Kind::Map => format!("{{ [key: string]: {} }}", ts_type(item(kind), model)?),
        Kind::Ref => model.title(kind.reference())?,
        Kind::Enum => kind.name().to_string(),
        Kind::Const => format!("\"{}\"", kind.values[0].py_str()),
        Kind::Text => format!("string | {}", model.title(kind.reference())?),
    })
}

fn reader(kind: &Type, value: &str, place: &str, model: &Model) -> PyResult<String> {
    Ok(match kind.kind {
        Kind::String => format!("expectString({}, {})", value, place),
        Kind::Boolean => format!("expectBoolean({}, {})", value, place),
        Kind::Integer => format!("expectInteger({}, {})", value, place),
        Kind::Number => format!("expectNumber({}, {})", value, place),
        Kind::Scalar => format!("expectScalar({}, {})", value, place),
        Kind::Any => format!("expectJSON({}, {})", value, place),
        Kind::Object => format!("expectJSONObject({}, {})", value, place),
        Kind::Array => {
            let inner = reader(
                item(kind),
                "item",
                &format!("`${{{}}}[${{index}}]`", place),
                model,
            )?;
            format!(
                "expectArray({}, {}).map((item, index) => {})",
                value, place, inner
            )
        }
        Kind::Map => {
            let inner = reader(
                item(kind),
                "item",
                &format!("`${{{}}}.${{key}}`", place),
                model,
            )?;
            format!("expectMap({}, {}, (item, key) => {})", value, place, inner)
        }
        Kind::Ref => format!(
            "read{}({}, {})",
            model.title(kind.reference())?,
            value,
            place
        ),
        Kind::Enum => format!(
            "expectOneOf({}, {}, {})",
            value,
            place,
            constant(kind.name())
        ),
        Kind::Const => format!(
            "expectOneOf({}, {}, [\"{}\"] as const)",
            value,
            place,
            kind.values[0].py_str()
        ),
        Kind::Text => format!(
            "(typeof {} === \"string\" ? {} : read{}({}, {}))",
            value,
            value,
            model.title(kind.reference())?,
            value,
            place
        ),
    })
}

fn constant(enum_name: &str) -> String {
    format!("{}S", pystr::upper(&camel_to_snake(enum_name)))
}

fn object_field(field: &crate::model::Field) -> String {
    format!("object[\"{}\"]", field.name)
}

fn path_of(field: &crate::model::Field) -> String {
    format!("`${{where}}.{}`", field.name)
}

fn variant_lines(definition: &Definition, model: &Model) -> PyResult<Vec<String>> {
    let title = &definition.title;
    let tag = definition.tag.clone().unwrap();
    let common: Vec<&crate::model::Field> =
        definition.fields.iter().filter(|f| f.name != tag).collect();
    let mut lines = vec![format!("/** The fields every kind of {} has. */", title)];
    lines.push(format!("export interface {}Fields {{", title));
    for field in &common {
        lines.extend(doc(&field.description, "  "));
        let mark = if field.required { "" } else { "?" };
        lines.push(format!(
            "  {}{}: {};",
            field.name,
            mark,
            ts_type(&field.ty, model)?
        ));
    }
    lines.push("}".into());
    lines.push(String::new());
    lines.push(format!(
        "/** A {} of a kind these types do not have, from a later protocol: kept as it came. */",
        title
    ));
    lines.push(format!(
        "export interface {}Other extends {}Fields {{",
        title, title
    ));
    lines.push(format!("  {}: string;", tag));
    lines.push("  [key: string]: unknown;".into());
    lines.push("}".into());
    lines.push(String::new());
    lines.extend(doc(&definition.description, ""));
    lines.push(format!("export type {} =", title));
    for (value, reference) in &definition.variants {
        lines.push(format!(
            "  | ({}Fields & {} & {{ {}: \"{}\" }})",
            title,
            model.title(reference)?,
            tag,
            value
        ));
    }
    lines.push(format!("  | {}Other;", title));
    lines.push(String::new());
    lines.push(format!(
        "export function read{}(value: unknown, where = \"{}\"): {} {{",
        title, definition.name, title
    ));
    lines.push("  const object = expectObject(value, where);".into());
    let required: Vec<&&crate::model::Field> = common.iter().filter(|f| f.required).collect();
    if !required.is_empty() {
        lines.push(format!("  const common: {}Fields = {{", title));
        for field in &required {
            lines.push(format!(
                "    {}: {},",
                field.name,
                reader(&field.ty, &object_field(field), &path_of(field), model)?
            ));
        }
        lines.push("  };".into());
    } else {
        lines.push(format!("  const common: {}Fields = {{}};", title));
    }
    for field in &common {
        if field.required {
            continue;
        }
        lines.push(format!(
            "  if (object[\"{}\"] !== undefined) {{",
            field.name
        ));
        lines.push(format!(
            "    common.{} = {};",
            field.name,
            reader(&field.ty, &object_field(field), &path_of(field), model)?
        ));
        lines.push("  }".into());
    }
    lines.push(format!(
        "  const {} = expectString(object[\"{}\"], `${{where}}.{}`);",
        tag, tag, tag
    ));
    lines.push(format!("  switch ({}) {{", tag));
    for (value, reference) in &definition.variants {
        lines.push(format!("    case \"{}\":", value));
        lines.push(format!(
            "      return {{ ...common, ...read{}(value, where), {} }};",
            model.title(reference)?,
            tag
        ));
    }
    lines.push("    default:".into());
    lines.push(format!("      return {{ ...object, ...common, {} }};", tag));
    lines.push("  }".into());
    lines.push("}".into());
    Ok(lines)
}

fn definition_lines(definition: &Definition, model: &Model) -> PyResult<Vec<String>> {
    if !definition.variants.is_empty() {
        return variant_lines(definition, model);
    }
    let title = &definition.title;
    let mut lines = doc(&definition.description, "");
    if let Some(alias) = &definition.alias {
        lines.push(format!(
            "export type {} = {};",
            title,
            ts_type(alias, model)?
        ));
        lines.push(String::new());
        lines.push(format!(
            "export function read{}(value: unknown, where = \"{}\"): {} {{",
            title, definition.name, title
        ));
        lines.push(format!(
            "  return {};",
            reader(alias, "value", "where", model)?
        ));
        lines.push("}".into());
        return Ok(lines);
    }
    if !definition.fields.is_empty() {
        lines.push(format!("export interface {} {{", title));
        for field in &definition.fields {
            lines.extend(doc(&field.description, "  "));
            let mark = if field.required { "" } else { "?" };
            lines.push(format!(
                "  {}{}: {};",
                field.name,
                mark,
                ts_type(&field.ty, model)?
            ));
        }
        lines.push("}".into());
    } else {
        lines.push(format!("export type {} = Record<string, never>;", title));
    }
    lines.push(String::new());
    lines.push(format!(
        "export function read{}(value: unknown, where = \"{}\"): {} {{",
        title, definition.name, title
    ));
    if definition.fields.is_empty() {
        lines.push("  expectObject(value, where);".into());
        lines.push("  return {};".into());
        lines.push("}".into());
        return Ok(lines);
    }
    lines.push("  const object = expectObject(value, where);".into());
    let required: Vec<&crate::model::Field> =
        definition.fields.iter().filter(|f| f.required).collect();
    let optional: Vec<&crate::model::Field> =
        definition.fields.iter().filter(|f| !f.required).collect();
    if !required.is_empty() {
        lines.push(format!("  const read: {} = {{", title));
        for field in &required {
            lines.push(format!(
                "    {}: {},",
                field.name,
                reader(&field.ty, &object_field(field), &path_of(field), model)?
            ));
        }
        lines.push("  };".into());
    } else {
        lines.push(format!("  const read: {} = {{}};", title));
    }
    for field in &optional {
        lines.push(format!(
            "  if (object[\"{}\"] !== undefined) {{",
            field.name
        ));
        lines.push(format!(
            "    read.{} = {};",
            field.name,
            reader(&field.ty, &object_field(field), &path_of(field), model)?
        ));
        lines.push("  }".into());
    }
    lines.push("  return read;".into());
    lines.push("}".into());
    Ok(lines)
}

fn kinds_of(field: &crate::model::Field) -> Vec<&Type> {
    let mut out = vec![&field.ty];
    if let Some(i) = field.ty.item.as_deref() {
        out.push(i);
    }
    out
}

fn shared_titles(model: &Model) -> PyResult<Vec<String>> {
    let names: Vec<&str> = model.messages.iter().map(|d| d.name.as_str()).collect();
    let mut found: BTreeSet<String> = BTreeSet::new();
    for definition in &model.manifest {
        for field in &definition.fields {
            for kind in kinds_of(field) {
                if matches!(kind.kind, Kind::Ref | Kind::Text) && names.contains(&kind.reference())
                {
                    found.insert(model.title(kind.reference())?);
                }
            }
        }
    }
    Ok(found.into_iter().collect())
}

fn enums_used<'a>(definitions: &[Definition], model: &'a Model) -> Vec<&'a Enum> {
    let mut names: Vec<String> = Vec::new();
    for definition in definitions {
        for field in &definition.fields {
            for kind in kinds_of(field) {
                if kind.kind == Kind::Enum && !names.iter().any(|n| n == kind.name()) {
                    names.push(kind.name().to_string());
                }
            }
        }
    }
    model
        .enums
        .iter()
        .filter(|e| names.contains(&e.name))
        .collect()
}

fn quoted(values: &[Value]) -> String {
    values
        .iter()
        .map(|v| format!("\"{}\"", v.py_str()))
        .collect::<Vec<_>>()
        .join(", ")
}

fn enum_lines(e: &Enum) -> Vec<String> {
    let mut lines = doc(&e.description, "");
    lines.push(format!(
        "export const {} = [{}] as const;",
        constant(&e.name),
        quoted(&e.values)
    ));
    lines.push(format!(
        "export type {} = (typeof {})[number];",
        e.name,
        constant(&e.name)
    ));
    lines
}

fn messages_file(model: &Model) -> PyResult<String> {
    let mut parts = vec![header("protocol/messages.schema.json"), SHAPES.to_string()];
    for e in &model.enums {
        parts.push(format!("{}\n", enum_lines(e).join("\n")));
    }
    for d in &model.messages {
        parts.push(format!("{}\n", definition_lines(d, model)?.join("\n")));
    }
    Ok(parts.join("\n"))
}

/// `re.search(rf"\b{name}\(", text)`.
fn calls(text: &str, name: &str) -> bool {
    let needle = format!("{}(", name);
    let mut from = 0;
    while let Some(at) = text[from..].find(&needle) {
        let at = from + at;
        let before = text[..at].chars().next_back();
        if !before.map(pystr::is_word).unwrap_or(false) {
            return true;
        }
        from = at + 1;
    }
    false
}

fn manifest_file(model: &Model) -> PyResult<String> {
    let mut body = Vec::new();
    for d in &model.manifest {
        body.push(format!("{}\n", definition_lines(d, model)?.join("\n")));
    }
    let readers = [
        "expectArray",
        "expectBoolean",
        "expectInteger",
        "expectJSON",
        "expectMap",
        "expectNumber",
        "expectObject",
        "expectOneOf",
        "expectString",
    ];
    let text = body.join("\n");
    let mut names: Vec<String> = readers
        .iter()
        .filter(|n| calls(&text, n))
        .map(|n| n.to_string())
        .collect();
    names.push("type JSONValue".into());
    for e in enums_used(&model.manifest, model) {
        names.push(constant(&e.name));
        names.push(format!("type {}", e.name));
    }
    for title in shared_titles(model)? {
        names.push(format!("read{}", title));
        names.push(format!("type {}", title));
    }
    let mut parts = vec![
        header("protocol/manifest.schema.json"),
        "import {".to_string(),
    ];
    for name in &names {
        parts.push(format!("  {},", name));
    }
    parts.push("} from \"./messages.js\";".into());
    parts.push(String::new());
    parts.extend(body);
    Ok(parts.join("\n"))
}

fn truthy(name: &Option<String>) -> Option<&str> {
    name.as_deref().filter(|n| !n.is_empty())
}

fn signature(model: &Model, m: &Method) -> PyResult<(String, String)> {
    let params = match truthy(&m.params) {
        Some(p) => format!("params: {}", model.title(p)?),
        None => String::new(),
    };
    let returns = if m.kind.as_str() == Some("request") {
        title_opt(model, &m.result)?
    } else {
        "void".into()
    };
    Ok((params, returns))
}

fn describe(model: &Model, m: &Method, indent: &str) -> PyResult<Vec<String>> {
    let what = match truthy(&m.params) {
        Some(p) => model.definition(p)?.description.clone(),
        None => String::new(),
    };
    let mut tail = if m.uses.truthy() {
        format!("Needs `{}` in the manifest's `uses`.", m.uses.py_str())
    } else {
        String::new()
    };
    if m.kind.as_str() == Some("notice") {
        tail = format!(
            "{}A notice: the app does not answer it.",
            if tail.is_empty() {
                String::new()
            } else {
                format!("{} ", tail)
            }
        );
    }
    let rest: Vec<&str> = [what.as_str(), tail.as_str()]
        .into_iter()
        .filter(|t| !t.is_empty())
        .collect();
    let text = format!("`{}`. {}", m.method.py_str(), rest.join(" "));
    Ok(vec![format!("{}/** {} */", indent, pystr::strip(&text))])
}

fn body(model: &Model, m: &Method, name: &str, indent: &str) -> PyResult<String> {
    let (params, _returns) = signature(model, m)?;
    let argument = if truthy(&m.params).is_some() {
        "params"
    } else {
        "undefined"
    };
    if m.kind.as_str() == Some("notice") {
        return Ok(format!(
            "{}{}: ({}) => notice(\"{}\", {}),",
            indent,
            name,
            params,
            m.method.py_str(),
            argument
        ));
    }
    let title = title_opt(model, &m.result)?;
    Ok(format!(
        "{}{}: ({}) => read{}(request(\"{}\", {}), \"the answer to {}\"),",
        indent,
        name,
        params,
        title,
        m.method.py_str(),
        argument,
        m.method.py_str()
    ))
}

fn methods_file(model: &Model) -> PyResult<String> {
    let mut lines = vec![header("protocol/methods.json")];
    let requests: Vec<&Method> = model
        .methods
        .iter()
        .filter(|m| m.is("tool", "request"))
        .collect();
    let notices: Vec<&Method> = model
        .methods
        .iter()
        .filter(|m| m.is("tool", "notice"))
        .collect();
    let both: Vec<&Method> = requests.iter().chain(notices.iter()).copied().collect();
    let mut names: BTreeSet<String> = BTreeSet::new();
    for m in &both {
        for n in [&m.params, &m.result] {
            if let Some(n) = truthy(n) {
                names.insert(model.title(n)?);
            }
        }
    }
    lines.push("import {".into());
    for title in &names {
        lines.push(format!("  type {},", title));
    }
    let mut results: BTreeSet<String> = BTreeSet::new();
    for m in &requests {
        results.insert(title_opt(model, &m.result)?);
    }
    for title in &results {
        lines.push(format!("  read{},", title));
    }
    for l in [
        "} from \"./messages.js\";",
        "import type { Service } from \"./messages.js\";",
        "",
        "/** The protocol version this file was made from. */",
    ] {
        lines.push(l.into());
    }
    lines.push(format!(
        "export const PROTOCOL_VERSION = \"{}\";",
        model.protocol.py_str()
    ));
    for l in [
        "",
        "/** One message of the protocol: who sends it, whether it is answered, and what it carries. */",
        "export interface MethodInfo {",
        "  readonly method: string;",
        "  readonly sender: \"app\" | \"tool\";",
        "  readonly kind: \"request\" | \"notice\";",
        "  /** The entry the tool's manifest must list in `uses` before the app will do it. */",
        "  readonly uses: Service | null;",
        "  /** The definition its params are, in messages.schema.json. */",
        "  readonly params: string | null;",
        "  readonly result: string | null;",
        "}",
        "",
        "/** Every message of the protocol, as methods.json lists them. */",
        "export const METHODS: readonly MethodInfo[] = [",
    ] {
        lines.push(l.into());
    }
    for m in &model.methods {
        let uses = if m.uses.truthy() {
            format!("\"{}\"", m.uses.py_str())
        } else {
            "null".into()
        };
        let params = match truthy(&m.params) {
            Some(p) => format!("\"{}\"", p),
            None => "null".into(),
        };
        let result = match truthy(&m.result) {
            Some(r) => format!("\"{}\"", r),
            None => "null".into(),
        };
        lines.push(format!(
            "  {{ method: \"{}\", sender: \"{}\", kind: \"{}\", uses: {}, params: {}, result: {} }},",
            m.method.py_str(),
            m.sender.py_str(),
            m.kind.py_str(),
            uses,
            params,
            result
        ));
    }
    for l in [
        "];",
        "",
        "/** Sends a request and returns what its answer carries, or throws. */",
        "export type Requester = (method: string, params: object | undefined) => unknown;",
        "/** Sends a notice. */",
        "export type Noticer = (method: string, params: object) => void;",
        "",
    ] {
        lines.push(l.into());
    }
    let grouped = groups(&both)?;
    lines.push("/** What a tool may ask of the app: one call per message, by its name. */".into());
    lines.push("export interface AppCalls {".into());
    for (group, members) in &grouped {
        match group {
            None => {
                for m in members {
                    let (params, returns) = signature(model, m)?;
                    lines.extend(describe(model, m, "  ")?);
                    lines.push(format!("  {}({}): {};", m.path()?[0], params, returns));
                }
            }
            Some(g) => {
                lines.push(format!("  readonly {}: {{", g));
                for m in members {
                    let (params, returns) = signature(model, m)?;
                    lines.extend(describe(model, m, "    ")?);
                    lines.push(format!("    {}({}): {};", m.path()?[1], params, returns));
                }
                lines.push("  };".into());
            }
        }
    }
    lines.push("}".into());
    lines.push(String::new());
    lines.push("/** The calls, made of the two functions that send. */".into());
    lines.push("export function appCalls(request: Requester, notice: Noticer): AppCalls {".into());
    lines.push("  return {".into());
    for (group, members) in &grouped {
        match group {
            None => {
                for m in members {
                    lines.push(body(model, m, &m.path()?[0], "    ")?);
                }
            }
            Some(g) => {
                lines.push(format!("    {}: {{", g));
                for m in members {
                    lines.push(body(model, m, &m.path()?[1], "      ")?);
                }
                lines.push("    },".into());
            }
        }
    }
    lines.push("  };".into());
    lines.push("}".into());
    Ok(format!("{}\n", lines.join("\n")))
}

pub fn emit(model: &Model) -> PyResult<Vec<(String, String)>> {
    let messages = messages_file(model)?;
    let manifest = manifest_file(model)?;
    let methods = methods_file(model)?;
    Ok(vec![
        (format!("{}/messages.ts", FOLDER), messages),
        (format!("{}/manifest.ts", FOLDER), manifest),
        (format!("{}/methods.ts", FOLDER), methods),
    ])
}

